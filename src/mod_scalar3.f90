L2NORM_MK_HALFK = 0.D0
L2NORM_MK_HALFK(:,1) = L2NORM_MK_ALL(:,1) ! K = 0
DO KK=2,NXCHOP
  KC = NXCHOPDIM+2-KK
  L2NORM_MK_HALFK(:,KK) = L2NORM_MK_ALL(:,KC)+L2NORM_MK_ALL(:,KK)
ENDDO

RETURN
END FUNCTION L2NORM_MK_HALFK
