FUNCTION L2NORM_MK_HALFK(A)
! ======================================================================
! [USAGE]:
! COMPUTES THE L2 NORM SQUARED OF A SCALAR FIELD A, WITH THE RESULT
! DISTRIBUTED OVER NON-NEGATIVE AZIMUTHAL (M) AND AXIAL (K) WAVENUMBERS.
! THE L2 NORM SQUARED IS DEFINED AS INT |A|^2 R DR D(PHI) DZ OVER THE
! ENTIRE DOMAIN.
! [PARAMETERS]:
! A >> A SCALAR-TYPE VARIABLE IN PFF_SPACE.
! [RETURNS]:
! A 2D REAL ARRAY OF SIZE (NTCHOP, NXCHOP) CONTAINING THE L2 NORM
! SQUARED CONTRIBUTION FROM EACH NON-NEGATIVE (M, K) MODE.
! [NOTES]:
! THIS FUNCTION FIRST CALLS L2NORM_MK_ALLK TO COMPUTE THE NORM FOR ALL
! K MODES, AND THEN FOLDS THE CONTRIBUTIONS FROM NEGATIVE K MODES
! INTO THE CORRESPONDING POSITIVE K MODES. FOR A REAL PHYSICAL FIELD,
! THE CONTRIBUTION FROM K AND -K ARE EQUAL.
! ======================================================================
IMPLICIT NONE
TYPE(SCALAR), INTENT(IN):: A
REAL(P8):: L2NORM_MK_HALFK(NTCHOP,NXCHOP), L2NORM_MK_ALL(NTCHOP,NXCHOPDIM)
