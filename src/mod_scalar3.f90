!=======================================================================
FUNCTION INTEG(F)
!=======================================================================
! [USAGE]:
! INTEGRATION OF A FUNCTION OVER A DOMAIN 
!     0  <  R   < INFTY
!     0  <  PHI < 2*PI
!     0  <  Z   < ZLEN
! CALL IN F/F SPACE
! INTEGRATED FUNCTION G IS IN THE FORM G = F*(1-MU)^2
! [INPUTS]:
! F >> A FUNTION INPUT FOR INTEGRATION (ACTUAL INTEGRATION IS DONE ON G)
! [OUTPUTS]:
! INTEG >> INTEGRATION EQUAL TO INT_[FULL_RANGE](G(R,PHI,Z) DR DPHI DZ)
! [UPDATES]:
! RE-CODED BY SANGJOON LEE @ NOV 18 2020
! MPI-ED BY JINGE WANG @ SEP 29 2021
!=======================================================================
IMPLICIT NONE
TYPE(SCALAR),INTENT(IN):: F
REAL(P8)::INTEG

IF(F%SPACE.NE.FFF_SPACE) THEN
  IF (MPI_RANK.EQ.0) WRITE(*,*) 'INTEG: NOT IN FFF_SPACE'
  STOP
ENDIF      

IF ((F%INTH.EQ.0).AND.(F%INX.EQ.0)) THEN
  ! INTEGRATION OF R*LOGTERM GOES TO INFINITY
  IF(F%LN.NE.0.0) THEN
    WRITE(*,*) 'INTEG: LOGTERM NOT ZERO'
    WRITE(*,*) 'LOGTERM=',F%LN
  ENDIF
  ! ADDITIONAL FACTOR OF 2 COMES FROM (N^0_0)^2 = 2
  INTEG = 4.0_P8*PI*ZLEN*ELL2*REAL(F%E(1,1,1))*TFM%NORM(1,1)
ELSE
  INTEG = 0
ENDIF
CALL MPI_ALLREDUCE(MPI_IN_PLACE, INTEG, 1, MPI_DOUBLE_PRECISION, &
      MPI_SUM, MPI_COMM_IVP, IERR)

RETURN
END FUNCTION INTEG
!=======================================================================
FUNCTION INTEG_MK(F)
!=======================================================================
! [USAGE]:
! INTEGRATION OF A FUNCTION OVER R FOR EACH M AND K
! CALL IN PFF_SPACE
! INTEGRATED FUNCTION G IS IN THE FORM G = F*(1-MU)^2
! [INPUTS]:
! F >> A FUNTION INPUT FOR INTEGRATION (ACTUAL INTEGRATION IS DONE ON G)
! [OUTPUTS]:
! INTEG_MK >> INTEGRATION EQUAL TO INT(G(R,PHI,Z) RDR)
!========================================================================
IMPLICIT NONE
TYPE(SCALAR),INTENT(IN):: F
COMPLEX(P8),DIMENSION(NTCHOP,NXCHOPDIM):: INTEG_MK
INTEGER:: MM,KK,COUNT
REAL(P8):: DOT_REAL, DOT_IMAG

IF(F%SPACE.NE.PFF_SPACE) THEN
  IF (MPI_RANK.EQ.0) THEN
    WRITE(*,*) 'INTEG_MK: NOT IN PFF_SPACE'
  ENDIF
  STOP
ENDIF

INTEG_MK = CMPLX(0.D0,0.D0)
!$OMP PARALLEL DO COLLAPSE(2) PRIVATE(DOT_REAL,DOT_IMAG) SCHEDULE(STATIC)
DO KK = 1,SIZE(F%E,3) !NXCHOP
  DO MM = 1,SIZE(F%E,2) !NTCHOP
    DOT_REAL = DOT_PRODUCT(REAL(F%E(:NR,MM,KK)),TFM%W)
    DOT_IMAG = DOT_PRODUCT(AIMAG(F%E(:NR,MM,KK)),TFM%W)
    INTEG_MK(MM+F%INTH,KK+F%INX) = &
      ELL2 * (DOT_REAL + IU*DOT_IMAG)
  ENDDO
ENDDO
!$OMP END PARALLEL DO

COUNT = NTCHOP*NXCHOPDIM
CALL MPI_ALLREDUCE(MPI_IN_PLACE, INTEG_MK, COUNT, &
                  MPI_DOUBLE_COMPLEX, MPI_SUM, MPI_COMM_IVP, IERR)

RETURN
END FUNCTION INTEG_MK
!=======================================================================
FUNCTION PRODCT(A,B)
!=======================================================================
! [USAGE]:
! CALCULATE THE PRODUCT AND INTEGRATE OVER THE DOMAIN
! CALL IN R-PHYSICAL / PHI,Z-FOURIER SPACE
! WHAT IS ACTUALLY INTEGRATED IS G = A*B*(1-MU)^2
! [INPUTS]:
! A >> FIRST SCALAR-TYPE VARIABLE FOR INTEGRATION
! B >> SECOND SCALAR-TYPE VARIABLE FOR INTEGRATION
! [OUTPUTS]:
! PRODCT >> INTEGRATION EQUAL TO INT_[FULL_RANGE](G(R,PHI,Z) DR DPHI DZ)
!=======================================================================
IMPLICIT NONE
TYPE(SCALAR),INTENT(IN):: A,B
REAL(P8):: PRODCT

COMPLEX(P8):: PROD(NR)
INTEGER:: MM,KK

IF(A%SPACE.NE.PFF_SPACE .OR. B%SPACE.NE.PFF_SPACE) THEN
  IF (MPI_RANK.EQ.0) THEN
    WRITE(*,*) 'PRODCT:NOT IN PFF_SPACE'
    WRITE(*,*) 'A%SPACE,B%SPACE=',A%SPACE,B%SPACE
  ENDIF
  STOP
ENDIF

! IF EITHER OR BOTH A AND B CONTAINS LOGTERM, THE INTEGRATION WILL ALWAYS
! DIVERGE TO INFINITY. SO, WE CHECK IF THE LOGTERM IS ZERO.
! NOTE: FOR G(R), INT[LOGTERM*G(R)*R]DR DIVERGES WHENEVER G(R) DECAYS SLOWER
! THAN 1/(R*LN(R)) AS R -> INFINITY. SINCE THE PHYSICAL SPACE FUNCTION 
! DECAYS ALGEBRAICALLY (I.E. R^-|M|), THE INTEGRATION WILL DIVERGE WHENEVER
! THE FUNCTION CONTAINS |M|<=2 MODES, WHICH IS ALMOST ALWAYS THE CASE.
IF(A%LN.NE.0.0 .OR. B%LN.NE.0.0) THEN
  WRITE(*,*) 'PRODCT:LOGTERM NOT ZERO'
ENDIF

! PROD=0
! DO KK = 1,NX
!   IF(KK.GT.NXCHOP .AND. KK.LT.NXCHOPH) CYCLE
!   PROD = PROD+A%E(:NR,1,KK)*CONJG(B%E(:NR,1,KK))
! ENDDO

! DO KK = 1,NX
!   IF(KK.GT.NXCHOP .AND. KK.LT.NXCHOPH) CYCLE
!   DO MM = 2,NTCHOP
!     PROD = PROD + 2*(REAL(A%E(:NR,MM,KK))*REAL(B%E(:NR,MM,KK)) &
!                 + AIMAG(A%E(:NR,MM,KK))*AIMAG(B%E(:NR,MM,KK)))
!   ENDDO
! ENDDO

PROD=0
!$OMP PARALLEL DO COLLAPSE(2) PRIVATE(MM,KK) SCHEDULE(STATIC) REDUCTION(+:PROD)
DO KK = 1,SIZE(A%E,3)
  DO MM = 1,SIZE(A%E,2) !NTCHOP
    IF (MM+A%INTH.EQ.1) THEN ! M(1) = 0
    PROD = PROD+A%E(:NR,1,KK)*CONJG(B%E(:NR,1,KK))
    ELSE
    PROD = PROD + 2.0_P8*(REAL(A%E(:NR,MM,KK))*REAL(B%E(:NR,MM,KK)) &
                + AIMAG(A%E(:NR,MM,KK))*AIMAG(B%E(:NR,MM,KK)))
    ENDIF
  ENDDO
ENDDO
!$OMP END PARALLEL DO
PRODCT = SUM(PROD*TFM%W)

CALL MPI_ALLREDUCE(MPI_IN_PLACE, PRODCT, 1, MPI_DOUBLE_PRECISION, MPI_SUM, MPI_COMM_IVP, IERR)
PRODCT = 2*PI*ZLEN*ELL2*PRODCT

RETURN
END FUNCTION PRODCT
