FUNCTION L2NORM_MK_ALLK(A)
! ======================================================================
! [USAGE]:
! COMPUTES THE L2 NORM SQUARED OF A SCALAR FIELD A, WITH THE RESULT
! DISTRIBUTED OVER NON-NEGATIVE AZIMUTHAL (M) AND ALL AXIAL (K) WAVENUMBERS.
! THE L2 NORM SQUARED IS DEFINED AS INT |A|^2 R DR D(PHI) DZ OVER THE
! ENTIRE DOMAIN.
! [PARAMETERS]:
! A >> A SCALAR-TYPE VARIABLE IN PFF_SPACE.
! [RETURNS]:
! A 2D REAL ARRAY OF SIZE (NTCHOP, NXCHOPDIM) CONTAINING THE L2 NORM
! SQUARED CONTRIBUTION FROM EACH (M >= 0, K) MODE.
! ======================================================================
IMPLICIT NONE
TYPE(SCALAR), INTENT(IN):: A
REAL(P8):: WK1(NR)
REAL(P8):: L2NORM_MK_ALLK(NTCHOP,NXCHOPDIM) !NX)
INTEGER:: MM,KK,COUNT

IF(A%SPACE.NE.PFF_SPACE) THEN
  IF (MPI_RANK.EQ.0) THEN
      PRINT *,'ERROR: L2NORM_MK() -- NOT IN PFF_SPACE.'
      PRINT *,'A%SPACE = ',A%SPACE
  ENDIF
  STOP
ENDIF

IF ((A%INTH.EQ.0).AND.(A%INX.EQ.0)) THEN
  IF(ABS(A%LN)>1.0E-8) THEN
      PRINT *,'WARNING: L2NORM_MK() -- LOGTERM NOT ZERO.'
      PRINT *,'A%LN = ',A%LN
  ENDIF
ENDIF

L2NORM_MK_ALLK = 0.D0
!$OMP PARALLEL DO COLLAPSE(2) PRIVATE(WK1) SCHEDULE(STATIC)
DO KK=1,SIZE(A%E,3) !NXCHOP
  DO MM=1,SIZE(A%E,2) !NTCHOP
      WK1 = ABS(A%E(:NR,MM,KK))**2/(1-TFM%X(:NR))**2
      ! {MM,KK}&{-MM,-KK} combined
      ! note: We save non-negative M's, but all K's.
      !       So, for {0,KK}, we should not add {0,-KK} during the calculation,
      !       as {0,-KK} is actually saved. Hence, all MM = 0 modes' product is
      !       off by a factor of 2.
      L2NORM_MK_ALLK(MM+A%INTH,KK+A%INX) = &
              4.0_P8*PI*ZLEN0*ELL2*DOT_PRODUCT(WK1,TFM%W)
  END DO
END DO
!$OMP END PARALLEL DO

COUNT = NTCHOP*NXCHOPDIM
CALL MPI_ALLREDUCE(MPI_IN_PLACE, L2NORM_MK_ALLK, COUNT, &
                  MPI_DOUBLE_PRECISION, MPI_SUM, MPI_COMM_IVP, IERR)
L2NORM_MK_ALLK(1,:) = 0.5_P8*L2NORM_MK_ALLK(1,:)

RETURN
END FUNCTION L2NORM_MK_ALLK
