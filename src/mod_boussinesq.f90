SUBROUTINE CALC_BOUSSI_NONLIN(B, RUR, RUP, UZ, BN, ROR, ROP, OZ)
!=======================================================================
! [USAGE]:
! CALCULATE THE NONLINEAR TERMS IN BOUSSINESQ APPROXIMATION:
! THE ADVECTION TERM (U X OMEGA) AND THE BUOYANCY FORCING -(U.GRAD)B.
!
! [PARAMETERS]:
! B  >> (IN) Density perturbation, must be in FFF space.
! BN >> (OUT) The nonlinear buoyancy tendency -(U.GRAD)B.
! RUR,RUP,UZ >> (INOUT) Velocity components. Updated with freestream.
! ROR,ROP,OZ >> (IN) Vorticity components from PC2VOR.
!            >> (OUT) Overwritten with U x OMEGA
! [NOTES]:
! B IN FFF SPACE
! BN IN PFF SPACE
! RUR, RUP, UZ ARE DEALLOCATED
! ROR, ROP, OZ IN FFF SPACE
!=======================================================================
IMPLICIT NONE
TYPE(SCALAR),INTENT(IN):: B
TYPE(SCALAR),INTENT(INOUT):: RUR,RUP,UZ
TYPE(SCALAR),INTENT(INOUT):: ROR,ROP,OZ,BN

TYPE(SCALAR):: RBR,RBP,BZ,PSI,CHI,W
INTEGER:: NI,NJ,NK

IF (B%SPACE .NE. FFF_SPACE) THEN
  CALL MPRINT('CALC_BOUSSI_NONLIN: B SHOULD BE IN FFF SPACE!')
  CALL MPI_ABORT(MPI_COMM_IVP, ERR_FLAGS%LEGOPERATOR, IERR)
ENDIF

CALL ALLOCATE(RBR)
CALL ALLOCATE(RBP)
CALL ALLOCATE(BZ)

CALL CHOPSET(1)
CALL GRAD(B,RBR,RBP,BZ)
CALL CHOPSET(-1)

! CONVERT ALL TO PPP SPACE
CALL TOFP(RUR); CALL TOFP(RUP); CALL TOFP(UZ)
CALL TOFP(ROR); CALL TOFP(ROP); CALL TOFP(OZ)
CALL TOFP(RBR); CALL TOFP(RBP); CALL TOFP(BZ)

NI=SIZE(RUR%E,1); NJ=SIZE(RUR%E,2); NK=SIZE(RUR%E,3)

! CALCULATING (U'+U0) X OMEGA'
! NOTE: RUR, RUP, UZ UPDATED WITH FREESTREAM VELOCITY IN PPP SPACE
!       ROR, ROP, OZ BECAME U X OMEGA IN PPP SPACE
CALL VPRODSUB(RUR%E,RUP%E,UZ%E,ROR%E,ROP%E,OZ%E,NI,NJ,NK,RUR%INR)

! CALCULATING -((U'+U0).GRAD)B
! NOTE: RUR, RUP, UZ ALREADY CONTAINS FREESTREAM DUE TO VPRODSUB
IF (ASSOCIATED(BN%E)) CALL DEALLOCATE(BN)
CALL ALLOCATE(BN,PPP_SPACE); BN%LN=0.d0
BN%E = -VDOTPSUB(RUR%E,RUP%E,UZ%E,RBR%E,RBP%E,BZ%E,NI,NJ,NK,RUR%INR,.FALSE.)

CALL DEALLOCATE(RBR); CALL DEALLOCATE(RBP); CALL DEALLOCATE(BZ)
CALL DEALLOCATE(RUR); CALL DEALLOCATE(RUP); CALL DEALLOCATE(UZ)

! MAKE ROR, ROP, OZ DIVERGENCE-FREE AGAIN
CALL ALLOCATE(PSI); CALL ALLOCATE(W)
CALL PROJECT(ROR,ROP,OZ,PSI,W,0.D0)
CALL DEALLOCATE(ROR); CALL DEALLOCATE(ROP); CALL DEALLOCATE(OZ)
CALL ALLOCATE(CHI)
CALL IDEL2(W,CHI)
CALL DEALLOCATE(W)

CALL CHOPSET(3)
CALL ALLOCATE(ROR); CALL ALLOCATE(ROP); CALL ALLOCATE(OZ)
CALL PC2VEL(PSI,CHI,ROR,ROP,OZ)
CALL DEALLOCATE(PSI); CALL DEALLOCATE(CHI)
CALL CHOPSET(-3)

! CONVERT BACK TO FFF SPACE
! CALL TOFF(BN)
CALL PLNFFT(BN,-1) ! TO PFF SPACE

RETURN
END SUBROUTINE CALC_BOUSSI_NONLIN
