SUBROUTINE BOUSSINESQ_LINEAR(PSI,CHI,B,PSIN,CHIN,BN)
! ======================================================================
! [USAGE]: 
! CALCULATE THE LINEAR TERM IN BOUSSINESQ APPROX:
! P[2*OMEGA Z_HAT X U - B Z_HAT] AND N_BAR^2 * UZ
! [PARAMETERS]:
! PSI    >> TOROIDAL TERM IN A SCALAR-TYPE VARIABLE
! CHI    >> POLOIDAL TERM IN A SCALAR-TYPE VARIABLE
! B      >> DENSITY TERM IN A SCALAR-TYPE VARIABLE
! PSIN   >> ON EXIT, TOROIDAL TERM FROM LINEAR TERMS
! CHIN   >> ON EXIT, POLOIDAL TERM FROM LINEAR TERMS
! BN     >> ON EXIT, DENSITY TERM FROM LINEAR TERMS (N_BAR^2 * UZ)
! [DEPENDENCIES]:
! 1. PC2VEL(~) @ MOD_LEGOPS
! 2. PROJECT(~), IDEL2(~) @ MOD_LEGOPS
! [UPDATES]:
! UPDATED BY JINGE WANG @ JULY 25 2025
!=======================================================================
IMPLICIT NONE
TYPE(SCALAR),INTENT(IN):: PSI,CHI,B
TYPE(SCALAR),INTENT(INOUT):: PSIN,CHIN,BN

TYPE(SCALAR):: RUR, RUP, UZ
TYPE(SCALAR):: VR, VP   ! Temporary variables for Coriolis components
TYPE(SCALAR):: W

CALL ALLOCATE(RUR)
CALL ALLOCATE(RUP)
CALL ALLOCATE(UZ)
CALL ALLOCATE(VR); VR%LN=0.D0
CALL ALLOCATE(VP); VP%LN=0.D0

! Get velocity components
CALL PC2VEL(PSI,CHI,RUR,RUP,UZ)

! Store linear Coriolis terms in temporary variables
VR%E = 2*BSNSQ%OMEGA*RUP%E       ! 2*OMEGA*RUP (Coriolis force, radial component)
VP%E = -2*BSNSQ%OMEGA*RUR%E      ! -2*OMEGA*RUR (Coriolis force, azimuthal component)

! Calculate BN = N_BAR^2 * UZ (buoyancy restoring force)
IF (ASSOCIATED(BN%E)) CALL DEALLOCATE(BN)
CALL ALLOCATE(BN); BN%LN=0.D0
BN%E = BSNSQ%BV0**2*UZ%E

! Add buoyancy force to UZ
UZ%E = -B%E

! Convert to PFF space
CALL RTRAN(VR,1); CALL RTRAN(VP,1); CALL RTRAN(UZ,1)

! Project to get scalar potentials
CALL ALLOCATE(W); W%LN=0.D0
CALL PROJECT(VR, VP, UZ, PSIN, W)  ! W now contains DEL2(CHI)
CALL IDEL2(W,CHIN)

! Clean up
CALL DEALLOCATE(RUR)
CALL DEALLOCATE(RUP)
CALL DEALLOCATE(UZ)
CALL DEALLOCATE(VR)
CALL DEALLOCATE(VP)
CALL DEALLOCATE(W)

END SUBROUTINE BOUSSINESQ_LINEAR

