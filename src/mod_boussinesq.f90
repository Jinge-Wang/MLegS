SUBROUTINE CALC_BOUSS_DIAG(J,S,S_INV,ECHO)
!=======================================================================
! [USAGE]:
! CALCULATE THE DIAGONAL ELEMENTS OF THE BOUSSINESQ OPERATOR
! [PARAMETERS]:
! J >> EIGENVALUE OF THE LINEAR BOUSSINESQ OPERATOR
! S >> RIGHT EIGENMATRIX
! S_INV >> LEFT EIGENMATRIX
!=======================================================================
  IMPLICIT NONE
  COMPLEX(P8), DIMENSION(4,4), INTENT(INOUT):: J, S, S_INV
  REAL(P8) :: N_FREQ, OMEGA
  LOGICAL, OPTIONAL :: ECHO

  N_FREQ = BSNSQ%BV0
  OMEGA  = BSNSQ%OMEGA

  J = CMPLX(0.0D0, 0.0D0, P8)
  J(1,1) = -IU * N_FREQ
  J(2,2) =  IU * N_FREQ
  J(3,3) = -2.0D0 * IU * OMEGA
  J(4,4) =  2.0D0 * IU * OMEGA

  S = CMPLX(0.0D0, 0.0D0, P8)
  S(1,3) = IU
  S(1,4) = -IU
  S(2,3) = 1.0D0
  S(2,4) = 1.0D0
  S(3,1) = -IU / N_FREQ
  S(3,2) =  IU / N_FREQ
  S(4,1) = 1.0D0
  S(4,2) = 1.0D0

  S_INV = CMPLX(0.0D0, 0.0D0, P8)
  S_INV(1,3) =  IU * N_FREQ / 2.0D0
  S_INV(1,4) = 0.5D0
  S_INV(2,3) = -IU * N_FREQ / 2.0D0
  S_INV(2,4) = 0.5D0
  S_INV(3,1) = -IU / 2.0D0
  S_INV(3,2) = 0.5D0
  S_INV(4,1) =  IU / 2.0D0
  S_INV(4,2) = 0.5D0

  IF (PRESENT(ECHO)) THEN
    IF ((MPI_RANK.EQ.0).AND.(ECHO)) THEN
      WRITE(*,*) 'MOD_BOUSSINESQ: L = SJS^-1'
      WRITE(*,*) 'J:'
      CALL MCAT(J)
      WRITE(*,*) 'S:'
      CALL MCAT(S)
      WRITE(*,*) 'S^-1:'
      CALL MCAT(S_INV)
      WRITE(*,*) 'S*S^-1:'
      CALL MCAT(MATMUL(S, S_INV))
    ENDIF
  ENDIF

  RETURN
END SUBROUTINE CALC_BOUSS_DIAG
