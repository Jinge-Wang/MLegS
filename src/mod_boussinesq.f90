FUNCTION INTEG_K_FFF(F)
!=======================================================================
! [USAGE]:
! INTEGRATION OF A FUNCTION OVER R FOR EACH K
! CALL IN FFF_SPACE
! INTEGRATED FUNCTION G IS IN THE FORM G = F*(1-MU)^2
! [INPUTS]:
! F >> A FUNTION INPUT FOR INTEGRATION (ACTUAL INTEGRATION IS DONE ON G)
! [OUTPUTS]:
! INTEG_K_FFF >> INTEGRATION EQUAL TO INT(G(R,PHI,Z) RDR)
!========================================================================
IMPLICIT NONE
TYPE(SCALAR),INTENT(IN):: F
COMPLEX(P8),DIMENSION(NXCHOPDIM):: INTEG_K_FFF
INTEGER:: KK,COUNT

IF(F%SPACE.NE.FFF_SPACE) THEN
  IF (MPI_RANK.EQ.0) THEN
    WRITE(*,*) 'INTEG_K_FFF: NOT IN FFF_SPACE'
  ENDIF
  STOP
ENDIF

INTEG_K_FFF = CMPLX(0.D0,0.D0)
IF (F%INTH .EQ. 0) THEN
  DO KK = 1,SIZE(F%E,3) !NXCHOP
    INTEG_K_FFF(KK+F%INX) = &
      2.0_P8 * ELL2 * F%E(1,1,KK) * TFM%NORM(1,1)
  ENDDO
ENDIF

COUNT = NXCHOPDIM
CALL MPI_ALLREDUCE(MPI_IN_PLACE, INTEG_K_FFF, COUNT, &
                  MPI_DOUBLE_COMPLEX, MPI_SUM, MPI_COMM_IVP, IERR)

RETURN
END FUNCTION INTEG_K_FFF
!=======================================================================

FUNCTION INTEG_K_PFF(F)
!=======================================================================
! [USAGE]:
! INTEGRATION OF A FUNCTION OVER R FOR EACH K
!========================================================================
IMPLICIT NONE
TYPE(SCALAR),INTENT(IN):: F
TYPE(SCALAR):: F_COPY
COMPLEX(P8),DIMENSION(NXCHOPDIM):: INTEG_K_PFF
INTEGER:: KK,COUNT
REAL(P8):: DOT_REAL, DOT_IMAG

IF(F%SPACE.NE.FFF_SPACE) THEN
  IF (MPI_RANK.EQ.0) THEN
    WRITE(*,*) 'INTEG_K_PFF: NOT IN FFF_SPACE'
  ENDIF
  STOP
ENDIF

CALL ALLOCATE(F_COPY)
F_COPY = F
CALL RTRAN(F_COPY,1) ! Convert to PFF space

INTEG_K_PFF = CMPLX(0.D0,0.D0)
IF (F_COPY%INTH .EQ. 0) THEN
  DO KK = 1,SIZE(F_COPY%E,3) !NXCHOP
    DOT_REAL = DOT_PRODUCT(REAL(F_COPY%E(:NR,1,KK))/(1.D0-TFM%X)**2,TFM%W)
    DOT_IMAG = DOT_PRODUCT(AIMAG(F_COPY%E(:NR,1,KK))/(1.D0-TFM%X)**2,TFM%W)
    INTEG_K_PFF(KK+F_COPY%INX) = ELL2 * (DOT_REAL + IU * DOT_IMAG)
  ENDDO
ENDIF

CALL DEALLOCATE(F_COPY)
COUNT = NXCHOPDIM
CALL MPI_ALLREDUCE(MPI_IN_PLACE, INTEG_K_PFF, COUNT, &
                  MPI_DOUBLE_COMPLEX, MPI_SUM, MPI_COMM_IVP, IERR)

RETURN
END FUNCTION INTEG_K_PFF
