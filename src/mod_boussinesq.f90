SUBROUTINE CALC_ENERGY(PSI,CHI,B,TIME,SAVEDIR)
!=======================================================================
! [USAGE]:
! CALCULATE KINETIC AND POTENTIAL ENERGY IN THE SYSTEM
! D(KE)/DT = DKE
! D(PE)/DT = -DKE
! [PARAMETERS]:
! PSI >> TOROIDAL TERM IN A SCALAR-TYPE VARIABLE (FFF SPACE)
! CHI >> POLOIDAL TERM IN A SCALAR-TYPE VARIABLE (FFF SPACE)
! B   >> DENSITY TERM IN A SCALAR-TYPE VARIABLE (FFF SPACE)
! TIME >> CURRENT TIME IN THE SIMULATION
! SAVEDIR >> DIRECTORY TO SAVE THE ENERGY DATA
! [DEPENDENCIES]:
! 1. DELSQH(~) @ MOD_LEGOPS <- REQUIRES CHOPSET
! 2. DEL2(~) @ MOD_LEGOPS
! 3. RTRAN(~) @ MOD_FFT
! 4. PRODCT_MK(~) @ MOD_SCALAR3
! 5. INTEG_MK(~) @ MOD_SCALAR3
!==========================================================================
IMPLICIT NONE
TYPE(SCALAR),INTENT(IN):: PSI,CHI,B
TYPE(SCALAR):: W1,W2,W3
REAL(P8):: KE(NTCHOP,NXCHOPDIM),DKE(NTCHOP,NXCHOPDIM),TIME
COMPLEX(P8):: PE_MK(NTCHOP,NXCHOPDIM),PE_K(NXCHOPDIM)
INTEGER:: KK,FILESTATUS
CHARACTER(LEN=72):: SAVEDIR

IF (B%LN .NE. 0.D0) THEN
! LN TERM IN B IS NOT PHYSICAL, AS B CAN'T BE IFINITE AT FAR FIELD
  CALL MPRINT('B has non-zero LN, this is not expected in Boussinesq')
  CALL MPI_ABORT(MPI_COMM_IVP, ERR_FLAGS%SCALAR3_LOGTERM, IERR)
ENDIF

CALL ALLOCATE(W1)
CALL ALLOCATE(W2)
CALL ALLOCATE(W3)
CALL CHOPSET(3)

! KINETIC ENERGY:
! ENERGY IN TOROIDAL COMPONENT
W1 = PSI
IF ((PSI%INX.EQ.0).AND.(PSI%INTH.EQ.0)) W1%LN = 2.0_P8*PSI%LN
CALL DELSQH(W1,W2)
W1%LN = 0.0_P8
W2%LN = 0.0_P8
CALL RTRAN(W1,1)
CALL RTRAN(W2,1)
KE = -PRODCT_MK(W1,W2)

! ENERGY IN POLOIDAL COMPONENT
CALL DEL2(CHI,W1)
CALL DELSQH(CHI,W2)
W1%LN = 0.0_P8
W2%LN = 0.0_P8
CALL RTRAN(W1,1)
CALL RTRAN(W2,1)

! TOTAL KINETIC ENERGY
KE = KE + PRODCT_MK(W1,W2)

! ENERGY EXCHANGE
W3 = B
W3%LN = 0.0_P8
CALL RTRAN(W3,1) ! Convert to PFF space
DKE = PRODCT_MK(W3,W2)  ! W3 = B, W2 = (1-X)^-2*DEL^2_H(CHI) = -(1-X)^-2*UZ

CALL CHOPSET(-3)
CALL DEALLOCATE(W1)
CALL DEALLOCATE(W2)
CALL DEALLOCATE(W3)

! POTENTIAL ENERGY:
CALL ALLOCATE(W3)
CALL DIVXM2(B,W3) ! W3 = (1-X)^-2 * B
PE_MK = INTEG_MK(W3)
PE_K = PE_MK(1,:)
PE_K(1) = PE_K(1) * ZLEN0**2 * PI
PE_K(2:) = -(PE_K(2:)/AK(1,2:)) * ZLEN0 * 2 * PI * IU 
CALL DEALLOCATE(W3)

! PRINTOUT
IF (MPI_RANK.EQ.0) THEN
  OPEN(UNIT=667,FILE=TRIM(ADJUSTL(SAVEDIR))//'especData_K.dat',STATUS='UNKNOWN',&
  & IOSTAT=FILESTATUS, POSITION='APPEND')
  !  WRITE(667, 788) TIME , (ESPEC(1,KK),KK=1,NXCHOP)        ! Only record k = 0 mode
  WRITE(667, '(*(E24.16,1X))') TIME, (SUM(KE(:,KK)),KK=1,NXCHOPDIM)            
  CLOSE(667)

  OPEN(UNIT=668,FILE=TRIM(ADJUSTL(SAVEDIR))//'especData_P.dat',STATUS='UNKNOWN',&
  & IOSTAT=FILESTATUS, POSITION='APPEND')
  !  WRITE(668, 789) TIME , (ESPEC(1,KK),KK=1,NXCHOP)        ! Only record k = 0 mode
  WRITE(668, '(*(E24.16,1X,E24.16,1X))') TIME, (REAL(PE_K(KK)), AIMAG(PE_K(KK)), KK=1,NXCHOPDIM)
  CLOSE(668)

  OPEN(UNIT=669,FILE=TRIM(ADJUSTL(SAVEDIR))//'especData_DKE.dat',STATUS='UNKNOWN',&
  & IOSTAT=FILESTATUS, POSITION='APPEND')
  WRITE(669, '(*(E24.16,1X))') TIME, (SUM(DKE(:,KK)),KK=1,NXCHOPDIM)            
  CLOSE(669)
ENDIF

END SUBROUTINE CALC_ENERGY


