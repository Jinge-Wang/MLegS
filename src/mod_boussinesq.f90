SUBROUTINE CALC_BOUSSI_FORCE(PSI,CHI,B,PSIN,CHIN,BN)
!=======================================================================
! [USAGE]: 
! CALCULATE THE NONLINEAR AND LINEAR TERMS
! INCLUDING ROTATION, STRATIFICATION, AND NONLINEAR ADVECTION
! [PARAMETERS]:
! PSI  >> TOROIDAL TERM IN A SCALAR-TYPE VARIABLE
! CHI  >> POLOIDAL TERM IN A SCALAR-TYPE VARIABLE
! B    >> DENSITY TERM IN A SCALAR-TYPE VARIABLE
! PSIN >> ON EXIT, TOROIDAL TERM FOR TIME ADVANCEMENT
! CHIN >> ON EXIT, POLOIDAL TERM FOR TIME ADVANCEMENT
! BN   >> ON EXIT, DENSITY TERM FOR TIME ADVANCEMENT
! [DEPENDENCIES]:
! 1. GRAD(~), PC2VEL(~), PC2VOR(~) @ MOD_LEGOPS
! 2. VPRODSUB(~), VDOTPSUB(~) @ MOD_LEGOPS
! 3. PROJECT(~), IDEL2(~) @ MOD_LEGOPS
! 4. TOFP(~), TOFF(~) @ MOD_FFT
! [NOTES]:
! 1. UPON COMPLETION, PSIN AND CHIN WILL HAVE LOG TERMS
!=======================================================================
IMPLICIT NONE
TYPE(SCALAR),INTENT(IN):: PSI,CHI,B
TYPE(SCALAR),INTENT(INOUT):: PSIN,CHIN,BN

TYPE(SCALAR):: RUR,RUP,UZ
TYPE(SCALAR):: ROR,ROP,OZ
TYPE(SCALAR):: RBR,RBP,BZ
TYPE(SCALAR):: W
INTEGER:: NI,NJ,NK

CALL ALLOCATE( RUR ); CALL ALLOCATE( RUP ); CALL ALLOCATE(  UZ )
CALL ALLOCATE( ROR ); CALL ALLOCATE( ROP ); CALL ALLOCATE(  OZ )
CALL ALLOCATE( RBR ); CALL ALLOCATE( RBP ); CALL ALLOCATE(  BZ )

! DEALIASING
CALL CHOPSET(3)

! OBTAINING GRAD(B)
CALL GRAD(B,RBR,RBP,BZ)                                            ! NOTE: INPUT AND OUTPUTS ARE STILL IN FFF SPACE

! OBTAINING VELOCITY AND VORTICITY
CALL PC2VEL(PSI,CHI,RUR,RUP,UZ)                                    ! NOTE: INPUT AND OUTPUTS ARE STILL IN FFF SPACE
CALL PC2VOR(PSI,CHI,ROR,ROP,OZ)                                    ! NOTE: INPUT AND OUTPUTS ARE STILL IN FFF SPACE

! FFF -> PPP SPACE
CALL TOFP(RUR); CALL TOFP(RUP); CALL TOFP(UZ)
CALL TOFP(ROR); CALL TOFP(ROP); CALL TOFP(OZ)
CALL TOFP(RBR); CALL TOFP(RBP); CALL TOFP(BZ)

! CALCULATE NONLINEAR TERMS
NI=SIZE(RUR%E,1); NJ=SIZE(RUR%E,2); NK=SIZE(RUR%E,3)
!> CALCULATING U X OMEGA
!> NOTE: RUR, RUP, UZ UPDATED WITH FREESTREAM VELOCITY IN PPP SPACE
!>       ROR, ROP, OZ BECAME U X OMEGA IN PPP SPACE
CALL VPRODSUB(RUR%E,RUP%E,UZ%E,ROR%E,ROP%E,OZ%E,NI,NJ,NK,RUR%INR)
!> CALCULATING -(U.GRAD)B
!> NOTE: RUR, RUP, UZ ALREADY CONTAINS FREESTREAM DUE TO VPRODSUB
IF (ASSOCIATED(BN%E)) CALL DEALLOCATE(BN)
CALL ALLOCATE(BN,PPP_SPACE); BN%LN=0
BN%E = -VDOTPSUB(RUR%E,RUP%E,UZ%E,RBR%E,RBP%E,BZ%E,NI,NJ,NK,RUR%INR,.FALSE.)

! END DEALIASING
CALL CHOPSET(-3)

! ADD LINEAR TERMS TO NONLINEAR TERMS
CALL ALLOCATE(W); W = B
CALL TOFP(W)
!> 2OMEGA Z_HAT X U - B Z_HAT
ROR%E = ROR%E + 2*BSNSQ%OMEGA*RUP%E
ROP%E = ROP%E - 2*BSNSQ%OMEGA*RUR%E

OZ%E  = OZ%E - W%E
CALL DEALLOCATE(W)
!> N_BAR^2 * UZ
BN%E = BN%E + BSNSQ%BV0**2*UZ%E

CALL DEALLOCATE( RUR ); CALL DEALLOCATE( RUP ); CALL DEALLOCATE( UZ  )
CALL DEALLOCATE( RBR ); CALL DEALLOCATE( RBP ); CALL DEALLOCATE( BZ  )

!> CALCULATING FINAL TERMS PSIN, CHIN, BN IN FFF SPACE
CALL ALLOCATE(W)
CALL PROJECT(ROR,ROP,OZ,PSIN,W,0.D0)                               ! NOW PSIN = PSI_NONLINEAR AND W = DELSQ(CHI_NONLINEAR)
CALL DEALLOCATE( ROR )
CALL DEALLOCATE( ROP )
CALL DEALLOCATE( OZ  )

! CALL IDEL2(W,CHIN)                                               ! NOW CHIN = CHI_NONLINEAR
CALL IDEL2LN(W,CHIN)
CALL DEALLOCATE( W   )
CALL TOFF(BN)

CALL MPI_BARRIER(MPI_COMM_IVP,IERR)
RETURN
END SUBROUTINE CALC_BOUSSI_FORCE
