SUBROUTINE CALC_ENERGY(PSI,CHI,B,TIME,SAVEDIR)
!=======================================================================
! [USAGE]:
! CALCULATE KINETIC AND POTENTIAL ENERGY IN THE SYSTEM
! D(KE)/DT = DKE
! D(PE)/DT = -DKE
! [PARAMETERS]:
! PSI >> TOROIDAL TERM IN A SCALAR-TYPE VARIABLE (FFF SPACE)
! CHI >> POLOIDAL TERM IN A SCALAR-TYPE VARIABLE (FFF SPACE)
! B   >> DENSITY TERM IN A SCALAR-TYPE VARIABLE (FFF SPACE)
! TIME >> CURRENT TIME IN THE SIMULATION
! SAVEDIR >> DIRECTORY TO SAVE THE ENERGY DATA
! [DEPENDENCIES]:
! 1. DELSQH(~) @ MOD_LEGOPS <- REQUIRES CHOPSET
! 2. DEL2(~) @ MOD_LEGOPS
! 3. RTRAN(~) @ MOD_FFT
! 4. PRODCT_MK(~) @ MOD_SCALAR3
! 5. INTEG_MK(~) @ MOD_SCALAR3
!==========================================================================
IMPLICIT NONE
TYPE(SCALAR),INTENT(IN):: PSI,CHI,B
TYPE(SCALAR):: W1,W2,W3
REAL(P8):: PE(NXCHOP),PE2(NXCHOP),KE(NTCHOP,NXCHOP),DKE(NTCHOP,NXCHOP),TIME
COMPLEX(P8):: PE_MK(NTCHOP,NXCHOPDIM), PE_K2(NXCHOPDIM)
INTEGER:: KK,KC,FILESTATUS
CHARACTER(LEN=72):: SAVEDIR

IF (B%LN .NE. 0.D0) THEN
! LN TERM IN B IS NOT PHYSICAL, AS B CAN'T BE IFINITE AT FAR FIELD
  CALL MPRINT('B has non-zero LN, this is not expected in Boussinesq')
  CALL MPI_ABORT(MPI_COMM_IVP, ERR_FLAGS%SCALAR3_LOGTERM, IERR)
ENDIF

CALL ALLOCATE(W1)
CALL ALLOCATE(W2)
CALL ALLOCATE(W3)
CALL CHOPSET(3)

! KINETIC ENERGY:
! ENERGY IN TOROIDAL COMPONENT
W1 = PSI
IF ((PSI%INX.EQ.0).AND.(PSI%INTH.EQ.0)) W1%LN = 2.0_P8*PSI%LN
CALL DELSQH(W1,W2)
W1%LN = 0.0_P8
W2%LN = 0.0_P8
CALL RTRAN(W1,1)
CALL RTRAN(W2,1)
KE = -PRODCT_MK_HALFK(W1,W2)

! ENERGY IN POLOIDAL COMPONENT
CALL DEL2(CHI,W1)
CALL DELSQH(CHI,W2)
W1%LN = 0.0_P8
W2%LN = 0.0_P8
CALL RTRAN(W1,1)
CALL RTRAN(W2,1)

! TOTAL KINETIC ENERGY
KE = KE + PRODCT_MK_HALFK(W1,W2)

! ENERGY EXCHANGE
W3 = B
W3%LN = 0.0_P8
CALL RTRAN(W3,1) ! Convert to PFF space
DKE = PRODCT_MK_HALFK(W3,W2)  ! W3 = B, W2 = (1-X)^-2*DEL^2_H(CHI) = -(1-X)^-2*UZ

CALL CHOPSET(-3)
CALL DEALLOCATE(W1)
CALL DEALLOCATE(W2)
CALL DEALLOCATE(W3)

! POTENTIAL ENERGY:
CALL ALLOCATE(W3)
CALL DIVXM2(B,W3) ! W3 = (1-X)^-2 * B
! PE_K2 = INTEG_K_FFF(W3)
PE_K2 = INTEG_K_PFF(B)

CALL RTRAN(W3,1) ! Convert to PFF space
PE_MK = INTEG_MK(W3)
CALL DEALLOCATE(W3)

! CHECK SYMMETRY FOR M = 0
DO KK = 1,NXCHOP
  IF (KK.EQ.1) THEN
    IF (ABS(AIMAG(PE_MK(1,1))) .GT. 1E-12) THEN
      CALL MPRINT('CALC_ENERGY: M = 0, K = 0 MODE OF INT[B] IS NOT REAL!')
      CALL MPI_ABORT(MPI_COMM_IVP, ERR_FLAGS%CALCULATION, IERR)
    ENDIF
    CYCLE
  ENDIF
  KC = NXCHOPDIM+2-KK
  IF (ABS(PE_MK(1,KK)-CONJG(PE_MK(1,KC))) .GT. 1E-12) THEN
    CALL MPRINT('CALC_ENERGY: M = 0 MODES OF INT[B] DO NOT PRESERVE CONJUGATE SYMMETRY. INT[B] IS NOT REAL!')
    CALL MPI_ABORT(MPI_COMM_IVP, ERR_FLAGS%CALCULATION, IERR)
  ENDIF
ENDDO
! CALCULATE INT[Z*B']
PE = 0.D0
PE(1) = REAL(PE_MK(1,1)) * ZLEN0**2 * PI
! PE_K(2:) = -(PE_MK(1,2:)/AK(1,2:)) * ZLEN0 * 2 * PI * IU
! PE_K(KK) = PE_K(KK) + PE_K(KC)
PE(2:NXCHOP) = AIMAG(PE_MK(1,2:NXCHOP)) / AK(1,2:NXCHOP) * ZLEN0 * 4.0_P8 * PI

! PE2
PE2 = 0.D0
PE2(1) = REAL(PE_K2(1)) * ZLEN0**2 * PI
PE2(2:NXCHOP) = AIMAG(PE_K2(2:NXCHOP)) / AK(1,2:NXCHOP) * ZLEN0 * 4.0_P8 * PI
! DO KK = 2,NXCHOP
!   PE2(KK) = AIMAG(PE_K2(1,KK)) / AK(1,KK) * ZLEN0 *4 *PI
! ENDDO

! Combined PRINTOUT
IF (MPI_RANK.EQ.0) THEN
  OPEN(UNIT=667,FILE=TRIM(ADJUSTL(SAVEDIR))//'especData.dat',STATUS='UNKNOWN',&
    & IOSTAT=FILESTATUS, POSITION='APPEND')
  WRITE(667, '(" KE:",F24.16,1X,*(E24.16,1X))') TIME, (SUM(KE(:,KK)),KK=1,NXCHOP)
  WRITE(667, '(" PE:",F24.16,1X,*(E24.16,1X))') TIME, (PE(KK), KK=1,NXCHOP)
  WRITE(667, '("PE2:",F24.16,1X,*(E24.16,1X))') TIME, (PE2(KK), KK=1,NXCHOP)
  WRITE(667, '("DKE:",F24.16,1X,*(E24.16,1X))') TIME, (SUM(DKE(:,KK)),KK=1,NXCHOP)
  CLOSE(667)
ENDIF

END SUBROUTINE CALC_ENERGY
