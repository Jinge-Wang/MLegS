  SUBROUTINE STEP_INCOMP_AB_CN(PSI,CHI,PSINO,CHINO)
!=======================================================================
! [USAGE]: 
! UPDATE POLOIDAL-TOROIDAL TERMS OF THE VELOCITY FIELD BY 1 TIME STEP
! USING ADAMS-BASHFORTH METHOD
! [PARAMETERS]:
! PSI >> TOROIDAL TERM IN A SCALAR-TYPE VARIABLE
! CHI >> POLOIDAL TERM IN A SCALAR-TYPE VARIABLE
! PSINO >> NONLINEAR COMPONENT OF THE TOROIDAL TERM IN THE PREVIOUS STEP
! CHINO >> NONLINEAR COMPONENT OF THE POLOIDAL TERM IN THE PREVIOUS STEP
! [DEPENDENCIES]:
! 1. (DE)ALLOCATE(~) @ MOD_SCALAR3
! 2. NONLIN(~) @ MOD_LEGOPS
! 3. CALC_INCOMP_VISC_CN(~) @ MOD_MARCH
! 4. CALC_INCOMP_HYPERV(~) @ MOD_MARCH
! [UPDATES]:
! RE-CODED BY SANGJOON LEE @ NOV 20 2020
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR):: PSI,CHI,PSINO,CHINO
  TYPE(SCALAR):: PSIN,CHIN

  TYPE(SCALAR):: PSI0,CHI0
  REAL(P8):: DT

  DT = TIM%DT
  TIM%T = TIM%T + DT
  TIM%N = TIM%N + 1
  ADV%X = ADV%X + ADV%UX*DT
  ADV%Y = ADV%Y + ADV%UY*DT

  CALL ALLOCATE( PSIN )
  CALL ALLOCATE( CHIN )

  CALL NONLIN(PSI,CHI,PSIN,CHIN)

  CALL ALLOCATE( PSI0 )
  CALL ALLOCATE( CHI0 )

  PSI0 = PSI
  CHI0 = CHI

  PSI%E = PSI%E +DT*(1.5D0*PSIN%E -0.5D0*PSINO%E)
  CHI%E = CHI%E +DT*(1.5D0*CHIN%E -0.5D0*CHINO%E)

  PSINO=PSIN
  CHINO=CHIN

  CALL DEALLOCATE( PSIN )
  CALL DEALLOCATE( CHIN )

  CALL CALC_INCOMP_VISC_CN(PSI,CHI,PSI0,CHI0)
  CALL DEALLOCATE( PSI0 )
  CALL DEALLOCATE( CHI0 )

  CALL CALC_INCOMP_HYPERV(PSI,CHI,DT)

  RETURN
  END SUBROUTINE STEP_INCOMP_AB_CN
!=======================================================================

  SUBROUTINE RICH_INCOMP_FE_BE(PSI,CHI,PSIN,CHIN)
!=======================================================================
! [USAGE]: 
! UPDATE POLOIDAL-TOROIDAL TERMS OF THE VELOCITY FIELD BY 1 TIME STEP
! USING RICHARDSON EXTRAPOLATION
! [PARAMETERS]:
! PSI >> TOROIDAL TERM IN A SCALAR-TYPE VARIABLE
! CHI >> POLOIDAL TERM IN A SCALAR-TYPE VARIABLE
! PSIN >> NONLINEAR COMPONENT OF THE TOROIDAL TERM
! CHIN >> NONLINEAR COMPONENT OF THE POLOIDAL TERM
! [DEPENDENCIES]:
! 1. (DE)ALLOCATE(~) @ MOD_SCALAR3
! 2. NONLIN(~) @ MOD_LEGOPS
! 3. CALC_INCOMP_VISC_BE(~) @ MOD_MARCH
! 4. CALC_INCOMP_HYPERV(~) @ MOD_MARCH
! [UPDATES]:
! RE-CODED BY SANGJOON LEE @ NOV 20 2020
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR):: PSI,CHI,PSIN,CHIN

  TYPE(SCALAR):: PSI2,CHI2
  TYPE(SCALAR):: P_N,C_N
  REAL(P8):: DT, HDT

  DT = TIM%DT
  HDT = DT*0.5D0
  TIM%T = TIM%T + DT
  TIM%N = TIM%N + 1
  ADV%X = ADV%X + ADV%UX*DT
  ADV%Y = ADV%Y + ADV%UY*DT

  CALL ALLOCATE(PSI2)
  CALL ALLOCATE(CHI2)

  ! FIRST HALF-STEP
  CALL NONLIN(PSI,CHI,PSIN,CHIN)

  PSI2%E =PSI%E + (HDT*PSIN%E)
  CHI2%E =CHI%E + (HDT*CHIN%E)
  CALL CALC_INCOMP_VISC_BE(PSI2,CHI2,HDT)
  CALL CALC_INCOMP_HYPERV(PSI2,CHI2,HDT)

  CALL ALLOCATE( P_N )
  CALL ALLOCATE( C_N )

  ! SECOND HALF-STEP
  CALL NONLIN(PSI2,CHI2,P_N,C_N)

  PSI2%E =PSI2%E + (HDT*P_N%E)
  CHI2%E =CHI2%E + (HDT*C_N%E)
  CALL DEALLOCATE( P_N )
  CALL DEALLOCATE( C_N )
  CALL CALC_INCOMP_VISC_BE(PSI2,CHI2,HDT)
  CALL CALC_INCOMP_HYPERV(PSI2,CHI2,HDT)

  ! FULL STEP
  PSI%E =PSI%E +(DT)*PSIN%E
  CHI%E =CHI%E +(DT)*CHIN%E

  CALL CALC_INCOMP_VISC_BE(PSI,CHI,DT)
  CALL CALC_INCOMP_HYPERV(PSI,CHI,DT)

  PSI%E =(2.0D0*PSI2%E)-PSI%E
  CHI%E =(2.0D0*CHI2%E)-CHI%E

  CALL DEALLOCATE( PSI2 )
  CALL DEALLOCATE( CHI2 )

  RETURN
  END SUBROUTINE RICH_INCOMP_FE_BE
!=======================================================================

  SUBROUTINE STEP_BOUSSI_FE_BE(PSI,CHI,B,PSIN,CHIN,BN)
!=======================================================================
! [USAGE]: 
! UPDATE POLOIDAL-TOROIDAL TERMS OF THE VELOCITY FIELD BY 1 TIME STEP
! USING FORWARD EULER METHOD
! [PARAMETERS]:
! PSI >> TOROIDAL TERM IN A SCALAR-TYPE VARIABLE
! CHI >> POLOIDAL TERM IN A SCALAR-TYPE VARIABLE
! B   >> DENSITY TERM IN A SCALAR-TYPE VARIABLE
! PSIN >> NONLINEAR COMPONENT OF THE TOROIDAL TERM
! CHIN >> NONLINEAR COMPONENT OF THE POLOIDAL TERM
! BN   >> NONLINEAR COMPONENT OF THE DENSITY TERM
! [DEPENDENCIES]:
! 1. (DE)ALLOCATE(~) @ MOD_SCALAR3
! 2. NONLIN(~) @ MOD_LEGOPS
! 3. CALC_BOUSSI_VISC_BE(~) @ MOD_MARCH
! 4. CALC_BOUSSI_HYPERV(~) @ MOD_MARCH
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR):: PSI,CHI,B,PSIN,CHIN,BN

  REAL(P8):: DT

  DT = TIM%DT
  TIM%T = TIM%T + DT
  TIM%N = TIM%N + 1
  ADV%X = ADV%X + ADV%UX*DT
  ADV%Y = ADV%Y + ADV%UY*DT

  CALL CALC_BOUSSI_FORCE(PSI,CHI,B,PSIN,CHIN,BN)

  PSI%E  = PSI%E  + (DT*PSIN%E)
  PSI%LN = PSI%LN + (DT*PSIN%LN)
  CHI%E  = CHI%E  + (DT*CHIN%E)
  CHI%LN = CHI%LN + (DT*CHIN%LN)
  B%E    =  B%E   + (DT*  BN%E)

  CALL CALC_BOUSSI_VISC_BE(PSI,CHI,B,DT)
  CALL CALC_BOUSSI_HYPERV(PSI,CHI,B,DT)

  RETURN
  END SUBROUTINE STEP_BOUSSI_FE_BE
!=======================================================================

  SUBROUTINE RICH_BOUSSI_FE_BE(THIS, PSI, CHI, B)
!=======================================================================
  IMPLICIT NONE
  TYPE(SOLVER_T), INTENT(INOUT) :: THIS
  TYPE(SCALAR), INTENT(INOUT)   :: PSI, CHI, B

  TYPE(SCALAR):: PSI2,CHI2,B2
  TYPE(SCALAR):: P_N,C_N,B_N
  REAL(P8):: DT, HDT

  DT = TIM%DT
  HDT = DT*0.5D0
  TIM%T = TIM%T + DT
  TIM%N = TIM%N + 1
  ADV%X = ADV%X + ADV%UX*DT
  ADV%Y = ADV%Y + ADV%UY*DT

  CALL ALLOCATE(PSI2)
  CALL ALLOCATE(CHI2)
  CALL ALLOCATE(  B2)

  ! FIRST HALF-STEP
  CALL CALC_BOUSSI_FORCE(PSI,CHI,B,THIS%N_PSI,THIS%N_CHI,THIS%N_B)

  PSI2%E  =PSI%E  + (HDT*THIS%N_PSI%E)
  PSI2%LN =PSI%LN + (HDT*THIS%N_PSI%LN)
  CHI2%E  =CHI%E  + (HDT*THIS%N_CHI%E)
  CHI2%LN =CHI%LN + (HDT*THIS%N_CHI%LN)
  B2%E    =B%E    + (HDT*THIS%N_B%E)
  CALL CALC_BOUSSI_VISC_BE(PSI2,CHI2,B2,HDT)
  CALL CALC_BOUSSI_HYPERV(PSI2,CHI2,B2,HDT)

  CALL ALLOCATE( P_N )
  CALL ALLOCATE( C_N )
  CALL ALLOCATE( B_N )

  ! SECOND HALF-STEP
  CALL CALC_BOUSSI_FORCE(PSI2,CHI2,B2,P_N,C_N,B_N)

  PSI2%E  =PSI2%E  + (HDT*P_N%E)
  PSI2%LN =PSI2%LN + (HDT*P_N%LN)
  CHI2%E  =CHI2%E  + (HDT*C_N%E)
  CHI2%LN =CHI2%LN + (HDT*C_N%LN)
  B2%E    =B2%E    + (HDT*B_N%E)
  CALL DEALLOCATE( P_N )
  CALL DEALLOCATE( C_N )
  CALL DEALLOCATE( B_N )
  CALL CALC_BOUSSI_VISC_BE(PSI2,CHI2,B2,HDT)
  CALL CALC_BOUSSI_HYPERV(PSI2,CHI2,B2,HDT)

  ! FULL STEP
  PSI%E  =PSI%E  + (DT)*THIS%N_PSI%E
  PSI%LN =PSI%LN + (DT)*THIS%N_PSI%LN
  CHI%E  =CHI%E  + (DT)*THIS%N_CHI%E
  CHI%LN =CHI%LN + (DT)*THIS%N_CHI%LN
  B%E    =B%E    + (DT)*THIS%N_B%E

  CALL CALC_BOUSSI_VISC_BE(PSI,CHI,B,DT)
  CALL CALC_BOUSSI_HYPERV(PSI,CHI,B,DT)

  PSI%E  =(2.0D0*PSI2%E)-PSI%E
  PSI%LN =(2.0D0*PSI2%LN)-PSI%LN
  CHI%E  =(2.0D0*CHI2%E)-CHI%E
  CHI%LN =(2.0D0*CHI2%LN)-CHI%LN
  B%E    =(2.0D0*B2%E)-B%E

  CALL DEALLOCATE( PSI2 )
  CALL DEALLOCATE( CHI2 )
  CALL DEALLOCATE(   B2 )

  RETURN
  END SUBROUTINE RICH_BOUSSI_FE_BE
