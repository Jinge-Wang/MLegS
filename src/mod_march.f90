  SUBROUTINE CALC_BOUSSI_ETDAB_SUB(THIS,B,RUR,RUP,UZ,NB,RNR,RNP,NZ,DT)
!=======================================================================
! [USAGE]:
! APPLY EXPONENTIAL TIME DIFFERENCING SCHEME:
! L = S * J * S^-1
! E = S * exp(J*DT) * S^-1
! A = (3/2) * S * J^-1 * (exp(J*DT)-I) * S^-1
! B = (1/2) * S * J^-1 * (exp(J*DT)-I) * S^-1
! U^(N+1/2) = E*U^(N) + A*N[U^(N)] - B*N[U^(N-1)]
! [PARAMETERS]:
! THIS >> SOLVER OBJECT CONTAINING THE NONLINEAR STATE OF PREV STEP
!   B >> ON ENTRY, B OF CURRENT STEP
!        ON EXIT, B^(N+1/2)
! RUR >> ON ENTRY, R*U_R OF CURRENT STEP IN PFF SPACE
!        ON EXIT, R*U^(N+1/2)_R
! RUP >> ON ENTRY, R*U_P OF CURRENT STEP IN PFF SPACE
!        ON EXIT, R*U^(N+1/2)_P
!  UZ >> ON ENTRY, U_Z OF CURRENT STEP IN PFF SPACE
!        ON EXIT, U^(N+1/2)_Z
!  NB >> ON ENTRY, N_B OF CURRENT STEP IN PFF SPACE
! RNR >> ON ENTRY, R*N_R OF CURRENT STEP IN PFF SPACE
! RNP >> ON ENTRY, R*N_P OF CURRENT_STEP IN PFF SPACE
!  NZ >> ON ENTRY, N_Z OF CURRENT STEP IN PFF SPACE
!=======================================================================
  IMPLICIT NONE
  TYPE(SOLVER_T),INTENT(IN):: THIS
  TYPE(SCALAR),INTENT(IN):: RNR,RNP,NZ,NB
  TYPE(SCALAR),INTENT(INOUT):: RUR,RUP,UZ,B
  REAL(P8), INTENT(IN):: DT

  INTEGER:: NI, NJ, NK, NN, MM, KK
  COMPLEX(P8), DIMENSION(4,1) :: EV, ABV, CV
  REAL(P8) :: NOT_M0, NOT_K0

  ! --- Space Checks ---
  IF ((RUR%SPACE .NE. PFF_SPACE) .OR. (NB%SPACE .NE. PFF_SPACE) .OR. (RNR%SPACE .NE. PFF_SPACE)) THEN
    CALL MPRINT('CALC_BOUSSI_ETDAB_SUB: RUR, NB, RNR must be in PFF space.')
    CALL MPI_ABORT(MPI_COMM_IVP, ERR_FLAGS%LEGOPERATOR, IERR)
  ENDIF

  IF (B%SPACE .EQ. FFF_SPACE) THEN
    CALL RTRAN(B, 1)
  ELSEIF (B%SPACE .NE. PFF_SPACE) THEN
    CALL MPRINT('CALC_BOUSSI_ETDAB_SUB: B must be in PFF or FFF space.')
    CALL MPI_ABORT(MPI_COMM_IVP, ERR_FLAGS%LEGOPERATOR, IERR)
  ENDIF
  ! --- End Space Checks ---

  !$OMP PARALLEL DO PRIVATE(MM, NN, EV, ABV, CV, NOT_K0, NOT_M0) SCHEDULE(STATIC)
  DO KK = 1,SIZE(B%E,3)
    NOT_K0 = 1.0D0
    DO MM = 1,SIZE(B%E,2)
      NOT_M0 = 1.0D0
      IF (B%INTH+MM .EQ. 1) NOT_M0 = 0.0D0
      DO NN = 1, NR
        ! E*( U^(N) - GRAD PI^(N) ) + A*N[U^(N)] - B*N[U^(N-1)]
        EV(1,1) = RUR%E(NN,MM,KK) - THIS%R_PI_R%E(NN,MM,KK)
        EV(2,1) = RUP%E(NN,MM,KK) - THIS%R_PI_P%E(NN,MM,KK)*NOT_M0
        EV(3,1) = UZ%E(NN,MM,KK) - THIS%PI_Z%E(NN,MM,KK)*NOT_K0
        EV(4,1) = B%E(NN,MM,KK)

        ABV(1,1) = 1.5D0*RNR%E(NN,MM,KK) - 0.5D0*THIS%R_N_R%E(NN,MM,KK)
        ABV(2,1) = 1.5D0*RNP%E(NN,MM,KK) - 0.5D0*THIS%R_N_P%E(NN,MM,KK)
        ABV(3,1) = 1.5D0*NZ%E(NN,MM,KK) - 0.5D0*THIS%N_Z%E(NN,MM,KK)
        ABV(4,1) = 1.5D0*NB%E(NN,MM,KK) - 0.5D0*THIS%N_B%E(NN,MM,KK)

        ! CV = MATMUL(ETD_E_R, EV) + MATMUL(ETD_NL_R, ABV)
        CV(1:2,1) = MATMUL(THIS%ETD_FULL%E_H(:,:,NN,MM), EV(1:2,1)) + &
                  MATMUL(THIS%ETD_FULL%NL_H(:,:,NN,MM), ABV(1:2,1))
        CV(3:4,1) = MATMUL(THIS%ETD_FULL%E_V(:,:,NN,MM), EV(3:4,1)) + & 
                  MATMUL(THIS%ETD_FULL%NL_V(:,:,NN,MM), ABV(3:4,1))

        RUR%E(NN,MM,KK) = CV(1,1)
        RUP%E(NN,MM,KK) = CV(2,1)
        UZ%E(NN,MM,KK) = CV(3,1)
        B%E(NN,MM,KK) = CV(4,1)

      ENDDO
    ENDDO
  ENDDO
  !$OMP END PARALLEL DO

  RETURN
  END SUBROUTINE CALC_BOUSSI_ETDAB_SUB
