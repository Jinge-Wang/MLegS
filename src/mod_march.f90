  TYPE(SCALAR), INTENT(INOUT)   :: PSI, CHI, B

  TYPE(SCALAR):: PSI2, CHI2, B2
  TYPE(SCALAR):: RUR, RUP, UZ
  REAL(P8):: DT, HDT
  IF ((.NOT.ALLOCATED(THIS%ETD_FULL%E_H)).OR. &
      (.NOT.ALLOCATED(THIS%ETD_HALF%E_H))) THEN
