  SUBROUTINE CALC_BOUSSI_ETD_HYPERV(RUR,RUP,UZ,B,DT)
!=======================================================================
! [USAGE]: 
! DUMP HYPERVISCOSITY TO THE HIGHER ORDER COEFFICIENTS FOR ETD METHODS
! OPERATES ONLY WHEN VISC%SW = 3
! [PARAMETERS]:
! RUR, RUP, UZ, B >> SCALAR FIELDS TO APPLY HYPERVISCOSITY/DIFFUSIVITY
! DT >> TIMESTEP
! [DEPENDENCIES]:
! 1. (DE)ALLOCATE(~) @ MOD_SCALAR3
! 2. HYPERV(~) @ MOD_MARCH
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR), INTENT(INOUT):: RUR, RUP, UZ, B
  REAL(P8), INTENT(IN):: DT

  INTEGER:: MM, KK, NN
  REAL(P8):: TIME_FACTOR

  IF(VISC%SW.EQ.0) THEN

    IF ((MPI_RANK.EQ.0).AND.(MOD(tim%n,diagv%it1).eq.0)) WRITE(6,*) 'WARNING: NO DISSIPATION AT ALL.'

  ELSEIF(VISC%SW.EQ.2) THEN

    CALL MPRINT('CALC_BOUSSI_ETD_HYPERV: HYPERV IN VELOCITY FORM IS NOT IMPLEMENTED YET.')

  ELSEIF(VISC%SW.EQ.3) THEN

    IF (RUR%SPACE .NE. FFF_SPACE) THEN
      CALL MPRINT('CALC_BOUSSI_ETD_HYPERV: RUR must be in FFF space.')
      CALL MPI_ABORT(MPI_COMM_IVP, ERR_FLAGS%TRANSFORM, IERR)
    ENDIF

    TIME_FACTOR = DT/TIM%DT

    !$OMP PARALLEL DO PRIVATE(KK, MM, NN) &
    !$OMP& SCHEDULE(STATIC) COLLAPSE(2)
    DO KK = 1,SIZE(RUR%E,3); DO MM = 1,SIZE(RUR%E,2)

      NN = NRCHOPS(MM + RUR%INTH)

      ! HYPERVISCOSITY
      RUR%E(:NN,MM,KK) = RUR%E(:NN,MM,KK) * &
        (VISC%HYPERV_R(:NN,MM+RUR%INTH) * VISC%HYPERV_T(MM+RUR%INTH) * VISC%HYPERV_X(KK+RUR%INX))**TIME_FACTOR
      RUP%E(:NN,MM,KK) = RUP%E(:NN,MM,KK) * &
        (VISC%HYPERV_R(:NN,MM+RUR%INTH) * VISC%HYPERV_T(MM+RUR%INTH) * VISC%HYPERV_X(KK+RUR%INX))**TIME_FACTOR
      UZ%E(:NN,MM,KK) = UZ%E(:NN,MM,KK) * &
        (VISC%HYPERV_R(:NN,MM+RUR%INTH) * VISC%HYPERV_T(MM+RUR%INTH) * VISC%HYPERV_X(KK+RUR%INX))**TIME_FACTOR

      ! HYPERDIFFUSIVITY
      B%E(:NN,MM,KK) = B%E(:NN,MM,KK) * &
        (VISC%HYPERD_R(:NN,MM+RUR%INTH) * VISC%HYPERD_T(MM+RUR%INTH) * VISC%HYPERD_X(KK+RUR%INX))**TIME_FACTOR

    ENDDO; ENDDO
    !$OMP END PARALLEL DO
    CALL CHOPDO(RUR)
    CALL CHOPDO(RUP)
    CALL CHOPDO(UZ)
    CALL CHOPDO(B)

  ENDIF

  RETURN
  END SUBROUTINE CALC_BOUSSI_ETD_HYPERV

!> ====================================================================
!> @brief APPLIES SPONGE LAYER DAMPING TO UZ AND B'.
!>
!> @details
!> THIS SUBROUTINE APPLIES EXPONENTIAL DAMPING TO UZ AND B' AS:
!>   A'(r,th,z) = exp[-D(z) x DT] x A(r,th,z)
!> WHERE THE DAMPING FUNCTION IS:
!>   D(z) = [1 - T_z(z)] / tau_sponge
!>
!> @param[in,out] UZ >> AXIAL VELOCITY FIELD  
!> @param[in,out] B  >> DENSITY PERTURBATION FIELD
!> @param[in]     DT  >> TIMESTEP SIZE
!>
!> @note REQUIRES PRIOR CALL TO SPNGINIT.
!>
!> @author JINGE WANG
!> @date   OCT 2025  
!> ====================================================================
SUBROUTINE CALC_BOUSSI_ETD_SPONGE(UZ,B,DT)
! ======================================================================
  IMPLICIT NONE
  TYPE(SCALAR), INTENT(INOUT):: UZ, B
  REAL(P8), INTENT(IN):: DT

  INTEGER:: KK
  REAL(P8):: DAMP_RATE

  IF (RMV%SW.NE.2) RETURN

  IF (UZ%SPACE .EQ. FFF_SPACE) THEN
    CALL RTRAN(UZ,1); CALL VERFFT(UZ,1)
    CALL RTRAN(B,1); CALL VERFFT(B,1)
  ELSEIF (UZ%SPACE .EQ. PFF_SPACE) THEN
    CALL VERFFT(UZ,1)
    CALL VERFFT(B,1)
  ELSEIF (UZ%SPACE .EQ. PPP_SPACE) THEN
    CALL MPRINT('SPONGE: INPUT CANNOT BE IN PPP_SPACE')
    CALL MPI_ABORT(MPI_COMM_IVP, ERR_FLAGS%TRANSFORM, IERR)
  ENDIF

  !$OMP PARALLEL DO PRIVATE(KK, DAMP_RATE)
  DO KK = 1, SIZE(UZ%E,3) ! Loop over physical z-points
    DAMP_RATE = EXP(-(1.D0 - RMV%TOPHAT_X(KK+UZ%INX))/RMV%TAU * DT)
      UZ%E(:,:,KK) = UZ%E(:,:,KK) * DAMP_RATE
      B%E(:,:,KK) = B%E(:,:,KK) * DAMP_RATE
  ENDDO
  !$OMP END PARALLEL DO

  ! MAKE M=0 MODES REAL TO PRESERVE COMPLEX SYMMETRY
  UZ%E(:,1,:) = CMPLX(REAL(UZ%E(:,1,:),P8),0.D0,P8)
  B%E(:,1,:) = CMPLX(REAL(B%E(:,1,:),P8),0.D0,P8)

  ! CALL TOFF(UZ); CALL TOFF(B)
  CALL VERFFT(B,-1)
  CALL VERFFT(UZ,-1)

  END SUBROUTINE CALC_BOUSSI_ETD_SPONGE
