!> ====================================================================
!> @brief APPLIES SPONGE LAYER DAMPING TO SCALAR FIELDS.
!>
!> @details
!> THIS SUBROUTINE APPLIES EXPONENTIAL DAMPING TO THE POLOIDAL-TOROIDAL
!> FIELDS (PSI, CHI) AND OPTIONALLY THE BUOYANCY FIELD (B) USING
!> PRECOMPUTED SPONGE LAYER COEFFICIENTS FROM SPNGINIT.
!>
!> THE DAMPING IS APPLIED AS:
!>   A'(r,th,z) = exp[-D(z) x DT] x A(r,th,z)
!>
!> WHERE THE DAMPING FUNCTION IS:
!>   D(r,z) = [1 - T_z(z)] / tau_sponge
!>   (OLD & INCORRECT) D(r,z) = [1 - T_r(r) x T_z(z)] / tau_sponge 
!>
!> @param[in,out] PSI >> TOROIDAL SCALAR FIELD IN FFF_SPACE  
!> @param[in,out] CHI >> POLOIDAL SCALAR FIELD IN FFF_SPACE
!> @param[in]     DT  >> TIMESTEP SIZE
!> @param[in,out] B   >> OPTIONAL BUOYANCY FIELD IN FFF_SPACE
!>
!> @warning FIELDS MUST BE IN FFF_SPACE ON ENTRY. THE ROUTINE PERFORMS
!>          MULTIPLE TRANSFORMS AND RETURNS FIELDS IN FFF_SPACE.
!>
!> @note ONLY OPERATES WHEN RMV%SW = 2. REQUIRES PRIOR CALL TO SPNGINIT.
!> @note Applying radial sponge layer to chi is definitely incorrect, 
!>       since uz is constructed from chi using delsqh operator which
!>       contains radial gradient. There will be large artifacts caused
!>       by the radial sponge in the transition region.
!>       On the other hand, applying the axial sponge layer to both psi
!>       and chi essentially imposes damping on all velocity components
!>       near the boundaries, which for ur and ut may not be physically
!>       necessary or correct as that is close to applying a drag near
!>       the sponge transition region.
!>       However, this may have future use when we need to have a finite
!>       viscous outshell region similar to Taylor-Couette setups.
!>
!> @author JINGE WANG
!> @date   OCT 2025  
!> ====================================================================
SUBROUTINE SPONGE(PSI,CHI,DT,B)
! ======================================================================
  IMPLICIT NONE
  TYPE(SCALAR), INTENT(INOUT):: PSI,CHI
  TYPE(SCALAR), INTENT(INOUT), OPTIONAL:: B
  REAL(P8), INTENT(IN):: DT

  LOGICAL:: HAS_B
  INTEGER:: NN, MM, KK
  REAL(P8):: DAMP_RATE, PSI_LN, CHI_LN

  IF (RMV%SW.NE.2) RETURN

  IF (PSI%SPACE .NE. FFF_SPACE) THEN
    CALL MPRINT('SPONGE: PSI INPUT MUST BE IN FFF_SPACE')
    CALL MPI_ABORT(MPI_COMM_IVP, ERR_FLAGS%TRANSFORM, IERR)
  ENDIF

  HAS_B = PRESENT(B)

  PSI_LN = PSI%LN; PSI%LN = 0.D0
  CHI_LN = CHI%LN; CHI%LN = 0.D0

  CALL RTRAN(PSI,1); CALL VERFFT(PSI,1)
  CALL RTRAN(CHI,1); CALL VERFFT(CHI,1)
  IF (HAS_B) THEN
    CALL RTRAN(B,1); CALL VERFFT(B,1)
  ENDIF

  ! only apply omp to the outer loops to preserve cache locality
  !$OMP PARALLEL DO PRIVATE(KK, MM, NN, DAMP_RATE)
  DO KK = 1, SIZE(PSI%E,3) ! Loop over physical z-points
    DAMP_RATE = EXP(-(1.D0 - RMV%TOPHAT_X(KK+PSI%INX))/RMV%TAU * DT)
    PSI%E(:,:,KK) = PSI%E(:,:,KK) * DAMP_RATE
    CHI%E(:,:,KK) = CHI%E(:,:,KK) * DAMP_RATE
    IF (HAS_B) B%E(:,:,KK) = B%E(:,:,KK) * DAMP_RATE
  ENDDO
  !$OMP END PARALLEL DO

  ! MAKE M=0 MODES REAL TO PRESERVE COMPLEX SYMMETRY
  PSI%E(:,1,:) = CMPLX(REAL(PSI%E(:,1,:),P8),0.D0,P8)
  CHI%E(:,1,:) = CMPLX(REAL(CHI%E(:,1,:),P8),0.D0,P8)
  IF (HAS_B) B%E(:,1,:) = CMPLX(REAL(B%E(:,1,:),P8),0.D0,P8)

  CALL TOFF(PSI); PSI%LN = PSI_LN
  CALL TOFF(CHI); CHI%LN = CHI_LN
  IF (HAS_B) CALL TOFF(B)

END SUBROUTINE SPONGE

!> ====================================================================
!> @brief APPLY SMOOTHENED RING CUTOFF TO SCALAR FIELD IN PFF SPACE.
!>
!> @details
!> ZERO MODES FROM NS0 TO FAR FIELD ALONG RADIAL DIRECTION AND PERFORM
!> CONVOLUTIONAL SMOOTHING FROM NS TO FAR FIELD WITH WEIGHTING.
!>
!> @param[in,out] WK  >> SCALAR FIELD IN PFF SPACE
!> @param[in]     NS0 >> START INDEX FOR ZEROING (TYPICALLY 2/3*NR+4)
!> @param[in]     NS  >> START INDEX FOR SMOOTHING (TYPICALLY 2/3*NR)
!> @param[in]     APPLY_DIVXM2 >> CONTAIN (1-X)^-2 IN WEIGHTING
!>
!> @note TFM%W/(1-TFM%X)^2 = 1/ELL2 * R. NOTE THAT DELSQH OPERATOR 
!>       CONTAINS A DIVISION BY (1-X)^2, WHILE DEL2 DOES NOT.
!> 
!> @author JINGE WANG
!> @date   OCT 2025  
!> ====================================================================
SUBROUTINE RINGCUT(WK, NS0, NS, APPLY_DIVXM2)
! ======================================================================
  IMPLICIT NONE
  TYPE(SCALAR), INTENT(INOUT) :: WK
  INTEGER, INTENT(IN) :: NS0, NS
  LOGICAL, INTENT(IN) :: APPLY_DIVXM2

  INTEGER :: MM, KK, I
  REAL(P8), DIMENSION(NS:NR) :: WEIGHT_FACTOR

  ! ZERO OUT MODES IN FAR FIELD
  IF (WK%INTH == 0) THEN
    WK%E(NS0:NR, 2:, :) = 0  ! Zero m > 0 modes
    IF (NX > 1) WK%E(NS0:NR, 1, MAX(2 - WK%INX, 1):) = 0  ! Zero m=0, k>0
  ELSE
    WK%E(NS0:NR, :, :) = 0
  END IF

  ! COMPUTE WEIGHTING FACTOR
  IF (APPLY_DIVXM2) THEN
    WEIGHT_FACTOR = TFM%W(NS:NR) / (1.D0 - TFM%X(NS:NR))**2
  ELSE
    WEIGHT_FACTOR = TFM%W(NS:NR)
  END IF

  ! APPLY SMOOTHING WITH WEIGHTING
  !$OMP PARALLEL DO PRIVATE(KK, MM, I) COLLAPSE(2)
  DO KK = 1, SIZE(WK%E, 3)
    DO MM = 1, SIZE(WK%E, 2)
      WK%E(NS:NR, MM, KK) = WK%E(NS:NR, MM, KK) * WEIGHT_FACTOR
      DO I = 1, 5
        WK%E(NS:NR, MM, KK) = SMOOTH(WK%E(NS:NR, MM, KK))
      END DO
      WK%E(NS:NR, MM, KK) = WK%E(NS:NR, MM, KK) / WEIGHT_FACTOR
    END DO
  END DO
  !$OMP END PARALLEL DO

END SUBROUTINE RINGCUT

!> ====================================================================
!> @brief KILL VORTICITIES IN FAR FIELD
!>
!> @details
!> ZERO MODES FROM NS0 TO FAR FIELD ALONG RADIAL DIRECTION AND PERFORM
!> CONVOLUTIONAL SMOOTHING FROM NS TO FAR FIELD WITH WEIGHTING.
!>
!> @param[in,out] PSI >> TOROIDAL FIELD IN PFF SPACE
!> @param[in,out] CHI >> POLOIDAL FIELD IN PFF SPACE
!> @param[in,out]   B >> OPTIONAL: DENSITY FIELD IN PFF SPACE
!>
!> @author SANGJOON LEE (UPDATES), JINGE WANG (UPDATES)
!> @date   NOV 2020, SEP 2025
!> ====================================================================
SUBROUTINE REMOVE(PSI, CHI, B)
! ======================================================================
  IMPLICIT NONE
  TYPE(SCALAR), INTENT(INOUT) :: PSI, CHI
  TYPE(SCALAR), INTENT(INOUT), OPTIONAL :: B

  TYPE(SCALAR) :: WK
  INTEGER :: NS, NS0
  REAL(P8) :: LN

  IF (RMV%SW .NE. 0) THEN
    CALL ALLOCATE(WK)
    
    ! SET RING CUTOFF INDICES
    NS = NR * 2 / 3
    NS0 = MIN(NS + 4, NR)

    ! ===== Process PSI: DEL^2_H weighting without (1-X)^2 correction =====
    CALL DELSQH(PSI, WK)              ! WK = DEL^2_H PSI / (1-X)^2
    CALL RTRAN(WK, 1)                 ! Transform to PFF space
    CALL RINGCUT(WK, NS0, NS, .FALSE.)  ! Use W weighting
    CALL RTRAN(WK, -1)                ! Back to FFF space
    CALL IDELSQH(WK, PSI)             ! Invert to get smoothed PSI

    ! ===== Process CHI: DEL^2 weighting WITH (1-X)^2 correction =====
    CALL CHOPSET(2)
    CALL DEL2(CHI, WK)                ! WK = DEL^2 CHI
    CALL RTRAN(WK, 1)                 ! Transform to PFF space
    CALL RINGCUT(WK, NS0, NS, .TRUE.) ! Use W/(1-X)^2 weighting
    CALL CHOPSET(-2)
    CALL RTRAN(WK, -1)                ! Back to FFF space
    LN = CHI%LN
    CALL IDEL2(WK, CHI, LN)           ! Invert to get smoothed CHI

    CALL DEALLOCATE(WK)

    IF (PRESENT(B)) THEN
      ! ===== Process B: DEL^2 weighting WITH (1-X)^2 correction =====
      CALL RTRAN(B, 1)                 ! Transform to PFF space
      CALL RINGCUT(B, NS0, NS, .TRUE.) ! Use W/(1-X)^2 weighting
      CALL RTRAN(B, -1)                ! Back to FFF space
    END IF

    IF (MPI_RANK .EQ. 0) WRITE(6, 60) TIM%N, TFM%R(NS)
60  FORMAT('REMOVE: TIM%N=', I5, '  R >=', F6.2)
  END IF

  RETURN
END SUBROUTINE REMOVE

!> ====================================================================
!> @brief COMPUTES KINETIC ENERGY SPECTRA BY WAVENUMBER.
!>
!> @details
!> THIS SUBROUTINE COMPUTES THE KINETIC ENERGY DISTRIBUTION ACROSS
!> AZIMUTHAL (`M`) AND AXIAL (`K`) WAVENUMBERS FROM THE POLOIDAL-
!> TOROIDAL FIELD DECOMPOSITION. 
!>
!> THE COMPUTATION INVOLVES:
!> 1. **TOROIDAL CONTRIBUTION**: COMPUTES ENERGY FROM PSI FIELD
!>    USING HORIZONTAL LAPLACIAN OPERATIONS (DELSQH)
!> 2. **POLOIDAL CONTRIBUTION**: COMPUTES ENERGY FROM CHI FIELD
!>    USING FULL LAPLACIAN AND HORIZONTAL LAPLACIAN OPERATIONS  
!> 3. **SPECTRAL PROJECTION**: USES PRODCT_M AND PRODCT_K TO
!>    PROJECT ENERGY ONTO AZIMUTHAL AND AXIAL WAVENUMBER MODES
!>
!> THE RESULTING SPECTRA ARE USED FOR SPECTRAL ANALYSIS, ENERGY
!> MONITORING, AND ADAPTIVE HYPERVISCOSITY CONTROL IN HYPADJ
!> AND HYP3ADJ.
!>
!> @param[in]  PSI >> TOROIDAL SCALAR FIELD IN FFF_SPACE
!> @param[in]  CHI >> POLOIDAL SCALAR FIELD IN FFF_SPACE
!> @param[out] EM  >> AZIMUTHAL ENERGY SPECTRUM E(M)
!> @param[out] EK  >> OPTIONAL AXIAL ENERGY SPECTRUM E(K)
!>
!> @author SANGJOON LEE (UPDATES), JINGE WANG (UPDATES)
!> @date   NOV 2020, SEP 2025
!> ====================================================================
SUBROUTINE ENEMON(PSI,CHI,EM,EK)
! ======================================================================
  IMPLICIT NONE
  TYPE(SCALAR):: PSI,CHI, W1,W2
  REAL(P8):: EM(NTCHOP)
  REAL(P8),OPTIONAL:: EK(NXCHOP)

  CALL ALLOCATE(W1)
  CALL ALLOCATE(W2)

  !> ENERGY P157
  W1=PSI
  IF ((PSI%INTH.EQ.0).AND.(PSI%INX.EQ.0)) W1%LN=2*PSI%LN
  CALL DELSQH(W1,W2)
  CALL RTRAN(W2,1)
  W1=PSI
  W1%LN=0.D0
  CALL RTRAN(W1,1)
  EM= PRODCT_M(W2,W1)
  IF (PRESENT(EK)) THEN
  EK= PRODCT_K(W2,W1)
  END IF
  
  CALL DEL2(CHI,W1)
  CALL RTRAN(W1,1)
  CALL DELSQH(CHI,W2)
  CALL RTRAN(W2,1)
  EM= -EM+PRODCT_M(W2,W1)
  IF (PRESENT(EK)) THEN
  EK= -EK+PRODCT_K(W2,W1)
  END IF

  CALL DEALLOCATE(W1)
  CALL DEALLOCATE(W2)

  RETURN
END SUBROUTINE ENEMON

!> =====================================================================
!> @brief COMPUTES SPECTRAL CURVATURE USING LEGENDRE POLYNOMIAL P_2(X).
!>
!> @details
!> THIS FUNCTION MEASURES THE CURVATURE OF A LOG10-SCALED ENERGY SPECTRUM
!> BY COMPUTING THE DOT PRODUCT WITH THE SECOND LEGENDRE POLYNOMIAL.
!> THE ANALYSIS IS PERFORMED OVER THE HIGH-WAVENUMBER TAIL TO DETECT
!> ENERGY BOTTLENECKS AND POTENTIAL NUMERICAL INSTABILITIES.
!>
!> THE CURVATURE IS COMPUTED AS:
!>   CURV = INT LOG10(E(k)) x P_2(X) dX
!> WHERE P_2(X) = SQRT(5/8) x (3X^2 - 1) AND X MAPS THE SPECTRAL RANGE.
!>
!> POSITIVE CURVATURE INDICATES UPWARD CONCAVITY (ENERGY BOTTLENECK).
!> NEGATIVE CURVATURE INDICATES DOWNWARD CONCAVITY (SMOOTH DECAY).
!>
!> @param[in] ESPEC >> ENERGY SPECTRUM ARRAY (SIZE ≥ 3)
!> @param[in] RATIO >> OPTIONAL: FRACTION OF SPECTRUM TO ANALYZE
!> @return    CURV  >> SPECTRAL CURVATURE VALUE
!>
!> @author JINGE WANG
!> @date   SEP 2025
!> =====================================================================
FUNCTION SPECURV(ESPEC, USE_RATIO) RESULT(CURV)
! ======================================================================
  IMPLICIT NONE
  REAL(P8), DIMENSION(:), INTENT(IN) :: ESPEC
  REAL(P8), INTENT(IN), OPTIONAL :: USE_RATIO
  REAL(P8) :: CURV

  REAL(P8), PARAMETER :: SPECTRAL_FLOOR = 1.0D-22, TARGET_CURV = -0.05D0
  REAL(P8), DIMENSION(:), ALLOCATABLE :: LOGSP
  REAL(P8) :: DX, X, FAC, R_USE, R_TRUNC
  INTEGER :: IS, IE, N, I

  ! DETERMINE ANALYSIS RANGE
  IF (PRESENT(USE_RATIO)) THEN; R_USE = USE_RATIO; ELSE; R_USE = 1.0D0/3.0D0; END IF
  
  IE = SIZE(ESPEC)  
  IS = IE - MAX(1, INT(IE * R_USE))
  DO WHILE (IE > IS .AND. (ESPEC(IE) < SPECTRAL_FLOOR))
    IE = IE - 1
  END DO
  R_TRUNC = 1.0D0 - REAL(IE-IS) / REAL(SIZE(ESPEC)-IS) ! FRACTION OF SPECTRUM TRUNCATED DUE TO FLOORING
  
  ! CHECK FOR INSUFFICIENT DATA OR FLOOR-HITTING
  N = IE - IS + 1
  IF ((N < 10) .OR. (R_TRUNC > 0.2)) THEN
    CURV = TARGET_CURV
    RETURN
  END IF
  
  ALLOCATE(LOGSP(N))
  LOGSP = LOG10(ESPEC(IS:IE))
  
  CURV = 0.0_P8
  DX = 2.0D0 / (N - 1)  ! INTEGRATION STEP SIZE
  
  ! TRAPEZOIDAL RULE WITH P_2(X) = SQRT(5/8) x (3X^2 - 1)
  DO I = 1, N
    X = -1.0_P8 + 2.0_P8 * (I - 1) / (N - 1)
    FAC = 1.0_P8
    IF (I == 1 .OR. I == N) FAC = 0.5_P8  ! TRAPEZOIDAL END WEIGHTS
    CURV = CURV + FAC * LOGSP(I) * DX * SQRT(5.0D0/8.0D0) * (3.0_P8 * X**2 - 1.0_P8)
  END DO
  
  ! CLAMP CURVATURE TO PREVENT RUNAWAY FEEDBACK
  CURV = MIN(10.0D0, MAX(-10.0D0, CURV))
  
  DEALLOCATE(LOGSP)

END FUNCTION SPECURV

!> =====================================================================
!> @brief CALCULATES SPECTRAL SLOPE FROM ENERGY SPECTRUM USING P1 
!>        LEGENDRE PROJECTION WITH LOGARITHMIC WAVENUMBER SPACING.
!>
!> @details
!> THIS FUNCTION COMPUTES THE SPECTRAL SLOPE FROM THE EQUATION
!> E(k) ~ k^a BY PROJECTING LOG10(E) ONTO THE P1 LEGENDRE POLYNOMIAL
!> USING A LOGARITHMIC WAVENUMBER SCALE: k' = LOG10(k/k_min).
!>
!> KEY DIFFERENCES FROM SPECURV:
!> • SPECURV: USES LINEAR INDEX SPACING, P2 POLYNOMIAL -> MEASURES CURVATURE
!> • SPESLOP: USES LOG-K SPACING, P1 POLYNOMIAL -> MEASURES SLOPE
!>
!> THE P1 PROJECTION IS: SLOPE = INT LOG10(E(k')) x P1(X) dX
!> WHERE X in [-1, +1] MAPS TO k' in [k'_MIN, k'_MAX],
!> AND P1(X) = (3/2)^1/2 X.
!>
!> PHYSICAL INTERPRETATION:
!> • a > -1:  SPECTRUM TOO FLAT, INSUFFICIENT DISSIPATION -> INCREASE DISSIPATION
!> • -3 < a < -2: HEALTHY INERTIAL RANGE (k^-5/3 ≈ -1.67)
!> • a < -5:  OVER-DAMPED, EXCESSIVE DISSIPATION -> DECREASE DISSIPATION
!>
!> THE LOG-K SPACING ENSURES EQUAL WEIGHT TO EACH DECADE OF WAVENUMBERS,
!> MAKING THE SLOPE MEASUREMENT ROBUST TO SPECTRAL SHAPE VARIATIONS.
!>
!> @param[in] ESPEC >> ENERGY SPECTRUM ARRAY E(k), k=1,2,...,N
!> @param[in] RATIO >> OPTIONAL: FRACTION OF SPECTRUM TO ANALYZE (DEFAULT=1/3)
!>                     ANALYZES HIGH-WAVENUMBER TAIL FROM k > N*RATIO
!>
!> @return    SLOPE >> SPECTRAL SLOPE a, CLAMPED TO [-15, +5]
!>
!> @note THE SLOPE IS CLAMPED TO PREVENT RUNAWAY FEEDBACK FROM
!>       NUMERICAL ARTIFACTS OR EXTREME SPECTRAL SHAPES.
!>
!> @author JINGE WANG
!> @date   OCT 2025
!> =====================================================================
FUNCTION SPESLOP(ESPEC, RATIO) RESULT(SLOPE)
! ======================================================================
  IMPLICIT NONE
  REAL(P8), DIMENSION(:), INTENT(IN) :: ESPEC
  REAL(P8), INTENT(IN), OPTIONAL :: RATIO
  REAL(P8) :: SLOPE
  
  REAL(P8), PARAMETER :: SPECTRAL_FLOOR = 1.0D-24  ! DOUBLE PRECISION LIMIT (ENERGY^2)
  REAL(P8), PARAMETER :: RELATIVE_DROP_THRESHOLD = 1.0D10
  REAL(P8), DIMENSION(:), ALLOCATABLE :: LOGSP, LOG_K
  REAL(P8) :: DX, X, XI, XI_MIN, XI_MAX, FAC, R_USE, PEAK_VALUE, RELATIVE_FLOOR
  INTEGER :: IS, IE, N, I, K_START

  ! DETERMINE ANALYSIS RANGE
  IF (PRESENT(RATIO)) THEN
    R_USE = RATIO
  ELSE
    R_USE = 1.0D0/3.0D0
  END IF
  
  IE = SIZE(ESPEC)
  IS = IE - MAX(1, INT(IE * R_USE))
  K_START = IS  ! STARTING WAVENUMBER INDEX
  
  ! FIND PEAK VALUE IN ANALYSIS RANGE TO SET RELATIVE THRESHOLD
  PEAK_VALUE = MAXVAL(ESPEC(IS:IE))
  RELATIVE_FLOOR = PEAK_VALUE / RELATIVE_DROP_THRESHOLD
  
  ! HYBRID THRESHOLD: USE HIGHER OF ABSOLUTE OR RELATIVE FLOOR
  DO WHILE (IE > IS .AND. (ESPEC(IE) < SPECTRAL_FLOOR .OR. ESPEC(IE) < RELATIVE_FLOOR))
    IE = IE - 1
  END DO
  
  ! CHECK FOR SUFFICIENT DATA AFTER TRIMMING
  N = IE - IS + 1
  IF (N < 3) THEN
    SLOPE = -3.0_P8
    RETURN
  END IF
  
  ALLOCATE(LOGSP(N), LOG_K(N))
  LOGSP = LOG10(ESPEC(IS:IE))
  
  ! LOGARITHMIC WAVENUMBER SCALE: k' = LOG10(k)
  DO I = 1, N
    LOG_K(I) = LOG10(REAL(K_START + I - 1, P8))
  END DO
  
  ! MAP LOG_K TO X in [-1, +1] FOR LEGENDRE PROJECTION
  XI_MIN = LOG_K(1)
  XI_MAX = LOG_K(N)
  SLOPE = 0.0_P8
  DX = 2.0D0 / (N - 1)  ! INTEGRATION STEP SIZE IN X-SPACE
  
  ! TRAPEZOIDAL RULE WITH P_1(X) = SQRT(3/2) x X
  DO I = 1, N
    XI = LOG_K(I)
    X = -1.0_P8 + 2.0_P8 * (XI - XI_MIN) / (XI_MAX - XI_MIN)  ! MAP k' -> X
    FAC = 1.0_P8
    IF (I == 1 .OR. I == N) FAC = 0.5_P8  ! TRAPEZOIDAL END WEIGHTS
    SLOPE = SLOPE + FAC * LOGSP(I) * DX * SQRT(3.0D0/2.0D0) * X
  END DO
  
  ! CONVERT P1 COEFFICIENT TO SLOPE VIA LEAST-SQUARES INTERPRETATION
  ! THE P1 COEFFICIENT REPRESENTS THE LINEAR TREND IN LOG-LOG SPACE
  ! SCALE BY (ξ_MAX - ξ_MIN) TO GET SLOPE PER LOG10(k) UNIT
  SLOPE = SLOPE * 2.0D0 / (XI_MAX - XI_MIN)
  
  ! CLAMP SLOPE TO PREVENT RUNAWAY FEEDBACK
  SLOPE = MIN(5.0D0, MAX(-15.0D0, SLOPE))
  
  DEALLOCATE(LOGSP, LOG_K)

END FUNCTION SPESLOP

!> =====================================================================
!> @brief APPLIES PD-CONTROL ALGORITHM WITH OVER-DAMPING PROTECTION.
!>
!> @details
!> IMPLEMENTS PROPORTIONAL-DERIVATIVE CONTROL FOR COEFFICIENT ADJUSTMENT:
!>   CONTROL = KP*(CURRENT - PREVIOUS) + KD*CURRENT + OFFSET
!> AT EQUILIBRIUM:
!>   0 = 0 + KD*TARGET + OFFSET  ->  TARGET = - OFFSET/KD
!>
!> WITH OPTIONAL OVER-DAMPING PROTECTION THAT PREVENTS RUNAWAY DAMPING
!> WHEN THE MEASURED SIGNAL BECOMES TOO NEGATIVE (INDICATING SEVERE
!> OVER-DAMPING). THE THRESHOLD IS METRIC-DEPENDENT.
!>
!> CONTROL SIGNAL IS CLAMPED TO [-0.4, +1.0] AFTER SCALING, THEN
!> APPLIED AS: COEFF = (1 + CONTROL) * COEFF WITH BASELINE CONSTRAINT.
!>
!> @param[inout] COEFF             >> COEFFICIENT TO BE ADJUSTED
!> @param[in]    CURRENT           >> CURRENT MEASUREMENT/SIGNAL VALUE
!> @param[in]    PREVIOUS          >> PREVIOUS MEASUREMENT/SIGNAL VALUE
!> @param[in]    BASELINE          >> MINIMUM ALLOWED COEFFICIENT VALUE
!> @param[in]    PARAMS(4)         >> CONTROL PARAMETER ARRAY:
!>                                    PARAMS(1) = KP (PROPORTIONAL GAIN)
!>                                    PARAMS(2) = KD (DERIVATIVE GAIN)
!>                                    PARAMS(3) = OFFSET (CONTROL BIAS)
!>                                    PARAMS(4) = SCALE (OUTPUT SCALING)
!> @param[in]    OVERDAMP_THRESHOLD >> OPTIONAL: THRESHOLD FOR OVER-DAMPING PROTECTION.
!>                                    IF PRESENT, ACTIVATES PROTECTION WHEN BOTH CURRENT
!>                                    AND PREVIOUS VALUES ARE BELOW THIS THRESHOLD.
!> 
!> @note CURRENT PARAMETER VALUES USED BY:
!>   HYP3ADJ (CURVATURE): PARAMS = [2.0, 1.0, 0.05, 0.8], THRESHOLD=-1.0
!>   HYP3ADJ (SLOPE):     PARAMS = [1.5, 0.5, 1.5, 1.0], NO THRESHOLD
!>   HYPADJ (CURVATURE):  PARAMS = [2.0, 1.0, 0.2, 0.8], THRESHOLD=-2.0
!>
!> @author JINGE WANG
!> @date   SEP 2025, OCT 2025 (GENERALIZED THRESHOLD, ARRAY PARAMETERS)
!> =====================================================================
SUBROUTINE PDAJUST(COEFF, CURRENT, PREVIOUS, BASELINE, PARAMS, OVERDAMP_THRESHOLD)
! ======================================================================
  IMPLICIT NONE
  REAL(P8), INTENT(INOUT) :: COEFF
  REAL(P8), INTENT(IN) :: CURRENT, PREVIOUS, BASELINE
  REAL(P8), DIMENSION(4), INTENT(IN) :: PARAMS  ! [KP, KD, OFFSET, SCALE]
  REAL(P8), INTENT(IN), OPTIONAL :: OVERDAMP_THRESHOLD
  
  REAL(P8) :: CONTROL, REDUCTION_STRENGTH, SEVERITY
  REAL(P8) :: KP, KD, OFFSET, SCALE

  KP = PARAMS(1)
  KD = PARAMS(2)
  OFFSET = PARAMS(3)
  SCALE = PARAMS(4)
  CONTROL = KP * (CURRENT - PREVIOUS) + KD * CURRENT + OFFSET
  
  ! OVER-DAMPING PROTECTION: FORCE DAMPING REDUCTION WHEN SEVERELY OVER-DAMPED
  IF (PRESENT(OVERDAMP_THRESHOLD)) THEN    
    IF (CURRENT < OVERDAMP_THRESHOLD .AND. PREVIOUS < OVERDAMP_THRESHOLD) THEN
      ! SEVERITY MEASURES HOW FAR BELOW THRESHOLD WE ARE (0 TO 5+)
      SEVERITY = MIN(5.0D0, ABS(CURRENT - OVERDAMP_THRESHOLD))
      ! BASE REDUCTION OF 10% + UP TO 25% MORE BASED ON SEVERITY
      REDUCTION_STRENGTH = 0.1D0 + 0.05D0 * SEVERITY
      CONTROL = -REDUCTION_STRENGTH
      PRINT '("PDAJUST: SEVERE OVER-DAMPING, FORCING REDUCTION, SIGNAL=", F8.4, " PREV=", F8.4, " THR=", F8.4)', &
             CURRENT, PREVIOUS, OVERDAMP_THRESHOLD
    END IF
  END IF
  
  ! CONTROL = MIN(3.0D0, MAX(-0.5D0, SCALE * CONTROL)) ! ORIGINAL DIMENSIONAL NUP
  CONTROL = MIN(1.0D0, MAX(-0.4D0, SCALE * CONTROL)) ! DIMENSIONLESS NUP  
  COEFF = (1.0_P8 + CONTROL) * COEFF
  IF (COEFF < BASELINE) COEFF = BASELINE

END SUBROUTINE PDAJUST

!> ====================================================================
!> @brief ADJUSTS ISOTROPIC HYPERVISCOSITY USING SPECTRAL FEEDBACK.
!>
!> @details
!> THIS SUBROUTINE IMPLEMENTS AN ISOTROPIC HYPERVISCOSITY ADJUSTMENT
!> SCHEME THAT CONTROLS A SINGLE COEFFICIENT (`NUP`) BASED ON
!> WEIGHTED FEEDBACK FROM ENERGY SPECTRA IN AZIMUTHAL AND AXIAL
!> DIRECTIONS. THIS APPROACH ASSUMES UNIFORM DISSIPATION IN ALL
!> SPATIAL DIRECTIONS.
!>
!> THE ADJUSTMENT PROCESS:
!> 1. **SPECTRAL ANALYSIS**: COMPUTES ENERGY SPECTRA FOR AZIMUTHAL
!>    (`M`) AND AXIAL (`K`) DIRECTIONS USING `ENEMON`.
!> 2. **CURVATURE CALCULATION**: MEASURES SPECTRAL CURVATURE IN BOTH
!>    DIRECTIONS USING `SPECURV` TO DETECT ENERGY BOTTLENECKS.
!> 3. **WEIGHTED AVERAGING**: COMBINES AZIMUTHAL AND AXIAL
!>    CURVATURES USING A 3:1 WEIGHTING SCHEME THAT FAVORS THE MORE
!>    UNSTABLE DIRECTION.
!> 4. **PD CONTROL**: APPLIES SINGLE PD CONTROLLER WITH PARAMETERS
!>    KP=2.0, KD=1.0, OFFSET=0.2, SCALE=1.5.
!>
!> @note THIS IS THE ISOTROPIC ALTERNATIVE TO `HYP3ADJ`, WHICH USES
!> 3 SEPARATE DIRECTIONAL CONTROL KNOBS (NU_R, NU_T, NU_X) AND UP
!> TO 6 TOTAL KNOBS WHEN DENSITY FIELD B IS PRESENT (ADDING KAPPA_R,
!> KAPPA_T, KAPPA_X).
!>
!> **CONTROL PARAMETERS** (LEGACY REFERENCE):
!> ORIGINALLY USED: KP=2.0, KD=1.0, OFFSET=0.2, SCALE=1.5, THRESHOLD=-2.0
!>
!> @param[in]    PSI >> TOROIDAL SCALAR FIELD IN FFF_SPACE
!> @param[in]    CHI >> POLOIDAL SCALAR FIELD IN FFF_SPACE
!> @param[inout] NUP >> ISOTROPIC HYPERVISCOSITY COEFFICIENT
!>
!> @author JINGE WANG
!> @date   (PRE-2024), OCT 2025 (PARAMETER ARRAY REFACTOR)
!> ====================================================================
SUBROUTINE HYPADJ(PSI,CHI,NUP)
! ======================================================================
  IMPLICIT NONE
  TYPE(SCALAR):: PSI,CHI
  REAL(P8):: NUP

  REAL(P8),DIMENSION(:),ALLOCATABLE:: EM,EK
  REAL(P8):: SUMM,SUMK,SUM,SUMO
  REAL(P8), DIMENSION(4) :: CURV_PARAMS  ! [KP, KD, OFFSET, SCALE]

  ! SET CONTROL PARAMETERS FOR CURVATURE CONTROLLER
  CURV_PARAMS = [2.0_P8, 1.0_P8, 0.2_P8, 0.8_P8]

  ALLOCATE( EM(NTCHOP), EK(NXCHOP) )

  CALL CHOPSET(2)
  CALL ENEMON(PSI,CHI,EM,EK)
  CALL CHOPSET(-2)

  ! COMPUTE SPECTRAL CURVATURES USING REUSABLE FUNCTION
  SUMM = SPECURV(EM(1:SIZE(EM)-2))  ! EXCLUDE LAST 2 ELEMENTS FOR AZIMUTHAL
  SUMK = SPECURV(EK)                ! USE FULL AXIAL SPECTRUM

  ! INITIALIZATION
  IF(VISC%NUPB .LT. 0.0D0) THEN
    VISC%CURVMO=SUMM
    VISC%CURVKO=SUMK
    VISC%NUPB = 0.2 !/(1.5D0*NRCHOP**2/ELL**2)**(VISC%P/2)
  ENDIF

  ! WEIGHTED AVERAGE
  IF(SUMM.GT.SUMK) THEN
    SUMO = (3*VISC%CURVMO+VISC%CURVKO)/4
    SUM  = (3*SUMM+SUMK)/4
  ELSE
    SUMO = (VISC%CURVMO+3*VISC%CURVKO)/4
    SUM  = (SUMM+3*SUMK)/4
  ENDIF

  CALL PDAJUST(NUP, SUM, SUMO, VISC%NUPB, CURV_PARAMS, -2.0_P8)

  IF (MPI_RANK.EQ.0) WRITE(6,60) TIM%T,NUP,SUMM,SUMK
60   FORMAT('HYPADJ:T= ',1PE10.3,' NUP= ',1PE10.3,' SUMM= ', &
            1PE10.3, ' SUMK= ',1PE10.3)
  VISC%CURVMO=SUMM
  VISC%CURVKO=SUMK

  DEALLOCATE( EM, EK )

  RETURN
END SUBROUTINE HYPADJ

!> ====================================================================
!> @brief ADJUSTS DIRECTIONAL HYPERVISCOSITY USING DUAL-CONTROLLER
!>        SPECTRAL FEEDBACK (CURVATURE + SLOPE).
!>
!> @details
!> THIS SUBROUTINE IMPLEMENTS A DIRECTIONAL HYPERVISCOSITY ADJUSTMENT
!> SCHEME THAT CONTROLS SEPARATE COEFFICIENTS FOR RADIAL (`NU_R`),
!> AZIMUTHAL (`NU_T`), AND AXIAL (`NU_X`) DIRECTIONS BASED ON ENERGY
!> SPECTRA. THIS APPROACH ALLOWS INDEPENDENT DISSIPATION TUNING IN
!> EACH SPATIAL DIRECTION.
!>
!> **DUAL-CONTROLLER ARCHITECTURE** (NEW AS OF OCT 2025):
!> 1. **CURVATURE CONTROLLER**: USES `SPECURV` (P2 LEGENDRE, LINEAR-k)
!>    TO DETECT ENERGY PILE-UP AT HIGH WAVENUMBERS.
!>    • TARGET: CURV ≈ -0.05 (NEAR-ZERO IN DISSIPATIVE TAIL)
!>    • PARAMETERS: [KP, KD, OFFSET, SCALE] = [2.0, 1.0, 0.05, 0.8]
!>    • OVER-DAMPING THRESHOLD: -1.0
!> 2. **SLOPE CONTROLLER**: USES `SPESLOP` (P1 LEGENDRE, LOG-k)
!>    TO ENFORCE HEALTHY INERTIAL-RANGE SLOPE a ~ -5/3.
!>    • TARGET: a ≈ -3.0 (ADEQUATE DISSIPATION RATE)
!>    • PARAMETERS: [KP, KD, OFFSET, SCALE] = [1.5, 0.5, 1.5, 1.0]
!>    • NO OVER-DAMPING THRESHOLD (SLOPE CAN BE LEGITIMATELY VERY NEGATIVE)
!>
!> @note THIS IS THE DIRECTIONAL ALTERNATIVE TO `HYPADJ`, WHICH
!> USES A SINGLE ISOTROPIC CONTROL KNOB (`NUP`) WITH WEIGHTED
!> FEEDBACK FROM BOTH SPECTRAL DIRECTIONS.
!>
!> @param[in]    PSI >> TOROIDAL SCALAR FIELD IN FFF_SPACE
!> @param[in]    CHI >> POLOIDAL SCALAR FIELD IN FFF_SPACE
!> @param[in]    B   >> OPTIONAL DENSITY FIELD IN FFF_SPACE
!>
!> @author JINGE WANG
!> @date   SEP 2025, ENHANCED OCT 2025 (DUAL-CONTROLLER)
!> ====================================================================
SUBROUTINE HYP3ADJ(PSI, CHI, B)
! ======================================================================
  IMPLICIT NONE
  TYPE(SCALAR), INTENT(IN) :: PSI, CHI
  TYPE(SCALAR), OPTIONAL, INTENT(IN) :: B

  REAL(P8), DIMENSION(:), ALLOCATABLE :: EM, EK
  REAL(P8) :: KMIN_SQ
  REAL(P8) :: SUM_M_CURVE, SUM_K_CURVE, SUM_R_CURVE, SUM_R_CURVE_O
  REAL(P8) :: SUM_M_SLOPE, SUM_K_SLOPE, SUM_R_SLOPE, SUM_R_SLOPE_O
  REAL(P8) :: NU_R_CURV, NU_T_CURV, NU_X_CURV  ! CURVATURE-BASED ADJUSTMENTS
  REAL(P8) :: NU_R_SLOP, NU_T_SLOP, NU_X_SLOP  ! SLOPE-BASED ADJUSTMENTS
  REAL(P8), DIMENSION(:, :), ALLOCATABLE :: PEMK
  REAL(P8) :: BASELINE_NUP = 0.8D0
  REAL(P8), DIMENSION(4) :: CURV_PARAMS, SLOPE_PARAMS  ! CONTROL PARAMETER ARRAYS

  ! SET CONTROL PARAMETERS FOR DUAL CONTROLLERS
  ! CURVATURE: [KP, KD, OFFSET, SCALE] = [2.0, 1.0, 0.05, 0.8]
  ! TARGET = -OFFSET/KD = -0.05/1.0 = -0.05
  CURV_PARAMS = [2.0_P8, 1.0_P8, 0.05_P8, 0.8_P8]
  
  ! SLOPE: [KP, KD, OFFSET, SCALE] = [1.5, 0.5, 1.5, 1.0]
  ! TARGET = -OFFSET/KD = -1.5/0.5 = -3.0
  SLOPE_PARAMS = [1.5_P8, 0.5_P8, 1.5_P8, 1.0_P8]

  ALLOCATE(EM(NTCHOP), EK(NXCHOP))

  ! COMPUTE KINETIC ENERGY SPECTRA (VELOCITY FIELD)
  CALL CHOPSET(2)
  CALL ENEMON(PSI, CHI, EM, EK)
  CALL CHOPSET(-2)
  
  ! CALCULATE DUAL METRICS: CURVATURE AND SLOPE
  SUM_M_CURVE = SPECURV(EM(1:SIZE(EM)-2), USE_RATIO=1.0D0/4.0D0)
  SUM_K_CURVE = SPECURV(EK, USE_RATIO=1.0D0/4.0D0)
  SUM_M_SLOPE = SPESLOP(EM(1:SIZE(EM)-2))
  SUM_K_SLOPE = SPESLOP(EK)

  ! --- INITIALIZATION ON FIRST CALL ---
  IF (VISC%NUPB < 0.0D0) THEN
    VISC%CURVMO = SUM_M_CURVE
    VISC%CURVKO = SUM_K_CURVE
    VISC%SLOPMO = SUM_M_SLOPE
    VISC%SLOPKO = SUM_K_SLOPE
    KMIN_SQ = MIN(REAL(M(NTCHOP)**2, P8), AK(1, NXCHOP)**2, (1.5D0**2 * NRCHOP**2 / ELL**2))
    VISC%NUPB = BASELINE_NUP ! / KMIN_SQ**(VISC%P / 2.0_P8)
  ENDIF

  ! CURVATURE CONTROLLER (NU_T, NU_X)
  NU_T_CURV = VISC%NUP_T
  NU_X_CURV = VISC%NUP_X
  CALL PDAJUST(NU_T_CURV, SUM_M_CURVE, VISC%CURVMO, VISC%NUPB, CURV_PARAMS, -1.0_P8)
  CALL PDAJUST(NU_X_CURV, SUM_K_CURVE, VISC%CURVKO, VISC%NUPB, CURV_PARAMS, -1.0_P8)

  ! SLOPE CONTROLLER (NU_T, NU_X)
  NU_T_SLOP = VISC%NUP_T
  NU_X_SLOP = VISC%NUP_X
  CALL PDAJUST(NU_T_SLOP, SUM_M_SLOPE, VISC%SLOPMO, VISC%NUPB, SLOPE_PARAMS)
  CALL PDAJUST(NU_X_SLOP, SUM_K_SLOPE, VISC%SLOPKO, VISC%NUPB, SLOPE_PARAMS)

  VISC%NUP_T = MAX(NU_T_CURV, NU_T_SLOP)
  VISC%NUP_X = MAX(NU_X_CURV, NU_X_SLOP)

  ! RADIAL DIRECTION (WEIGHTED AVERAGE OF M AND K METRICS)
  ! CURVATURE-BASED RADIAL ADJUSTMENT
  IF (SUM_M_CURVE > SUM_K_CURVE) THEN
    SUM_R_CURVE_O = (3.0_P8 * VISC%CURVMO + VISC%CURVKO) / 4.0_P8
    SUM_R_CURVE   = (3.0_P8 * SUM_M_CURVE + SUM_K_CURVE) / 4.0_P8
  ELSE
    SUM_R_CURVE_O = (VISC%CURVMO + 3.0_P8 * VISC%CURVKO) / 4.0_P8
    SUM_R_CURVE   = (SUM_M_CURVE + 3.0_P8 * SUM_K_CURVE) / 4.0_P8
  ENDIF
  NU_R_CURV = VISC%NUP_R
  CALL PDAJUST(NU_R_CURV, SUM_R_CURVE, SUM_R_CURVE_O, VISC%NUPB, CURV_PARAMS, -1.0_P8)
  ! SLOPE-BASED RADIAL ADJUSTMENT
  IF (SUM_M_SLOPE > SUM_K_SLOPE) THEN
    SUM_R_SLOPE_O = (3.0_P8 * VISC%SLOPMO + VISC%SLOPKO) / 4.0_P8
    SUM_R_SLOPE   = (3.0_P8 * SUM_M_SLOPE + SUM_K_SLOPE) / 4.0_P8
  ELSE
    SUM_R_SLOPE_O = (VISC%SLOPMO + 3.0_P8 * VISC%SLOPKO) / 4.0_P8
    SUM_R_SLOPE   = (SUM_M_SLOPE + 3.0_P8 * SUM_K_SLOPE) / 4.0_P8
  ENDIF
  NU_R_SLOP = VISC%NUP_R
  CALL PDAJUST(NU_R_SLOP, SUM_R_SLOPE, SUM_R_SLOPE_O, VISC%NUPB, SLOPE_PARAMS)
  VISC%NUP_R = MIN(MAX(NU_R_CURV, NU_R_SLOP), 2.0D0)

  IF (MPI_RANK == 0) THEN
    WRITE(6, 60) TIM%T, VISC%NUP_R, VISC%NUP_T, VISC%NUP_X, &
                 SUM_M_CURVE, SUM_K_CURVE, SUM_M_SLOPE, SUM_K_SLOPE
60  FORMAT('HYP3ADJ: T=',1PE10.3,' R/T/X=',3(1PE9.2),' CURV=',2(1PE9.2),' SLOP=',2(1PE9.2))
  END IF

  ! UPDATE HISTORY FOR NEXT TIMESTEP
  VISC%CURVMO = SUM_M_CURVE
  VISC%CURVKO = SUM_K_CURVE
  VISC%SLOPMO = SUM_M_SLOPE
  VISC%SLOPKO = SUM_K_SLOPE

  ! DENSITY FIELD HYPERDIFFUSIVITY (OPTIONAL)
  IF (PRESENT(B)) THEN
    ALLOCATE(PEMK(NTCHOP,NXCHOP))
    PEMK = CALC_BOUSSI_PE(B)
    
    ! CALCULATE DUAL METRICS FROM PE SPECTRUM
    SUM_M_CURVE = SPECURV(SUM(PEMK(1:NTCHOP-2,:), DIM=2), USE_RATIO=1.0D0/4.0D0)
    SUM_K_CURVE = SPECURV(SUM(PEMK(:,:), DIM=1), USE_RATIO=1.0D0/4.0D0)
    SUM_M_SLOPE = SPESLOP(SUM(PEMK(1:NTCHOP-2,:), DIM=2))
    SUM_K_SLOPE = SPESLOP(SUM(PEMK(:,:), DIM=1))

    IF (VISC%KAPPAPB < 0.0D0) THEN
      VISC%PCURVMO = SUM_M_CURVE
      VISC%PCURVKO = SUM_K_CURVE
      VISC%PSLOPMO = SUM_M_SLOPE
      VISC%PSLOPKO = SUM_K_SLOPE
      VISC%KAPPAPB = VISC%NUPB
    ENDIF

    ! CURVATURE CONTROLLER FOR KAPPA
    NU_T_CURV = VISC%KAPPAP_T
    NU_X_CURV = VISC%KAPPAP_X
    CALL PDAJUST(NU_T_CURV, SUM_M_CURVE, VISC%PCURVMO, VISC%KAPPAPB, CURV_PARAMS, -1.0_P8)
    CALL PDAJUST(NU_X_CURV, SUM_K_CURVE, VISC%PCURVKO, VISC%KAPPAPB, CURV_PARAMS, -1.0_P8)

    ! SLOPE CONTROLLER FOR KAPPA
    NU_T_SLOP = VISC%KAPPAP_T
    NU_X_SLOP = VISC%KAPPAP_X
    CALL PDAJUST(NU_T_SLOP, SUM_M_SLOPE, VISC%PSLOPMO, VISC%KAPPAPB, SLOPE_PARAMS)
    CALL PDAJUST(NU_X_SLOP, SUM_K_SLOPE, VISC%PSLOPKO, VISC%KAPPAPB, SLOPE_PARAMS)

    ! MAXIMUM SELECTION FOR KAPPA_T, KAPPA_X
    VISC%KAPPAP_T = MAX(NU_T_CURV, NU_T_SLOP)
    VISC%KAPPAP_X = MAX(NU_X_CURV, NU_X_SLOP)

    ! RADIAL DIRECTION FOR KAPPA (CURVATURE)
    IF (SUM_M_CURVE > SUM_K_CURVE) THEN
      SUM_R_CURVE_O = (3.0_P8 * VISC%PCURVMO + VISC%PCURVKO) / 4.0_P8
      SUM_R_CURVE   = (3.0_P8 * SUM_M_CURVE + SUM_K_CURVE) / 4.0_P8
    ELSE
      SUM_R_CURVE_O = (VISC%PCURVMO + 3.0_P8 * VISC%PCURVKO) / 4.0_P8
      SUM_R_CURVE   = (SUM_M_CURVE + 3.0_P8 * SUM_K_CURVE) / 4.0_P8
    ENDIF
    NU_R_CURV = VISC%KAPPAP_R
    CALL PDAJUST(NU_R_CURV, SUM_R_CURVE, SUM_R_CURVE_O, VISC%KAPPAPB, CURV_PARAMS, -1.0_P8)
    
    ! RADIAL DIRECTION FOR KAPPA (SLOPE)
    IF (SUM_M_SLOPE > SUM_K_SLOPE) THEN
      SUM_R_SLOPE_O = (3.0_P8 * VISC%PSLOPMO + VISC%PSLOPKO) / 4.0_P8
      SUM_R_SLOPE   = (3.0_P8 * SUM_M_SLOPE + SUM_K_SLOPE) / 4.0_P8
    ELSE
      SUM_R_SLOPE_O = (VISC%PSLOPMO + 3.0_P8 * VISC%PSLOPKO) / 4.0_P8
      SUM_R_SLOPE   = (SUM_M_SLOPE + 3.0_P8 * SUM_K_SLOPE) / 4.0_P8
    ENDIF
    NU_R_SLOP = VISC%KAPPAP_R
    CALL PDAJUST(NU_R_SLOP, SUM_R_SLOPE, SUM_R_SLOPE_O, VISC%KAPPAPB, SLOPE_PARAMS)
    VISC%KAPPAP_R = MIN(MAX(NU_R_CURV, NU_R_SLOP), 2.0D0)

    IF (MPI_RANK == 0) THEN
      WRITE(6, 61) TIM%T, VISC%KAPPAP_R, VISC%KAPPAP_T, VISC%KAPPAP_X, &
                   SUM_M_CURVE, SUM_K_CURVE, SUM_M_SLOPE, SUM_K_SLOPE
  61  FORMAT('HYP3ADJ(K): T=',1PE10.3,' R/T/X=',3(1PE9.2),' CURV=',2(1PE9.2),' SLOP=',2(1PE9.2))
      ! DIAGNOSTIC: CHECK FOR SUSPICIOUS VALUES RELATIVE TO INPUT VALUE
      IF (VISC%KAPPAP_R > 100.0_P8 * BSNSQ%KAPPAP .OR. &
          VISC%KAPPAP_T > 100.0_P8 * BSNSQ%KAPPAP .OR. &
          VISC%KAPPAP_X > 100.0_P8 * BSNSQ%KAPPAP) THEN
        WRITE(6, 62) MINVAL(PEMK), MAXVAL(PEMK), SUM(PEMK)/SIZE(PEMK)
  62    FORMAT('  ** KAPPA RUNAWAY WARNING: PE_MIN=',1PE10.3,' PE_MAX=',1PE10.3,' PE_AVG=',1PE10.3)
      END IF
    END IF

    ! UPDATE HISTORY FOR NEXT TIMESTEP
    VISC%PCURVMO = SUM_M_CURVE
    VISC%PCURVKO = SUM_K_CURVE
    VISC%PSLOPMO = SUM_M_SLOPE
    VISC%PSLOPKO = SUM_K_SLOPE

    DEALLOCATE(PEMK)

  ENDIF

  DEALLOCATE(EM, EK)

  RETURN
END SUBROUTINE HYP3ADJ

!> =====================================================================
!> @brief SETS UP HYPERVISCOSITY DAMPING FACTORS (LEGACY METHOD).
!>
!> @details
!> THIS SUBROUTINE CALCULATES THE HYPERVISCOSITY DAMPING FACTORS FOR
!> THE RADIAL (R), AZIMUTHAL (T), AND AXIAL (X) DIRECTIONS. THESE
!> FACTORS ARE APPLIED IN `HYPERV3` TO SELECTIVELY DAMP HIGH-WAVENUMBER
!> MODES AND ENSURE NUMERICAL STABILITY.
!>
!> THE METHOD FOLLOWS THESE STEPS:
!> 1. **DYNAMIC CUTOFF**: IT DETERMINES AN UPPER WAVENUMBER LIMIT
!>    (`NT_UP`, `NX_UP`) FOR "PHYSICAL" MODES BY INSPECTING THE
!>    DOMINANT WAVENUMBERS STORED IN `MONITORDATA%MK`.
!> 2. **FILTER CREATION**: IT CONSTRUCTS SMOOTH `TANH`-BASED FILTERS
!>    FOR EACH DIRECTION. THE FILTER PARAMETERS (CENTER, STEEPNESS)
!>    ARE HARD-CODED WITH "MAGIC NUMBERS".
!> 3. **COEFFICIENT CALCULATION**: IT COMPUTES HYPERVISCOSITY
!>    COEFFICIENTS (`NU_R`, `NU_T`, `NU_X`) TO NORMALIZE THE DAMPING,
!>    ENSURING THE HIGHEST MODES DECAY AT A CONTROLLED RATE.
!> 4. **DAMPING VECTORS**: IT CALCULATES THE FINAL EXPONENTIAL DAMPING
!>    FACTORS AND STORES THEM IN `VISC%HYPERV_R`, `VISC%HYPERV_T`, AND
!>    `VISC%HYPERV_X`.
!>
!> THE ROUTINE ALSO WRITES THE RESULTING DAMPING VECTORS TO
!> `HYPERV.DAT` FOR DIAGNOSTIC PURPOSES.
!>
!> @note THIS IS A LEGACY IMPLEMENTATION WITH HARD-CODED PARAMETERS.
!> THE `HYP3SET` ROUTINE, WHICH USES THE MORE FLEXIBLE `HYP3MASK`
!> UTILITY, IS THE MODERN AND PREFERRED APPROACH. THIS ROUTINE IS
!> KEPT FOR REPRODUCIBILITY OF OLDER SIMULATION RESULTS.
!>
!> @author JINGE WANG
!> @date   (PRE-2024)
!> =====================================================================
SUBROUTINE HYP3SET_OLD()
! ======================================================================
  IMPLICIT NONE

  REAL(P8) :: NU_R, NU_T, NU_X
  INTEGER :: NT_UP, NX_UP

  REAL(P8) :: FACTOR_NU
  INTEGER :: II, JJ
  INTEGER :: FACTOR_UP, MONITOR_K(3)
  
  REAL(P8) :: FACTOR_R, FACTOR_T, FACTOR_X
  REAL(P8) :: INDEX_R(NRCHOP), INDEX_T(NTCHOPDIM), INDEX_X(NXCHOPDIM)
  REAL(P8) :: FILTER_R(NRCHOP), FILTER_T(NTCHOPDIM), FILTER_X(NXCHOPDIM)

  FACTOR_NU = 2.D0

  FACTOR_R = 1.D0
  FACTOR_T = 0.8
  FACTOR_X = 1.D0

  ! IF PERTURBATION/DISTURBANCE SIZE IS 0.1, ITS FACTOR_UP-TH HARMONICS
  ! WILL GET BELOW MACHINE ROUND-OFF ERROR
  FACTOR_UP = 24 ! DP
  NT_UP = MIN(FACTOR_UP*MAX(MAXVAL(MONITORDATA%MK(1:3,1)),1),NTCHOP-1)
  DO II = 1,3
    MONITOR_K(II) = MONITORDATA%MK(II,2)
    IF (MONITOR_K(II).GT.NXCHOP) MONITOR_K(II) = MONITOR_K(II) + 1 - 2*NXCHOP
    MONITOR_K(II) = ABS(MONITOR_K(II))
  ENDDO
  ! NX_UP = MIN(FACTOR_UP*MAX(MAXVAL(ABS(MONITORDATA%MK(1:3,2))),1),NXCHOP-1)
  NX_UP = MIN(FACTOR_UP*MAX(MAXVAL(MONITOR_K),1),NXCHOP-1)

  ! CREATE TANH FILTERS
  ! R: CENTER AT 1/2*NRCHOP WIDTH NRCHOP/4
  INDEX_R = (/(II, II=1,NRCHOP)/)
  FILTER_R = 0.5*(TANH((INDEX_R/REAL(NRCHOP)-1.D0/2.D0)*4.D0)+1.D0)
  ! T: CENTER AT 2/3*NT_UP WIDTH NT_UP/4
  INDEX_T = (/(II, II=0,NTCHOPDIM-1)/)
  FILTER_T = 0.5*(TANH((INDEX_T/REAL(NT_UP)-1.D0/2.D0)*5.D0)+1.D0)
  ! X: CENTER AT 2/3*NX_UP WIDTH NX_UP/4
  DO II=1,NXCHOPDIM
    INDEX_X(II) = II-1
    IF(II.GT.NXCHOP) THEN
        INDEX_X(II)=ABS(-(NXCHOPDIM-II+1))
    ENDIF
  ENDDO
  FILTER_X = 0.5*(TANH((INDEX_X/REAL(NX_UP)-1.D0/2.D0)*8.D0)+1.D0)

  ! FORCE THE LAST MODE TO DECAY AT EXP(-1*DT) WHILE ALSO USING TANH TO
  ! PREVENT CHANGES TO THE INTERESTED MODES
  NU_R = FACTOR_NU*(FACTOR_R*FILTER_R(NRCHOP))**(-VISC%P) 
  NU_T = FACTOR_NU*(FACTOR_T*FILTER_T(NTCHOPDIM))**(-VISC%P+2)
  NU_X = FACTOR_NU*(FACTOR_X*FILTER_X(NXCHOP))**(-VISC%P+2)

  ! CREATE HYPERV VECTORS
  ALLOCATE(VISC%HYPERV_R(NRCHOP,NTCHOPDIM), VISC%HYPERV_T(NTCHOPDIM), VISC%HYPERV_X(NXCHOPDIM))
  DO II=1,NTCHOPDIM
    VISC%HYPERV_R(:,II) = EXP(-(NU_R*TIM%DT)*(FILTER_R*INDEX_R/NRCHOP)**VISC%P)
  ENDDO
  VISC%HYPERV_T = EXP(-(NU_T*TIM%DT)*(FILTER_T*INDEX_T/NTCHOP)**(VISC%P-2))
  VISC%HYPERV_X = EXP(-(NU_X*TIM%DT)*(FILTER_X*INDEX_X/NXCHOP)**(VISC%P-2))

  ! SAVE HYPER VECTORS
  IF (MPI_RANK.EQ.0) THEN
    open(UNIT=888,FILE=TRIM(ADJUSTL(FILES%SAVEDIR))//'hyperv.dat',STATUS='UNKNOWN',ACTION='WRITE',POSITION='APPEND')
    ! write(888,518) NU_R, FILTER_R
    ! write(888,518) NU_T, FILTER_T
    ! write(888,518) NU_X, FILTER_X
    write(888,518) NU_R, VISC%HYPERV_R
    write(888,518) NU_T, VISC%HYPERV_T
    write(888,518) NU_X, VISC%HYPERV_X
    close(888)
  518 FORMAT((E23.16),*(' ,',E23.16))
  ENDIF

  RETURN
END SUBROUTINE HYP3SET_OLD

!> =====================================================================
!> @brief SETS UP HYPERVISCOSITY DAMPING FACTORS (MODERN METHOD).
!>
!> @details
!> THIS SUBROUTINE CALCULATES THE 1D HYPERVISCOSITY DAMPING ARRAYS
!> FOR THE RADIAL (R), AZIMUTHAL (T), AND AXIAL (X) DIRECTIONS.
!> IT USES THE `HYP3MASK` UTILITY TO CREATE SMOOTH, SCALE-SELECTIVE
!> FILTERS. THE FINAL DAMPING FACTORS ARE STORED IN THE GLOBAL
!> `VISC` TYPE FOR USE IN THE `HYPERV3` SUBROUTINE.
!>
!> THE DAMPING FACTOR FOR EACH MODE IS CALCULATED AS:
!> `EXP(-DT * MASK * NU * (K**2)**(P/2))`
!>
!> THIS ROUTINE IS THE PREFERRED METHOD FOR SETTING UP HYPERVISCOSITY
!> DUE TO ITS FLEXIBILITY COMPARED TO THE LEGACY `HYP3SET_OLD` ROUTINE.
!>
!> @param[in] NU_R HYPERVISCOSITY COEFFICIENT FOR RADIAL DIRECTION.
!> @param[in] NU_T HYPERVISCOSITY COEFFICIENT FOR AZIMUTHAL DIRECTION.
!> @param[in] NU_X HYPERVISCOSITY COEFFICIENT FOR AXIAL DIRECTION.
!>
!> @author JINGE WANG
!> @date   SEP 2025
!> =====================================================================
SUBROUTINE HYP3SET( NU_R, NU_T, NU_X, HYPER_R, HYPER_T, HYPER_X )
! ======================================================================
  IMPLICIT NONE
  REAL(P8), INTENT(IN) :: NU_R, NU_T, NU_X
  REAL(P8), DIMENSION(:,:), ALLOCATABLE, INTENT(OUT) :: HYPER_R
  REAL(P8), DIMENSION(:), ALLOCATABLE, INTENT(OUT) :: HYPER_T, HYPER_X
  
  ! LOCAL VARIABLES
  INTEGER :: NN, MM, KK
  REAL(P8) :: K2MAX_R, K2MAX_T, K2MAX_X
  
  ! --- CREATE THE 1D DEALIASING MASKS FOR EACH DIRECTION ---
  IF (.NOT. ALLOCATED(VISC%MASK_R)) THEN
    ALLOCATE(VISC%MASK_R(NRCHOP,NTCHOPDIM), VISC%MASK_T(NTCHOPDIM), VISC%MASK_X(NXCHOPDIM))
    DO MM = 1, NTCHOPDIM
      ! CALL HYP3MASK([(REAL(NN-1, P8), NN=1, NRCHOPS(MM))], VISC%MASK_R(:,MM), RATIO = 0.5D0, STEEPNESS = 2.5D0)
      CALL HYP3MASK([(REAL(NN-1, P8), NN=1, NRCHOPS(MM))], VISC%MASK_R(:,MM), RATIO = 0.5D0, STEEPNESS = 2.0D0)
    END DO
    CALL HYP3MASK(REAL(M, P8), VISC%MASK_T, STEEPNESS = 2.0D0)
    CALL HYP3MASK(ABS(AK(1,:)), VISC%MASK_X, STEEPNESS = 2.0D0)
  END IF

  ! --- CALCULATE THE 1D FILTER ARRAYS ---
  IF (.NOT. ALLOCATED(HYPER_R)) THEN
    ALLOCATE(HYPER_R(NRCHOP,NTCHOPDIM), HYPER_T(NTCHOPDIM), HYPER_X(NXCHOPDIM))
  END IF
  
  ! --- OLD IMPLEMENTATION: USE ABSOLUTE K VALUES ---
  ! DO MM = 1, NTCHOPDIM
  !   HYPER_T(MM) = EXP(-TIM%DT * VISC%MASK_T(MM) * NU_T * (REAL(M(MM)**2,P8))**(VISC%P/2))
  !   DO NN = 1, NRCHOP
  !     ! HYPER_R(NN,MM) = EXP(-TIM%DT * VISC%MASK_R(NN,MM) * NU_R * (1.5D0*REAL((NN-1)*NN,P8)/ELL2)**(VISC%P/2))
  !     HYPER_R(NN,MM) = EXP(-TIM%DT * VISC%MASK_R(NN,MM) * NU_R * (1.5D0**2*REAL((NN-1)*NN,P8)/ELL2)**(VISC%P/2))
  !   END DO
  ! ENDDO
  ! DO KK = 1, NXCHOPDIM
  !   HYPER_X(KK) = EXP(-TIM%DT * VISC%MASK_X(KK) * NU_X * (AK(1,KK)**2)**(VISC%P/2))
  ! END DO

  ! --- NEW IMPLEMENTATION: USE NORMALIZED K VALUES AND NU ---
  K2MAX_R = (1.5D0**2 * REAL((NRCHOP-1)*NRCHOP, P8) / ELL2)
  K2MAX_T = REAL(MAXVAL(M(:)**2), P8)
  K2MAX_X = REAL(MAXVAL(AK(1,:)**2), P8)
  DO MM = 1, NTCHOPDIM
    HYPER_T(MM) = EXP(-NU_T * VISC%MASK_T(MM) * (REAL(M(MM)**2,P8) / K2MAX_T)**(VISC%P/2))
    DO NN = 1, NRCHOP
      HYPER_R(NN,MM) = EXP(-NU_R * VISC%MASK_R(NN,MM) * (1.5D0**2*REAL((NN-1)*NN,P8)/ELL2 / K2MAX_R)**(VISC%P/2))
    END DO
  ENDDO
  DO KK = 1, NXCHOPDIM
    HYPER_X(KK) = EXP(-NU_X * VISC%MASK_X(KK) * (AK(1,KK)**2 / K2MAX_X)**(VISC%P/2))
  END DO

  IF (MPI_RANK.EQ.0) THEN
    open(UNIT=888,FILE=TRIM(ADJUSTL(FILES%SAVEDIR))//'hyperv.dat',STATUS='UNKNOWN',ACTION='WRITE',POSITION='APPEND')
    write(888,519) TIM%T, NU_R, HYPER_R(:,1) ! ONLY SAVE THE M = 0 SLICE
    write(888,519) TIM%T, NU_T, HYPER_T
    write(888,519) TIM%T, NU_X, HYPER_X(1:NXCHOP)
    close(888)
  519 FORMAT(2(E23.16,','),*(E23.16,','))
  ENDIF  
END SUBROUTINE HYP3SET

!> =====================================================================
!> @brief GENERATE A SMOOTH MASK FOR HYPERVISCOSITY FILTERING
!>
!> THIS SUBROUTINE CREATES A SMOOTH TRANSITION MASK THAT IS ZERO FOR
!> WAVENUMBERS BELOW A THRESHOLD AND SMOOTHLY TRANSITIONS TO 1 FOR
!> HIGHER WAVENUMBERS USING A HYPERBOLIC TANGENT FUNCTION.
!>
!> @param[in] K_VALS ARRAY OF WAVENUMBER VALUES TO GENERATE MASK FOR
!> @param[out] K_MASK ARRAY OF MASK VALUES (0 TO 1) FOR K_VALS
!> @param[in] RATIO OPTIONAL "SAFE" RATIO FOR FILTERING THRESHOLD
!>                 (DEFAULT: 2/3)
!>
!> @details
!> MASK FUNCTION USES FULL TANH PROFILE FOR SMOOTH FILTERING:
!> - MAPS K/K_MAX FROM [RATIO, 1] TO X_RAMP FROM [0, 1]
!> - APPLIES Y_RAMP = A*(2*X_RAMP - 1) TO CENTER TANH AT X_RAMP=0.5
!> - MASK = (TANH(Y_RAMP) + TANH(A)) / (2*TANH(A))
!> - RESULT: SMOOTH S-CURVE FROM 0 TO 1 OVER THE TRANSITION REGION
!>
!> NOTES:
!> - FULL TANH PROVIDES SYMMETRIC, SMOOTH TRANSITION
!> - STEEPNESS PARAMETER A CONTROLS TRANSITION SHARPNESS
!> - SAFETY CHECK PREVENTS DIVISION BY ZERO IF K_MAX IS SMALL
!>
!> @author JINGE WANG
!> @date SEP 2025
!> =====================================================================
SUBROUTINE HYP3MASK(K_VALS, K_MASK, RATIO, STEEPNESS)
!=======================================================================
  IMPLICIT NONE
  REAL(P8), INTENT(IN)    :: K_VALS(:)
  REAL(P8), INTENT(INOUT) :: K_MASK(:)
  REAL(P8), INTENT(IN), OPTIONAL :: RATIO, STEEPNESS
  
  REAL(P8) :: EFFECTIVE_RATIO, EFFECTIVE_STEEPNESS
  REAL(P8) :: K_MAX, K_NORM, X_RAMP, Y_RAMP, TANH_A
  INTEGER  :: I

  IF (PRESENT(RATIO)) THEN
    EFFECTIVE_RATIO = RATIO
  ELSE
    EFFECTIVE_RATIO = 2.0D0 / 3.0D0
  END IF

  IF (PRESENT(STEEPNESS)) THEN
    EFFECTIVE_STEEPNESS = STEEPNESS
  ELSE
    EFFECTIVE_STEEPNESS = 3.0D0
  END IF
  
  K_MAX = MAXVAL(K_VALS)
  IF (K_MAX < 1.0D-12) K_MAX = 1.0D0 ! AVOID DIVISION BY ZERO

  K_MASK = 1.0D0
  TANH_A = TANH(EFFECTIVE_STEEPNESS)
  DO I = 1, SIZE(K_VALS)
    K_NORM = K_VALS(I) / K_MAX
    
    IF (K_NORM < EFFECTIVE_RATIO) THEN
      K_MASK(I) = 0.0D0
    ELSE
      X_RAMP = (K_NORM - EFFECTIVE_RATIO) / (1.0D0 - EFFECTIVE_RATIO)
      Y_RAMP = EFFECTIVE_STEEPNESS * (2.0D0 * X_RAMP - 1.0D0)
      K_MASK(I) = (TANH(Y_RAMP) + TANH_A) / (2.0D0 * TANH_A)
    END IF
  END DO
    
END SUBROUTINE HYP3MASK

!> =====================================================================
!> @brief INITIALIZES HYPERVISCOSITY COEFFICIENTS.
!>
!> @details
!> THIS SUBROUTINE HANDLES THE INITIALIZATION OF HYPERVISCOSITY COEFFS.
!>
!> @param[in] IS_BOUSSI >> TRUE IF SIMULATION INCLUDES DENSITY FIELD
!>
!> @author JINGE WANG
!> @date   OCT 2025
!> =====================================================================
SUBROUTINE HYP3INIT(IS_BOUSSI)
!=======================================================================
  IMPLICIT NONE
  LOGICAL, INTENT(IN), OPTIONAL :: IS_BOUSSI

  VISC%NUP_R = VISC%NUP
  VISC%NUP_T = VISC%NUP
  VISC%NUP_X = VISC%NUP
  CALL HYP3SET(VISC%NUP_R, VISC%NUP_T, VISC%NUP_X, VISC%HYPERV_R, VISC%HYPERV_T, VISC%HYPERV_X)

  IF (PRESENT(IS_BOUSSI).AND.(IS_BOUSSI)) THEN
      VISC%KAPPAP_R = BSNSQ%KAPPAP
      VISC%KAPPAP_T = BSNSQ%KAPPAP
      VISC%KAPPAP_X = BSNSQ%KAPPAP
    CALL HYP3SET(VISC%KAPPAP_R, VISC%KAPPAP_T, VISC%KAPPAP_X, VISC%HYPERD_R, VISC%HYPERD_T, VISC%HYPERD_X)
  END IF

END SUBROUTINE HYP3INIT

