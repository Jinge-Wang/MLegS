  SUBROUTINE CALC_BOUSSI_ETD_OP(ETD_OP, DT, ECHO)
!=======================================================================
! [USAGE]: 
! COMPUTE ETD OPERATORS FOR BOUSSINESQ EQUATIONS
! [NOTE]:
! ETD OPERATION TAKES CARE OF ROTATION AND STRATIFICATION TERMS
! AS WELL AS CROSS-TERMS BETWEEN BASEFLOW AND PERTURBATIONS
!=======================================================================
  IMPLICIT NONE
  TYPE(ETD_OP_T), INTENT(INOUT) :: ETD_OP
  REAL(P8) :: DT
  LOGICAL, OPTIONAL :: ECHO

  INTEGER :: NN, MM, MSIZE, INTH
  COMPLEX(P8) :: J_SHIFT
  COMPLEX(P8), DIMENSION(2,2) :: S_V, J_V, S_INV_V
  REAL(P8), ALLOCATABLE, DIMENSION(:) :: OMEGA0
  COMPLEX(P8), ALLOCATABLE, DIMENSION(:,:,:) :: S_H, J_H, S_INV_H

  ! OBTAIN BASEFLOW
  IF (.NOT.ALLOCATED(BSNSQ%RUP0)) CALL CALC_BOUSSI_BASEFLOW(FILES%SAVEDIR)
  ALLOCATE(OMEGA0(NR)); OMEGA0 = BSNSQ%ANGULAR_VELOCITY()

  ! OBTAIN JORDAN DECOMPOSITION FOR AXISYMMETRIC MODES (M=0)
  IF (PRESENT(ECHO)) THEN
    CALL CALC_BOUSSI_DIAGV(J_V, S_V, S_INV_V, ECHO)
    CALL CALC_BOUSSI_DIAGH(J_H, S_H, S_INV_H, ECHO)
  ELSE
    CALL CALC_BOUSSI_DIAGV(J_V, S_V, S_INV_V)
    CALL CALC_BOUSSI_DIAGH(J_H, S_H, S_INV_H)
  ENDIF

  ! ALLOCATE ETD OPERATORS
  MSIZE = local_size(NTCHOPDIM,SUBCOMM_2)
  INTH = local_index(NTCHOPDIM,SUBCOMM_2)
  ALLOCATE(ETD_OP%E_V(2,2,NR,MSIZE), ETD_OP%NL_V(2,2,NR,MSIZE))
  ALLOCATE(ETD_OP%E_H(2,2,NR,MSIZE), ETD_OP%NL_H(2,2,NR,MSIZE))

  ! COMPUTE ETD OPERATORS
  !$OMP PARALLEL DO DEFAULT(SHARED) PRIVATE(NN,MM,J_SHIFT) COLLAPSE(2)
  DO MM = 1, MSIZE
    DO NN = 1, NR
      J_SHIFT = -IU * M(MM+INTH) * OMEGA0(NN)
      CALL CALC_BOUSSI_ETD_OP_SUB(J_V, S_V, S_INV_V, J_SHIFT, DT, &
                                  ETD_OP%E_V(:,:,NN,MM), ETD_OP%NL_V(:,:,NN,MM))
      CALL CALC_BOUSSI_ETD_OP_SUB(J_H(:,:,NN), S_H(:,:,NN), S_INV_H(:,:,NN), J_SHIFT, DT, &
                                  ETD_OP%E_H(:,:,NN,MM), ETD_OP%NL_H(:,:,NN,MM))
    ENDDO
  ENDDO
  !$OMP END PARALLEL DO

  DEALLOCATE(OMEGA0, S_H, J_H, S_INV_H)

  ! DIAGNOST
  IF (PRESENT(ECHO)) THEN
    IF (ECHO .AND. MPI_RANK.EQ.0) THEN
      WRITE(*,*) 'SOLVER: ETD operators initialized for dt = ', DT
      WRITE(*,*) 'ETD_E_V(r=0,m=0):'
      CALL MCAT(ETD_OP%E_V(:,:,1,1))
      WRITE(*,*) 'ETD_NL_V(r=0,m=0):'
      CALL MCAT(ETD_OP%NL_V(:,:,1,1))
      WRITE(*,*) 'ETD_E_H(r=0,m=0):'
      CALL MCAT(ETD_OP%E_H(:,:,1,1))
      WRITE(*,*) 'ETD_NL_H(r=0,m=0):'
      CALL MCAT(ETD_OP%NL_H(:,:,1,1))

      WRITE(*,*) 'ETD_E_V(r=0,m=1):'
      CALL MCAT(ETD_OP%E_V(:,:,1,2))
      WRITE(*,*) 'ETD_NL_V(r=0,m=1):'
      CALL MCAT(ETD_OP%NL_V(:,:,1,2))
      WRITE(*,*) 'ETD_E_H(r=0,m=1):'
      CALL MCAT(ETD_OP%E_H(:,:,1,2))
      WRITE(*,*) 'ETD_NL_H(r=0,m=1):'
      CALL MCAT(ETD_OP%NL_H(:,:,1,2))
    ENDIF
  ENDIF

  RETURN
  END SUBROUTINE CALC_BOUSSI_ETD_OP

!=======================================================================
  SUBROUTINE CALC_BOUSSI_ETD_OP_SUB(J_BASE, S_MATRIX, S_INV_MATRIX, &
                                     J_SHIFT, DT, E_OP, NL_OP)
!=======================================================================
! [USAGE]: 
! COMPUTE ETD OPERATORS FOR A 2X2 JORDAN BLOCK SYSTEM
! [INPUTS]:
! J_BASE >> 2X2 BASE JORDAN MATRIX 
! S_MATRIX >> 2X2 RIGHT EIGENMATRIX
! S_INV_MATRIX >> 2X2 LEFT EIGENMATRIX (INVERSE OF S_MATRIX)
! J_SHIFT >> COMPLEX SHIFT TO BE ADDED TO DIAGONAL OF J_BASE
! DT >> TIME STEP
! [OUTPUTS]:
! E_OP >> 2X2 EVOLUTION OPERATOR (EXP TERM)
! NL_OP >> 2X2 NONLINEAR OPERATOR (PHI1 TERM)
!=======================================================================
  IMPLICIT NONE
  COMPLEX(P8), DIMENSION(2,2), INTENT(IN) :: J_BASE, S_MATRIX, S_INV_MATRIX
  COMPLEX(P8), INTENT(IN) :: J_SHIFT
  REAL(P8), INTENT(IN) :: DT
  COMPLEX(P8), DIMENSION(2,2), INTENT(OUT) :: E_OP, NL_OP

  INTEGER :: I
  COMPLEX(P8), DIMENSION(2,2) :: J_TEMP, J_EXP_TEMP, J_PHI1_TEMP

  ! INITIALIZE TEMPORARY MATRICES
  J_TEMP = J_BASE
  J_EXP_TEMP = CMPLX(0.0D0, 0.0D0, P8)
  J_PHI1_TEMP = CMPLX(0.0D0, 0.0D0, P8)

  ! COMPUTE SHIFTED EIGENVALUES AND CORRESPONDING OPERATORS
  DO I = 1, 2
    J_TEMP(I,I) = J_TEMP(I,I) + J_SHIFT
    J_EXP_TEMP(I,I) = EXP(J_TEMP(I,I) * DT)
    IF (ABS(J_TEMP(I,I)) > 1.0D-14) THEN
      J_PHI1_TEMP(I,I) = (J_EXP_TEMP(I,I) - 1.0D0) / J_TEMP(I,I)
    ELSE
      J_PHI1_TEMP(I,I) = DT
    ENDIF
  ENDDO

  ! TRANSFORM BACK TO ORIGINAL BASIS
  E_OP = MATMUL(S_MATRIX, MATMUL(J_EXP_TEMP, S_INV_MATRIX))
  NL_OP = MATMUL(S_MATRIX, MATMUL(J_PHI1_TEMP, S_INV_MATRIX))

  RETURN
  END SUBROUTINE CALC_BOUSSI_ETD_OP_SUB
!=======================================================================

  SUBROUTINE CALC_BOUSSI_ETDFE_SUB(ETD_OP,B,RUR,RUP,UZ,NB,RNR,RNP,NZ,DT)
!=======================================================================
! [USAGE]:
! APPLY 1ST ORDER EXPONENTIAL TIME DIFFERENCING SCHEME:
! L = S * J * S^-1
! E = S * exp(J*DT) * S^-1
! A = S * J^-1 * (exp(J*DT)-I) * S^-1
! U^(N+1/2) = E*U^(N) + A*N[U^(N)]
! [PARAMETERS]:
! THIS >> SOLVER OBJECT CONTAINING THE NONLINEAR STATE OF PREV STEP
!   B >> ON ENTRY, B OF CURRENT STEP
!        ON EXIT, B^(N+1/2)
! RUR >> ON ENTRY, R*U_R OF CURRENT STEP IN PFF SPACE
!        ON EXIT, R*U^(N+1/2)_R
! RUP >> ON ENTRY, R*U_P OF CURRENT STEP IN PFF SPACE
!        ON EXIT, R*U^(N+1/2)_P
!  UZ >> ON ENTRY, U_Z OF CURRENT STEP IN PFF SPACE
!        ON EXIT, U^(N+1/2)_Z
!  NB >> ON ENTRY, N_B OF CURRENT STEP IN PFF SPACE
! RNR >> ON ENTRY, R*N_R OF CURRENT STEP IN PFF SPACE
! RNP >> ON ENTRY, R*N_P OF CURRENT_STEP IN PFF SPACE
!  NZ >> ON ENTRY, N_Z OF CURRENT STEP IN PFF SPACE
! [NOTES]:
! THE LINEAR OPERATOR (L) STAYS UNCHANGED FOR THE RE-SCALED STATE
! VARIABLE [RUR, RUP, UZ, B]^T, SO E AND A MATRICES REMAIN UNCHANGED
!=======================================================================
  IMPLICIT NONE
  TYPE(ETD_OP_T), INTENT(IN) :: ETD_OP
  TYPE(SCALAR), INTENT(IN) :: RNR, RNP, NZ, NB
  TYPE(SCALAR), INTENT(INOUT) :: RUR, RUP, UZ, B
  REAL(P8), INTENT(IN) :: DT

  INTEGER :: NN, MM, KK
  COMPLEX(P8), DIMENSION(4, 1) :: EV, AV, CV  

  ! --- Space Checks ---
  IF ((RUR%SPACE .NE. PFF_SPACE) .OR. (NB%SPACE .NE. PFF_SPACE) .OR. (RNR%SPACE .NE. PFF_SPACE)) THEN
    CALL MPRINT('CALC_BOUSSI_ETDAB_SUB: RUR, NB, RNR must be in PFF space.')
    CALL MPI_ABORT(MPI_COMM_IVP, ERR_FLAGS%LEGOPERATOR, IERR)
  ENDIF

  IF (B%SPACE .EQ. FFF_SPACE) THEN
    CALL RTRAN(B, 1)
  ELSEIF (B%SPACE .NE. PFF_SPACE) THEN
    CALL MPRINT('CALC_BOUSSI_ETDAB_SUB: B must be in PFF or FFF space.')
    CALL MPI_ABORT(MPI_COMM_IVP, ERR_FLAGS%LEGOPERATOR, IERR)
  ENDIF
  ! --- End Space Checks ---

  !$OMP PARALLEL DO PRIVATE(MM, NN, EV, AV, CV) SCHEDULE(STATIC)
  DO KK = 1, SIZE(B%E, 3)
    DO MM = 1, SIZE(B%E, 2)
      DO NN = 1, NR
        EV(1, 1) = RUR%E(NN, MM, KK)
        EV(2, 1) = RUP%E(NN, MM, KK)
        EV(3, 1) = UZ%E(NN, MM, KK)
        EV(4, 1) = B%E(NN, MM, KK)

        AV(1, 1) = RNR%E(NN, MM, KK)
        AV(2, 1) = RNP%E(NN, MM, KK)
        AV(3, 1) = NZ%E(NN, MM, KK)
        AV(4, 1) = NB%E(NN, MM, KK)

        CV(1:2, 1) = MATMUL(ETD_OP%E_H(:,:,NN,MM), EV(1:2, 1)) + &
                  MATMUL(ETD_OP%NL_H(:,:,NN,MM), AV(1:2, 1))
        CV(3:4, 1) = MATMUL(ETD_OP%E_V(:,:,NN,MM), EV(3:4, 1)) + &
                  MATMUL(ETD_OP%NL_V(:,:,NN,MM), AV(3:4, 1))

        RUR%E(NN, MM, KK) = CV(1, 1)
        RUP%E(NN, MM, KK) = CV(2, 1)
        UZ%E(NN, MM, KK)  = CV(3, 1)
        B%E(NN, MM, KK)   = CV(4, 1)
      ENDDO
    ENDDO    
  ENDDO
  !$OMP END PARALLEL DO

  RETURN
  END SUBROUTINE CALC_BOUSSI_ETDFE_SUB
