  SUBROUTINE VISC1(A,NU,DT,WK)
!=======================================================================
! [USAGE]: 
! UPDATE A SCALAR FIELD WITH REGARD TO VISCOSITY
! USING BACKWARD (IMPLICIT) EULER METHOD
! [PARAMETERS]:
! A   >> SCALAR FIELD TO BE UPDATED
! NU  >> VISCOSITY/DIFFUSIVITY
! DT  >> TIMESTEP
! WK  >> PRE-ALLOCATED WORKING VARIABLE
! [DEPENDENCIES]:
! 1. (DE)ALLOCATE(~) @ MOD_SCALAR3
! 2. IHELM(~) @ MOD_LEGOPS
! [NOTES]:
! THE FOLLOWING FORMULA IS UTILIZED TO UPDATE A.
!     A(1)-A(0)
!     ------------- = VISCNU(DEL2)(A(1))
!           DT
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR), INTENT(INOUT):: A, WK
  REAL(P8):: DT, NU

  REAL(P8):: ALP

  IF(NU.EQ.0.0) THEN
    CALL MPRINT("VISC1: NU CAN'T BE ZERO")
    CALL MPI_ABORT(MPI_COMM_WORLD, ERR_FLAGS%SOLVER, IERR)
  ENDIF

  IF (A%SPACE .NE. FFF_SPACE) THEN
    CALL MPRINT("VISC1: INPUT IS NOT IN FFF_SPACE")
    CALL MPI_ABORT(MPI_COMM_WORLD, ERR_FLAGS%SOLVER, IERR)
  ENDIF

  IF (WK%SPACE .NE. FFF_SPACE) THEN
    CALL DEALLOCATE(WK)
    CALL ALLOCATE(WK,FFF_SPACE)
  ENDIF

  ALP=1/(NU*DT)

  IF ((A%INTH.EQ.0).AND.(A%INX.EQ.0)) WK%LN=-ALP*A%LN
  WK%E =-ALP*A%E
  CALL IHELM(WK,A,ALP)

  RETURN
  END SUBROUTINE VISC1
!=======================================================================

  SUBROUTINE VISC2(A,AO,NU,DT,WK)
!=======================================================================
! [USAGE]: 
! UPDATE A SCALAR FIELD WITH REGARD TO VISCOSITY
! USING CRANK-NICHOLSON (IMPLICIT) METHOD
! [PARAMETERS]:
! A   >> SCALAR FIELD TO BE UPDATED
! AO  >> SCALAR FIELD IN A PREVIOUS TIME STEP
! NU  >> VISCOSITY/DIFFUSIVITY
! DT  >> TIMESTEP
! WK  >> PRE-ALLOCATED WORKING VARIABLE
! [DEPENDENCIES]:
! 1. (DE)ALLOCATE(~) @ MOD_SCALAR3
! 2. CHOPSET(~) @ MOD_SCALAR3
! 3. CHOPDO(~) @ MOD_SCALAR3
! 4. DEL2(~) @ MOD_LEGOPS
! 5. IHELM(~) @ MOD_LEGOPS
! [NOTES]:
! THE FOLLOWING FORMULA IS UTILIZED TO UPDATE A.
!     A(1)-A(1/2)                  A(1)+A(0)
!    ------------ = VISCNU(DEL2)(------------)
!         DT                           2
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR),INTENT(INOUT):: A, WK
  TYPE(SCALAR),INTENT(IN):: AO
  REAL(P8):: DT, NU

  REAL(P8):: ALP

  IF(NU.EQ.0.0) THEN
    CALL MPRINT("VISC2: NU CAN'T BE ZERO")
    CALL MPI_ABORT(MPI_COMM_WORLD, ERR_FLAGS%SOLVER, IERR)
  ENDIF

  IF (A%SPACE .NE. FFF_SPACE) THEN
    CALL MPRINT("VISC2: INPUT IS NOT IN FFF_SPACE")
    CALL MPI_ABORT(MPI_COMM_WORLD, ERR_FLAGS%SOLVER, IERR)
  ENDIF

  IF (WK%SPACE .NE. FFF_SPACE) THEN
    CALL DEALLOCATE(WK)
    CALL ALLOCATE(WK,FFF_SPACE)
  ENDIF

  ALP=2/NU/DT

  CALL CHOPSET(2)
  CALL DEL2(AO,WK)
  CALL CHOPSET(-2)
  CALL CHOPDO(WK)

  WK%E = -WK%E-ALP*A%E
  IF ((A%INTH.EQ.0).AND.(A%INX.EQ.0)) WK%LN= -ALP*A%LN
  CALL IHELM(WK,A,ALP)

  RETURN
  END SUBROUTINE VISC2
!=======================================================================

  SUBROUTINE HYPERV(A,NU,NUP,P,DT,WK)
!=======================================================================
! [USAGE]: 
! DUMP HYPERVISCOSITY TO THE HIGHER ORDER COEFFICIENTS
! [PARAMETERS]:
! A   >> SCALAR FIELD TO BE UPDATED
! NU  >> VISCOSITY/DIFFUSIVITY
! NUP >> HYPERVISCOSITY/DIFFUSIVITY
! P   >> POWER OF THE HYPERVISCOSITY
! DT  >> TIMESTEP
! WK  >> PRE-ALLOCATED WORKING VARIABLE
! [DEPENDENCIES]:
! 1. (DE)ALLOCATE(~) @ MOD_SCALAR3
! 2. IHELMP(~) @ MOD_LEGOPS
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR), INTENT(INOUT):: A, WK
  REAL(P8):: NU, NUP, DT
  INTEGER:: P
  
  REAL(P8):: ALP,BET
  INTEGER:: PH

  IF(NUP.EQ.0.0) THEN
    CALL MPRINT("HYPERV: NUP CAN'T BE ZERO")
    CALL MPI_ABORT(MPI_COMM_WORLD, ERR_FLAGS%SOLVER, IERR)
  ENDIF

  IF (A%SPACE .NE. FFF_SPACE) THEN
    CALL MPRINT("HYPERV: INPUT IS NOT IN FFF_SPACE")
    CALL MPI_ABORT(MPI_COMM_WORLD, ERR_FLAGS%SOLVER, IERR)
  ENDIF

  IF (WK%SPACE .NE. FFF_SPACE) THEN
    CALL DEALLOCATE(WK)
    CALL ALLOCATE(WK,FFF_SPACE)
  ENDIF

  PH = P/2
  ALP = 1/DT/NUP *(-1)**PH
  BET = -(-1)**PH*NU/NUP

  WK%E = ALP*A%E
  IF ((A%INTH.EQ.0).AND.(A%INX.EQ.0)) WK%LN = ALP*A%LN
  CALL IHELMP(P,WK,A,-ALP,BET)

  RETURN
  END SUBROUTINE HYPERV
