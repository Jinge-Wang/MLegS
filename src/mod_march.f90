  SUBROUTINE STEP_BOUSSI_ETDFE_BE(PSI, CHI, B, ETD_E, ETD_NL, SOLVER)
!=======================================================================
! [USAGE]:
! FIRST-ORDER "ETD1-FORWARD EULER" EXPLICIT PREDICTOR STEP
! FOR BOUSSINESQ EQUATIONS
! [PARAMETERS]:
! ETD_E, ETD_NL >> (IN) PRE-COMPUTED ETD OPERATORS
! PSI, CHI, B   >> (IN) STATE AT CURRENT TIME
!               >> (OUT) OVERWRITTEN WITH THE PREDICTED STATE
! SOLVER (OPTIONAL) >> (INOUT) SOLVER OBJECT TO STORE HISTORY VARIABLES
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR), INTENT(INOUT)   :: PSI, CHI, B
  COMPLEX(P8), DIMENSION(4,4), INTENT(IN) :: ETD_E, ETD_NL
  TYPE(SOLVER_T), INTENT(INOUT), OPTIONAL :: SOLVER

  TYPE(SCALAR):: RURN, RUPN, UZN, BN
  TYPE(SCALAR):: RORN, ROPN, OZN
  TYPE(SCALAR):: W

  CALL ALLOCATE(RURN); CALL ALLOCATE(RUPN); CALL ALLOCATE(UZN)
  CALL ALLOCATE(RORN); CALL ALLOCATE(ROPN); CALL ALLOCATE(OZN)

  CALL CHOPSET(3)
  CALL PC2VEL(PSI,CHI,RURN,RUPN,UZN)
  CALL PC2VOR(PSI,CHI,RORN,ROPN,OZN)
  CALL CHOPSET(-3)

  ! CALCULATE NONLINEAR TERMS: U X W AND -(U.GRAD)B' 
  ! NOTES:
  ! - B REMAIN IN FFF SPACE
  ! - RURN, RUPN, UZN ARE RETURNED IN PPP SPACE
  !   AND UPDATED WITH FREESTREAM ADJUSTMENT
  ! - RORN, ROPN, OZN ARE RETURNED IN PPP SPACE
  !   AND UPDATED WITH THE NONLINEAR RESULT
  CALL CALC_BOUSSI_NONLIN(B,RURN,RUPN,UZN,BN,RORN,ROPN,OZN)
  CALL CALC_BOUSSI_ETDFE_SUB(ETD_E,ETD_NL,B,RURN,RUPN,UZN,BN,RORN,ROPN,OZN)
  CALL TOFF(B)

  IF (PRESENT(SOLVER)) THEN ! SAVE NONLINEAR STATES TO SOLVER
    SOLVER%N_B = BN
    SOLVER%R_N_R = RORN
    SOLVER%R_N_P = ROPN
    SOLVER%N_Z = OZN
    SOLVER%R_PI_R = RURN
    SOLVER%R_PI_P = RUPN
    SOLVER%PI_Z = UZN
  ENDIF
  CALL DEALLOCATE(BN)
  CALL DEALLOCATE(RORN)
  CALL DEALLOCATE(ROPN)
  CALL DEALLOCATE(OZN)

  CALL ALLOCATE(W)
  CALL PROJECT(RURN,RUPN,UZN,PSI,W,PSI%LN)
  CALL DEALLOCATE(RURN)
  CALL DEALLOCATE(RUPN)
  CALL DEALLOCATE(UZN)

  ! CALL IDEL2(W, CHI)
  CALL IDEL2LN(W, CHI)
  CALL DEALLOCATE(W)

  IF (PRESENT(SOLVER)) THEN
    CALL ALLOCATE(RURN)
    CALL ALLOCATE(RUPN)
    CALL ALLOCATE(UZN)
    CALL CHOPSET(3)
    CALL PC2VEL(PSI,CHI,RURN,RUPN,UZN)
    CALL CHOPSET(-3)
    CALL TOFP(RURN)
    CALL TOFP(RUPN)
    CALL TOFP(UZN)

    SOLVER%R_PI_R%E = RURN%E - SOLVER%R_PI_R%E
    SOLVER%R_PI_P%E = RUPN%E - SOLVER%R_PI_P%E
    SOLVER%PI_Z%E   = UZN%E  - SOLVER%PI_Z%E

    CALL DEALLOCATE(RURN)
    CALL DEALLOCATE(RUPN)
    CALL DEALLOCATE(UZN)
  ENDIF

  RETURN
  END SUBROUTINE STEP_BOUSSI_ETDFE_BE
!=======================================================================

  SUBROUTINE RICH_BOUSSI_ETDFE_BE(THIS, PSI, CHI, B)
!=======================================================================
  IMPLICIT NONE
  TYPE(SOLVER_T), INTENT(INOUT) :: THIS
  TYPE(SCALAR), INTENT(INOUT)   :: PSI, CHI, B

  TYPE(SCALAR):: PSI2, CHI2, B2
  TYPE(SCALAR):: RUR, RUP, UZ
  REAL(P8):: DT, HDT
  COMPLEX(P8),DIMENSION(4,4):: HETD_E, HETD_NL

  IF (.NOT.ALLOCATED(THIS%ETD_E)) THEN
    CALL MPRINT('ETD operators not initialized. Call CALC_BOUSSI_ETD_OP before using RICH_BOUSSI_ETDFE_BE.')
    CALL MPI_ABORT(MPI_COMM_IVP, ERR_FLAGS%SOLVER, IERR)
  ENDIF

  DT = TIM%DT
  HDT = DT*0.5D0
  CALL CALC_BOUSSI_ETD_OP(HETD_E, HETD_NL, HDT)

  TIM%T = TIM%T + DT
  TIM%N = TIM%N + 1
  ADV%X = ADV%X + ADV%UX*DT
  ADV%Y = ADV%Y + ADV%UY*DT

  CALL ALLOCATE(PSI2); PSI2 = PSI
  CALL ALLOCATE(CHI2); CHI2 = CHI
  CALL ALLOCATE(  B2);   B2 =   B

  ! FIRST HALF-STEP
  CALL STEP_BOUSSI_ETDFE_BE(PSI2, CHI2, B2, HETD_E, HETD_NL)
  CALL CALC_BOUSSI_VISC_BE(PSI2,CHI2,B2,HDT)
  CALL CALC_BOUSSI_HYPERV(PSI2,CHI2,B2,HDT)

  ! SECOND HALF-STEP
  CALL STEP_BOUSSI_ETDFE_BE(PSI2, CHI2, B2, HETD_E, HETD_NL)
  CALL CALC_BOUSSI_VISC_BE(PSI2,CHI2,B2,HDT)
  CALL CALC_BOUSSI_HYPERV(PSI2,CHI2,B2,HDT)

  ! FULL STEP
  CALL STEP_BOUSSI_ETDFE_BE(PSI, CHI, B, THIS%ETD_E, THIS%ETD_NL, THIS)
  CALL CALC_BOUSSI_VISC_BE(PSI,CHI,B,DT)
  CALL CALC_BOUSSI_HYPERV(PSI,CHI,B,DT)

  PSI%E  =(2.0D0*PSI2%E)-PSI%E
  PSI%LN =(2.0D0*PSI2%LN)-PSI%LN
  CHI%E  =(2.0D0*CHI2%E)-CHI%E
  CHI%LN =(2.0D0*CHI2%LN)-CHI%LN
  B%E    =(2.0D0*B2%E)-B%E

  CALL DEALLOCATE( PSI2 )
  CALL DEALLOCATE( CHI2 )
  CALL DEALLOCATE(   B2 )

  CALL ALLOCATE(RUR); CALL ALLOCATE(RUP); CALL ALLOCATE(UZ)
  CALL CHOPSET(3)
  CALL PC2VEL(PSI,CHI,RUR,RUP,UZ)
  CALL CHOPSET(-3)
  CALL TOFP(RUR); CALL TOFP(RUP); CALL TOFP(UZ)
  THIS%R_PI_R%E = RUR%E - 0.5D0 * THIS%R_PI_R%E
  THIS%R_PI_P%E = RUP%E - 0.5D0 * THIS%R_PI_P%E
  THIS%PI_Z%E   = UZ%E  - 0.5D0 * THIS%PI_Z%E
  CALL DEALLOCATE(RUR); CALL DEALLOCATE(RUP); CALL DEALLOCATE(UZ)
  RETURN
  END SUBROUTINE RICH_BOUSSI_ETDFE_BE
