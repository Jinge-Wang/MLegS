  SUBROUTINE STEP_BOUSSI_ETDFE_BE(PSI, CHI, B, ETD_OP, DT, SOLVER)
!=======================================================================
! [USAGE]:
! FIRST-ORDER "ETD1-FORWARD EULER" EXPLICIT PREDICTOR STEP
! FOR BOUSSINESQ EQUATIONS
! [PARAMETERS]:
! ETD_OP      >> (IN) PRE-COMPUTED ETD OPERATORS
! PSI, CHI, B >> (IN) STATE AT CURRENT TIME
!             >> (OUT) OVERWRITTEN WITH THE PREDICTED STATE
! DT          >> (IN) TIME STEP SIZE
! SOLVER (OPTIONAL) >> (INOUT) SOLVER OBJECT TO STORE HISTORY VARIABLES
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR), INTENT(INOUT) :: PSI, CHI, B
  TYPE(ETD_OP_T), INTENT(IN) :: ETD_OP
  REAL(P8), INTENT(IN) :: DT
  TYPE(SOLVER_T), INTENT(INOUT), OPTIONAL :: SOLVER

  TYPE(SCALAR) :: RURN, RUPN, UZN, BN
  TYPE(SCALAR) :: RORN, ROPN, OZN
  TYPE(SCALAR) :: W

  CALL ALLOCATE(RURN); CALL ALLOCATE(RUPN); CALL ALLOCATE(UZN)
  CALL ALLOCATE(RORN); CALL ALLOCATE(ROPN); CALL ALLOCATE(OZN)

  CALL CHOPSET(3)
  CALL PC2VEL(PSI,CHI,RURN,RUPN,UZN)
  CALL PC2VOR(PSI,CHI,RORN,ROPN,OZN)
  CALL CHOPSET(-3)

  ! CALCULATE NONLINEAR TERMS: U X W AND -(U.GRAD)B' 
  ! NOTES:
  ! - B IN FFF SPACE; BN IN PFF SPACE (WITH NONLIN RESULTS)
  ! - RURN, RUPN, UZN ARE DEALLOCATED
  ! - RORN, ROPN, OZN ARE IN FFF SPACE (WITH NONLIN RESULTS)
  CALL CALC_BOUSSI_NONLIN(B,RURN,RUPN,UZN,BN,RORN,ROPN,OZN)
  ! CALL CALC_BOUSSI_ETD_HYPERV(RORN,ROPN,OZN,BN,DT) ! TODO: PROBABLY DONT NEED

  ! APPLY ETD INTEGRATION
  CALL ALLOCATE(RURN); CALL ALLOCATE(RUPN); CALL ALLOCATE(UZN)
  CALL CHOPSET(3)
  CALL PC2VEL(PSI,CHI,RURN,RUPN,UZN)
  CALL CHOPSET(-3)
  CALL RTRAN(RURN,1); CALL RTRAN(RUPN,1); CALL RTRAN(UZN,1) ! TO PFF SPACE
  CALL RTRAN(RORN,1); CALL RTRAN(ROPN,1); CALL RTRAN(OZN,1) ! TO PFF SPACE
  CALL CALC_BOUSSI_ETDFE_SUB(ETD_OP,B,RURN,RUPN,UZN,BN,RORN,ROPN,OZN,DT) ! IN PFF SPACE

  ! APPLY SPONGE LAYER (AXIAL)
  CALL CALC_BOUSSI_ETD_SPONGE(UZN,B,DT); CALL RTRAN(B,-1)

  ! APPLY HYPERVISCOSITY IN FFF SPACE
  CALL RTRAN(RURN,-1); CALL RTRAN(RUPN,-1); CALL RTRAN(UZN,-1)
  CALL CALC_BOUSSI_ETD_HYPERV(RURN,RUPN,UZN,B,DT)
  CALL RTRAN(RURN,1); CALL RTRAN(RUPN,1); CALL RTRAN(UZN,1)

  IF (PRESENT(SOLVER)) THEN ! SAVE NONLINEAR STATES TO SOLVER
    SOLVER%N_B%E = BN%E
    SOLVER%R_N_R%E = RORN%E
    SOLVER%R_N_P%E = ROPN%E
    SOLVER%N_Z%E = OZN%E
    SOLVER%R_PI_R%E = RURN%E
    SOLVER%R_PI_P%E = RUPN%E
    SOLVER%PI_Z%E   = UZN%E
  ENDIF
  CALL DEALLOCATE(BN)
  CALL DEALLOCATE(RORN)
  CALL DEALLOCATE(ROPN)
  CALL DEALLOCATE(OZN)

  CALL ALLOCATE(W)
  CALL PROJECT(RURN,RUPN,UZN,PSI,W,PSI%LN)
  CALL DEALLOCATE(RURN)
  CALL DEALLOCATE(RUPN)
  CALL DEALLOCATE(UZN)

  CALL IDEL2LN(W, CHI)
  CALL DEALLOCATE(W)

  ! CALL CALC_BOUSSI_HYPERV(PSI,CHI,B,DT)

  IF (PRESENT(SOLVER)) THEN
    CALL ALLOCATE(RURN)
    CALL ALLOCATE(RUPN)
    CALL ALLOCATE(UZN)
    CALL CHOPSET(3)
    CALL PC2VEL(PSI,CHI,RURN,RUPN,UZN)
    CALL CHOPSET(-3)
    CALL RTRAN(RURN,1); CALL RTRAN(RUPN,1); CALL RTRAN(UZN,1) ! TO PFF SPACE
    SOLVER%R_PI_R%E = 0.5D0 * (SOLVER%R_PI_R%E - RURN%E)
    SOLVER%R_PI_P%E = 0.5D0 * (SOLVER%R_PI_P%E - RUPN%E)
    SOLVER%PI_Z%E   = 0.5D0 * (SOLVER%PI_Z%E   - UZN%E)
    CALL DEALLOCATE(RURN)
    CALL DEALLOCATE(RUPN)
    CALL DEALLOCATE(UZN)
  ENDIF

  RETURN
  END SUBROUTINE STEP_BOUSSI_ETDFE_BE
