  SUBROUTINE ENEMON(PSI,CHI,EM,EK)
!=======================================================================
! [USAGE]: 
! COMPUTE ENERGY FOR EACH AZIMUTHAL AND AXIAL WAVE NUMBER
! [PARAMETERS]:
! PSI >> TOROIDAL TERM IN A SCALAR-TYPE VARIABLE IN A FFF SPACE
! CHI >> POLOIDAL TERM IN A SCALAR-TYPE VARIABLE IN A FFF SPACE
! EM >> ENERGY FOR EACH M (AZIMUTHAL WAVENUMBER)
! EK >> ENERGY FOR EACH K (AXIAL WAVENUMBER)
! [DEPENDENCIES]:
! 1. (DE)ALLOCATE(~) @ MOD_SCALAR3
! 2. RTRAN(~)        @ MOD_SCALAR3
! 3. DELSQH(~)       @ MOD_LEGOPS
! 4. DEL2(~)         @ MOD_LEGOPS
! 5. PRODCT_M(~)     @ MOD_SCALAR3
! 6. PRODCT_K(~)     @ MOD_SCALAR3
! [UPDATES]:
! RE-CODED BY SANGJOON LEE @ NOV 20 2020
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR):: PSI,CHI, W1,W2
  REAL(P8):: EM(NTCHOP)
  REAL(P8),OPTIONAL:: EK(NXCHOP)

  CALL ALLOCATE(W1)
  CALL ALLOCATE(W2)

  !> ENERGY P157
  W1=PSI
  IF ((PSI%INTH.EQ.0).AND.(PSI%INX.EQ.0)) W1%LN=2*PSI%LN
  CALL DELSQH(W1,W2)
  CALL RTRAN(W2,1)
  W1=PSI
  W1%LN=0.D0
  CALL RTRAN(W1,1)
  EM= PRODCT_M(W2,W1)
  IF (PRESENT(EK)) THEN
  EK= PRODCT_K(W2,W1)
  END IF
  
  CALL DEL2(CHI,W1)
  CALL RTRAN(W1,1)
  CALL DELSQH(CHI,W2)
  CALL RTRAN(W2,1)
  EM= -EM+PRODCT_M(W2,W1)
  IF (PRESENT(EK)) THEN
  EK= -EK+PRODCT_K(W2,W1)
  END IF

  CALL DEALLOCATE(W1)
  CALL DEALLOCATE(W2)

  RETURN
  END SUBROUTINE ENEMON
