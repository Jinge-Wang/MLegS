  FUNCTION SMOOTH(A)
!=======================================================================
! [USAGE]: 
! SMOOTHING A SEQUENCE A BY CONVOLUTION
! [INPUTS]:
! A >> A SEQUENCE CONTAINING NOISES
! [OUTPUTS]:
! SMOOTH >> SMOOTHENED SEQUENCE USING CONVOLUTION
! [UPDATES]:
! RE-CODED BY SANGJOON LEE @ NOV 20 2020
!=======================================================================
  IMPLICIT NONE
  COMPLEX(P8),DIMENSION(:):: A
  COMPLEX(P8),DIMENSION(SIZE(A)):: SMOOTH

  REAL(P8),DIMENSION(3):: FAE=(/ 0.2D0, 0.3D0, 0.5D0 /)
  REAL(P8):: F
  INTEGER:: NI,I,NB,NE

  NI=SIZE(A)

  IF(NI.LT.3) THEN
    WRITE(*,*) 'SMOOTH: SIZE TOO SMALL'
    STOP
  ENDIF

  SMOOTH=0
  SMOOTH(1)=A(1)
  SMOOTH(NI-2:NI)= SMOOTH(NI-2:NI) +A(NI)*FAE

  DO I=2,NI-1
    F = (1+((NI-I)/(NI-1.0D0)))*0.5D0
    SMOOTH(I-1)= SMOOTH(I-1)+A(I)*(1-F)/2
    SMOOTH(I  )= SMOOTH(I  )+A(I)*F
    SMOOTH(I+1)= SMOOTH(I+1)+A(I)*(1-F)/2
  ENDDO

  RETURN
  END FUNCTION SMOOTH
!=======================================================================

  FUNCTION DDC(R)
!=======================================================================
! [USAGE]: 
! SMOOTHING A SEQUENCE A BY CONVOLUTION
! [INPUTS]:
! A >> A SEQUENCE CONTAINING NOISES
! [OUTPUTS]:
! SMOOTH >> SMOOTHENED SEQUENCE USING CONVOLUTION
! [UPDATES]:
! RE-CODED BY SANGJOON LEE @ NOV 20 2020
!=======================================================================
  REAL(P8),DIMENSION(:):: R
  REAL(P8),DIMENSION(SIZE(R),3):: DDC
  REAL(P8):: X0,X1,X2
  INTEGER:: NI,I
  NI = SIZE(R)
  DDC(1,:)=0
  DDC(NI,:)=0
  DO I=2,NI-1
  X0=R(I-1)
  X1=R(I  )
  X2=R(I+1)
  DDC(I,1) = 2/(X0-X1)/(X0-X2)
  DDC(I,2) = 2/(X1-X0)/(X1-X2)
  DDC(I,3) = 2/(X2-X0)/(X2-X1)
  ENDDO

  RETURN
  END FUNCTION DDC

!> ====================================================================
!> @brief COMPUTE INTEGRATION OF A FUNCTION OVER A DOMAIN
!>
!> @details
!> PERFORM INTEGRATION OF A FUNCTION: INT( F(R,PHI,Z) RDR DPHI DZ)
!> OVER THE ENTIRE UNBOUNDED CYLINDRICAL DOMAIN :
!>     0  <  R   < INFTY
!>     0  <  PHI < 2*PI
!>     0  <  Z   < ZLEN
!>
!> @param[in] F          >> INTEGRANT
!> @return    INTEG      >> INTEGRATION RESULT
!>
!> @author JINGE WANG
!> @date   OCT 2025
!> ====================================================================
FUNCTION INTEG_P(F)
!=======================================================================
IMPLICIT NONE
TYPE(SCALAR),INTENT(IN):: F
REAL(P8)::INTEG_P

TYPE(SCALAR):: F_COPY

IF(F%SPACE.NE.FFF_SPACE) THEN
  IF (MPI_RANK.EQ.0) WRITE(*,*) 'INTEG_P: NOT IN FFF_SPACE'
  STOP
ENDIF

IF(F%LN.NE.0.0) THEN
  WRITE(*,*) 'INTEGP: LOGTERM NOT ZERO'
  WRITE(*,*) 'LOGTERM=',F%LN
ENDIF

CALL ALLOCATE(F_COPY)
F_COPY = F
CALL RTRAN(F_COPY, 1)

IF ((F%INTH.EQ.0).AND.(F%INX.EQ.0)) THEN
  INTEG_P = 2.0_P8*PI*ZLEN*ELL2*DOT_PRODUCT(REAL(F%E(:NR,1,1))/(1-TFM%X(:NR))**2,TFM%W)
ELSE
  INTEG_P = 0
ENDIF
CALL MPI_ALLREDUCE(MPI_IN_PLACE, INTEG_P, 1, MPI_DOUBLE_PRECISION, &
      MPI_SUM, MPI_COMM_IVP, IERR)

CALL DEALLOCATE(F_COPY)

RETURN
END FUNCTION INTEG_P

!> ====================================================================
!> @brief COMPUTES SMOOTH TOP-HAT TRANSITION FUNCTION USING TANH.
!>
!> @details
!> THIS FUNCTION CREATES A SMOOTH TRANSITION FUNCTION THAT IS
!> APPROXIMATELY 1 INSIDE THE INTERVAL [-HLFWIDTH, +HLFWIDTH] AND
!> SMOOTHLY TRANSITIONS TO 0 OUTSIDE THIS REGION.
!>
!> THE FORMULA USED IS:
!> T(X)=.5*[TANH((X+HLFWIDTH)/STEEPNESS) - TANH((X-HLFWIDTH)/STEEPNESS)]
!>
!> @param[in] X          >> COORDINATE ARRAY TO EVALUATE FUNCTION
!> @param[in] HLFWIDTH   >> HALF-WIDTH OF THE ACTIVE REGION (L)
!> @param[in] STEEPNESS  >> TRANSITION SMOOTHNESS PARAMETER (S)
!>                          SMALLER VALUES -> SHARPER TRANSITIONS
!> @return    TOPHAT     >> TRANSITION FUNCTION VALUES in [0,1]
!>
!> @author JINGE WANG
!> @date   OCT 2025
!> ====================================================================
FUNCTION TOPHAT(X,HLFWIDTH,STEEPNESS)
! ======================================================================
  IMPLICIT NONE
  REAL(P8), INTENT(IN) :: X(:), HLFWIDTH, STEEPNESS
  REAL(P8) :: TOPHAT(SIZE(X))

  TOPHAT = 0.5D0 * (TANH((X+HLFWIDTH)/STEEPNESS) - TANH((X-HLFWIDTH)/STEEPNESS))

END FUNCTION TOPHAT

! ======================================================================
!> @brief Inspects and outputs field data to a file for analysis
!>
!> This subroutine examines a scalar field and writes its magnitude
!> squared values to an output file for inspection purposes. The
!> routine only processes distributed fields where both azimuthal 
!> and axial wavenumber starting indices (INTH and INX) are zero.
!>
!> @details The subroutine writes data in a structured format where
!> each line contains the current time followed by radial data for
!> selected vertical modes. The output is appended to 'inspect.output'
!> in the save directory. A MPI barrier ensures synchronization across
!> all processes after execution. Note that field%e is distributed
!> across processors.
!>
!> @param[in] field    Scalar field of type scalar containing the
!>                     distributed data to inspect
!> @param[in] nk       Optional integer specifying number of vertical
!>                     modes to save. If not provided, defaults to
!>                     minimum of 10 or total available modes
!>
!> @note Only processes fields with field%INTH = 0 and field%INX = 0
!> @note Output format: time on first line, then mode index followed
!>       by |field|² values
!> @note Uses MPI barrier for process synchronization
!> @note field%e is distributed across processors
!>
!> @author Jinge WANG
!> @date AUG 2025
subroutine inspect(field, nk)
!=======================================================================
   implicit none
   type(scalar), intent(in) :: field
   integer, intent(in), optional :: nk
   integer :: iunit, nrad, nsave, i, nn
   character(len=256) :: fname

   if ((field%INTH.eq.0).and.(field%INX.eq.0)) then

      nrad = size(field%e,1)
      if (present(nk)) then
         nsave = min(nk, size(field%e,3))
      else
         nsave = min(10, size(field%e,3))
      end if
      fname = trim(files%savedir)//'inspect.output'
      open(newunit=iunit, file=trim(fname), status='unknown', action='write', position='append')
      write(iunit,*) TIM%T
      do i = 1, nsave
         if (i.eq.1) then
            write(iunit,'(I4,1x,*(ES14.6,","))') i, (real(field%e(nn,1,i)), nn=1,nrad)
         else
            write(iunit,'(I4,1x,*(ES14.6,","))') i, (abs(field%e(nn,1,i)), nn=1,nrad)
         endif
      end do
      close(iunit)

   end if
   call mpi_barrier(MPI_COMM_IVP,IERR)
   return

end subroutine inspect

