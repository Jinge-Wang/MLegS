  SUBROUTINE STEP_BOUSSI_AB_CN(THIS, PSI, CHI, B)
!=======================================================================
  IMPLICIT NONE
  TYPE(SOLVER_T), INTENT(INOUT) :: THIS
  TYPE(SCALAR), INTENT(INOUT)   :: PSI, CHI, B

  TYPE(SCALAR):: PSIN,CHIN,BN
  TYPE(SCALAR):: PSI0,CHI0,B0
  REAL(P8):: DT

  DT = TIM%DT
  TIM%T = TIM%T + DT
  TIM%N = TIM%N + 1
  ADV%X = ADV%X + ADV%UX*DT
  ADV%Y = ADV%Y + ADV%UY*DT

  CALL ALLOCATE( PSIN )
  CALL ALLOCATE( CHIN )
  CALL ALLOCATE(   BN )

  CALL CALC_BOUSSI_FORCE(PSI,CHI,B,PSIN,CHIN,BN)

  CALL ALLOCATE( PSI0 )
  CALL ALLOCATE( CHI0 )
  CALL ALLOCATE(   B0 )

  PSI0 = PSI
  CHI0 = CHI
  B0 = B

  PSI%E  = PSI%E  +DT*(1.5D0*PSIN%E -0.5D0*THIS%N_PSI%E)
  PSI%LN = PSI%LN +DT*(1.5D0*PSIN%LN -0.5D0*THIS%N_PSI%LN)
  CHI%E  = CHI%E  +DT*(1.5D0*CHIN%E -0.5D0*THIS%N_CHI%E)
  CHI%LN = CHI%LN +DT*(1.5D0*CHIN%LN -0.5D0*THIS%N_CHI%LN)
  B%E    = B%E    +DT*(1.5D0*BN%E -0.5D0*THIS%N_B%E)

  THIS%N_PSI = PSIN
  THIS%N_CHI = CHIN
  THIS%N_B   = BN

  CALL DEALLOCATE( PSIN )
  CALL DEALLOCATE( CHIN )
  CALL DEALLOCATE(   BN )

  CALL CALC_BOUSSI_VISC_CN(PSI,CHI,B,PSI0,CHI0,B0)
  CALL DEALLOCATE( PSI0 )
  CALL DEALLOCATE( CHI0 )
  CALL DEALLOCATE(   B0 )

  CALL CALC_BOUSSI_HYPERV(PSI,CHI,B,DT)

  RETURN
  END SUBROUTINE STEP_BOUSSI_AB_CN
