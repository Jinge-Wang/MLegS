  SUBROUTINE CALC_INCOMP_VISC_BE(PSI,CHI,DT)
!=======================================================================
! [USAGE]: 
! APPLY DIFFUSION TO INCOMPRESSIBLE NAVIER-STOKES
! USING BACKWARD (IMPLICIT) EULER METHOD
! [PARAMETERS]:
! PSI, CHI >> TOROIDAL-POLOIDAL FIELDS IN A SCALAR-TYPE VARIABLE
! [DEPENDENCIES]:
! 1. VISC1 @ MOD_MARCH
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR):: PSI,CHI
  REAL(P8):: DT
  TYPE(SCALAR):: WK1

  IF(VISC%SW.NE.1) RETURN

  CALL ALLOCATE( WK1, FFF_SPACE )

  CALL VISC1(PSI, VISC%NU, DT, WK1)
  CALL VISC1(CHI, VISC%NU, DT, WK1)

  CALL DEALLOCATE( WK1 )

  RETURN
  END SUBROUTINE CALC_INCOMP_VISC_BE
!=======================================================================

  SUBROUTINE CALC_INCOMP_VISC_CN(PSI,CHI,PSIO,CHIO)
!=======================================================================
! [USAGE]: 
! APPLY DIFFUSION TO INCOMPRESSIBLE NAVIER-STOKES
! USING CRANK-NICHOLSON (IMPLICIT) METHOD
! [PARAMETERS]:
! PSI, CHI >> TOROIDAL-POLOIDAL FIELDS IN A SCALAR-TYPE VARIABLE
! PSIO, CHIO >> RESPECTIVE FIELD VARIABLES IN A PREVIOUS TIME STEP
! [DEPENDENCIES]:
! 1. VISC2 @ MOD_MARCH
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR), INTENT(INOUT):: PSI, CHI
  TYPE(SCALAR), INTENT(IN):: PSIO, CHIO
  
  TYPE(SCALAR):: WK1

  IF(VISC%SW.NE.1) RETURN

  CALL ALLOCATE( WK1, FFF_SPACE )

  CALL VISC2(PSI, PSIO, VISC%NU, TIM%DT, WK1)
  CALL VISC2(CHI, CHIO, VISC%NU, TIM%DT, WK1)

  CALL DEALLOCATE( WK1 )

  RETURN
  END SUBROUTINE CALC_INCOMP_VISC_CN
!=======================================================================

  SUBROUTINE CALC_BOUSSI_VISC_BE(PSI,CHI,B,DT)
!=======================================================================
! [USAGE]: 
! APPLY DIFFUSION TO BOUSSINESQ EQUATIONS
! USING BACKWARD (IMPLICIT) EULER METHOD
! [PARAMETERS]:
! B >> BUOYANCY FIELD IN A SCALAR-TYPE VARIABLE
! PSI, CHI >> TOROIDAL-POLOIDAL FIELDS IN A SCALAR-TYPE VARIABLE
! [DEPENDENCIES]:
! 1. VISC1 @ MOD_MARCH
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR):: PSI,CHI,B
  REAL(P8):: DT
  TYPE(SCALAR):: WK1

  IF(VISC%SW.NE.1) RETURN

  CALL ALLOCATE( WK1, FFF_SPACE )

  CALL VISC1(PSI, VISC%NU, DT, WK1)
  CALL VISC1(CHI, VISC%NU, DT, WK1)

  IF (BSNSQ%KAPPA .NE. 0.D0) THEN
    CALL VISC1(B, BSNSQ%KAPPA, DT, WK1)
  ENDIF

  CALL DEALLOCATE( WK1 )

  RETURN
  END SUBROUTINE CALC_BOUSSI_VISC_BE
!=======================================================================

  SUBROUTINE CALC_BOUSSI_VISC_CN(PSI,CHI,B,PSIO,CHIO,BO)
!=======================================================================
! [USAGE]: 
! APPLY DIFFUSION TO BOUSSINESQ EQUATIONS
! USING CRANK-NICHOLSON (IMPLICIT) METHOD
! [PARAMETERS]:
! B >> BUOYANCY FIELD IN A SCALAR-TYPE VARIABLE
! PSI, CHI >> TOROIDAL-POLOIDAL FIELDS IN A SCALAR-TYPE VARIABLE
! PSIO, CHIO, BO >> RESPECTIVE FIELD VARIABLES IN A PREVIOUS TIME STEP
! [DEPENDENCIES]:
! 1. VISC2 @ MOD_MARCH
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR), INTENT(INOUT):: PSI, CHI, B
  TYPE(SCALAR), INTENT(IN):: PSIO, CHIO, BO
  
  TYPE(SCALAR):: WK1

  IF(VISC%SW.NE.1) RETURN

  CALL ALLOCATE( WK1, FFF_SPACE )

  CALL VISC2(PSI, PSIO, VISC%NU, TIM%DT, WK1)
  CALL VISC2(CHI, CHIO, VISC%NU, TIM%DT, WK1)

  IF (BSNSQ%KAPPA .NE. 0.D0) THEN
    CALL VISC2(B, BO, BSNSQ%KAPPA, TIM%DT, WK1)
  ENDIF

  CALL DEALLOCATE( WK1 )

  RETURN
  END SUBROUTINE CALC_BOUSSI_VISC_CN
