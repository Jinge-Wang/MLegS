!> =====================================================================
!> @brief SETS UP HYPERVISCOSITY DAMPING FACTORS (LEGACY METHOD).
!>
!> @details
!> THIS SUBROUTINE CALCULATES THE HYPERVISCOSITY DAMPING FACTORS FOR
!> THE RADIAL (R), AZIMUTHAL (T), AND AXIAL (X) DIRECTIONS. THESE
!> FACTORS ARE APPLIED IN `HYPERV3` TO SELECTIVELY DAMP HIGH-WAVENUMBER
!> MODES AND ENSURE NUMERICAL STABILITY.
!>
!> THE METHOD FOLLOWS THESE STEPS:
!> 1. **DYNAMIC CUTOFF**: IT DETERMINES AN UPPER WAVENUMBER LIMIT
!>    (`NT_UP`, `NX_UP`) FOR "PHYSICAL" MODES BY INSPECTING THE
!>    DOMINANT WAVENUMBERS STORED IN `MONITORDATA%MK`.
!> 2. **FILTER CREATION**: IT CONSTRUCTS SMOOTH `TANH`-BASED FILTERS
!>    FOR EACH DIRECTION. THE FILTER PARAMETERS (CENTER, STEEPNESS)
!>    ARE HARD-CODED WITH "MAGIC NUMBERS".
!> 3. **COEFFICIENT CALCULATION**: IT COMPUTES HYPERVISCOSITY
!>    COEFFICIENTS (`NU_R`, `NU_T`, `NU_X`) TO NORMALIZE THE DAMPING,
!>    ENSURING THE HIGHEST MODES DECAY AT A CONTROLLED RATE.
!> 4. **DAMPING VECTORS**: IT CALCULATES THE FINAL EXPONENTIAL DAMPING
!>    FACTORS AND STORES THEM IN `VISC%HYPER_R`, `VISC%HYPER_T`, AND
!>    `VISC%HYPER_X`.
!>
!> THE ROUTINE ALSO WRITES THE RESULTING DAMPING VECTORS TO
!> `HYPERV.DAT` FOR DIAGNOSTIC PURPOSES.
!>
!> @note THIS IS A LEGACY IMPLEMENTATION WITH HARD-CODED PARAMETERS.
!> THE `HYP3SET` ROUTINE, WHICH USES THE MORE FLEXIBLE `HYP3MASK`
!> UTILITY, IS THE MODERN AND PREFERRED APPROACH. THIS ROUTINE IS
!> KEPT FOR REPRODUCIBILITY OF OLDER SIMULATION RESULTS.
!>
!> @author JINGE WANG
!> @date   (PRE-2024)
!> =====================================================================
SUBROUTINE HYP3SET_OLD()
! ======================================================================
  IMPLICIT NONE

  REAL(P8) :: NU_R, NU_T, NU_X
  INTEGER :: NT_UP, NX_UP

  REAL(P8) :: FACTOR_NU
  INTEGER :: II, JJ
  INTEGER :: FACTOR_UP, MONITOR_K(3)
  
  REAL(P8) :: FACTOR_R, FACTOR_T, FACTOR_X
  REAL(P8) :: INDEX_R(NRCHOP), INDEX_T(NTCHOPDIM), INDEX_X(NXCHOPDIM)
  REAL(P8) :: FILTER_R(NRCHOP), FILTER_T(NTCHOPDIM), FILTER_X(NXCHOPDIM)

  FACTOR_NU = 2.D0

  FACTOR_R = 1.D0
  FACTOR_T = 0.8
  FACTOR_X = 1.D0

  ! IF PERTURBATION/DISTURBANCE SIZE IS 0.1, ITS FACTOR_UP-TH HARMONICS
  ! WILL GET BELOW MACHINE ROUND-OFF ERROR
  FACTOR_UP = 24 ! DP
  NT_UP = MIN(FACTOR_UP*MAX(MAXVAL(MONITORDATA%MK(1:3,1)),1),NTCHOP-1)
  DO II = 1,3
    MONITOR_K(II) = MONITORDATA%MK(II,2)
    IF (MONITOR_K(II).GT.NXCHOP) MONITOR_K(II) = MONITOR_K(II) + 1 - 2*NXCHOP
    MONITOR_K(II) = ABS(MONITOR_K(II))
  ENDDO
  ! NX_UP = MIN(FACTOR_UP*MAX(MAXVAL(ABS(MONITORDATA%MK(1:3,2))),1),NXCHOP-1)
  NX_UP = MIN(FACTOR_UP*MAX(MAXVAL(MONITOR_K),1),NXCHOP-1)

  ! CREATE TANH FILTERS
  ! R: CENTER AT 1/2*NRCHOP WIDTH NRCHOP/4
  INDEX_R = (/(II, II=1,NRCHOP)/)
  FILTER_R = 0.5*(TANH((INDEX_R/REAL(NRCHOP)-1.D0/2.D0)*4.D0)+1.D0)
  ! T: CENTER AT 2/3*NT_UP WIDTH NT_UP/4
  INDEX_T = (/(II, II=0,NTCHOPDIM-1)/)
  FILTER_T = 0.5*(TANH((INDEX_T/REAL(NT_UP)-1.D0/2.D0)*5.D0)+1.D0)
  ! X: CENTER AT 2/3*NX_UP WIDTH NX_UP/4
  DO II=1,NXCHOPDIM
    INDEX_X(II) = II-1
    IF(II.GT.NXCHOP) THEN
        INDEX_X(II)=ABS(-(NXCHOPDIM-II+1))
    ENDIF
  ENDDO
  FILTER_X = 0.5*(TANH((INDEX_X/REAL(NX_UP)-1.D0/2.D0)*8.D0)+1.D0)

  ! FORCE THE LAST MODE TO DECAY AT EXP(-1*DT) WHILE ALSO USING TANH TO
  ! PREVENT CHANGES TO THE INTERESTED MODES
  NU_R = FACTOR_NU*(FACTOR_R*FILTER_R(NRCHOP))**(-VISC%P) 
  NU_T = FACTOR_NU*(FACTOR_T*FILTER_T(NTCHOPDIM))**(-VISC%P+2)
  NU_X = FACTOR_NU*(FACTOR_X*FILTER_X(NXCHOP))**(-VISC%P+2)

  ! CREATE HYPERV VECTORS
  ALLOCATE(VISC%HYPER_R(NRCHOP), VISC%HYPER_T(NTCHOPDIM), VISC%HYPER_X(NXCHOPDIM))
  VISC%HYPER_R = EXP(-(NU_R*TIM%DT)*(FILTER_R*INDEX_R/NRCHOP)**VISC%P)
  VISC%HYPER_T = EXP(-(NU_T*TIM%DT)*(FILTER_T*INDEX_T/NTCHOP)**(VISC%P-2))
  VISC%HYPER_X = EXP(-(NU_X*TIM%DT)*(FILTER_X*INDEX_X/NXCHOP)**(VISC%P-2))

  ! SAVE HYPER VECTORS
  IF (MPI_RANK.EQ.0) THEN
    open(UNIT=888,FILE='hyperv.dat',STATUS='UNKNOWN',ACTION='WRITE')
    ! write(888,518) NU_R, FILTER_R
    ! write(888,518) NU_T, FILTER_T
    ! write(888,518) NU_X, FILTER_X
    write(888,518) NU_R, VISC%HYPER_R
    write(888,518) NU_T, VISC%HYPER_T
    write(888,518) NU_X, VISC%HYPER_X
    close(888)
  518 FORMAT((E23.16),*(' ,',E23.16))
  ENDIF

  RETURN
END SUBROUTINE HYP3SET_OLD

!> =====================================================================
!> @brief SETS UP HYPERVISCOSITY DAMPING FACTORS (MODERN METHOD).
!>
!> @details
!> THIS SUBROUTINE CALCULATES THE 1D HYPERVISCOSITY DAMPING ARRAYS
!> FOR THE RADIAL (R), AZIMUTHAL (T), AND AXIAL (X) DIRECTIONS.
!> IT USES THE `HYP3MASK` UTILITY TO CREATE SMOOTH, SCALE-SELECTIVE
!> FILTERS. THE FINAL DAMPING FACTORS ARE STORED IN THE GLOBAL
!> `VISC` TYPE FOR USE IN THE `HYPERV3` SUBROUTINE.
!>
!> THE DAMPING FACTOR FOR EACH MODE IS CALCULATED AS:
!> `EXP(-DT * MASK * NU * (K**2)**(P/2))`
!>
!> THIS ROUTINE IS THE PREFERRED METHOD FOR SETTING UP HYPERVISCOSITY
!> DUE TO ITS FLEXIBILITY COMPARED TO THE LEGACY `HYP3SET_OLD` ROUTINE.
!>
!> @param[in] NU_R HYPERVISCOSITY COEFFICIENT FOR RADIAL DIRECTION.
!> @param[in] NU_T HYPERVISCOSITY COEFFICIENT FOR AZIMUTHAL DIRECTION.
!> @param[in] NU_X HYPERVISCOSITY COEFFICIENT FOR AXIAL DIRECTION.
!>
!> @author JINGE WANG
!> @date   SEP 2025
!> =====================================================================
SUBROUTINE HYP3SET( NU_R, NU_T, NU_X )
! ======================================================================
  IMPLICIT NONE
  REAL(P8), INTENT(IN) :: NU_R, NU_T, NU_X

  ! LOCAL VARIABLES
  INTEGER :: NN, MM, KK
  REAL(P8), ALLOCATABLE :: MASK_R(:), MASK_T(:), MASK_X(:)
  
  ! --- CREATE THE 1D DEALIASING MASKS FOR EACH DIRECTION ---
  ALLOCATE(MASK_R(NRCHOP), MASK_T(NTCHOPDIM), MASK_X(NXCHOPDIM))
  CALL HYP3MASK([(REAL(NN-1, P8), NN=1, NRCHOP)], MASK_R)
  CALL HYP3MASK(REAL(M, P8), MASK_T)
  CALL HYP3MASK(ABS(AK(1,:)), MASK_X)
  
  ! --- CALCULATE THE 1D FILTER ARRAYS ---
  IF (.NOT. ALLOCATED(VISC%HYPER_R)) THEN
    ALLOCATE(VISC%HYPER_R(NRCHOP), VISC%HYPER_T(NTCHOPDIM), VISC%HYPER_X(NXCHOPDIM))
  END IF
  DO NN = 1, NRCHOP
    VISC%HYPER_R(NN) = EXP(-TIM%DT * MASK_R(NN) * NU_R * (REAL((NN-1)*NN,P8))**(VISC%P/2))
  END DO
  DO MM = 1, NTCHOPDIM
    VISC%HYPER_T(MM) = EXP(-TIM%DT * MASK_T(MM) * NU_T * (REAL(M(MM)**2,P8))**(VISC%P/2))
  END DO
  DO KK = 1, NXCHOPDIM
    VISC%HYPER_X(KK) = EXP(-TIM%DT * MASK_X(KK) * NU_X * (AK(1,KK)**2)**(VISC%P/2))
  END DO

  DEALLOCATE(MASK_R, MASK_T, MASK_X)

  ! SAVE HYPER VECTORS
  IF (MPI_RANK.EQ.0) THEN
    open(UNIT=888,FILE='hyperv.dat',STATUS='UNKNOWN',ACTION='WRITE')
    ! write(888,518) NU_R, FILTER_R
    ! write(888,518) NU_T, FILTER_T
    ! write(888,518) NU_X, FILTER_X
    write(888,518) NU_R, VISC%HYPER_R
    write(888,518) NU_T, VISC%HYPER_T
    write(888,518) NU_X, VISC%HYPER_X
    close(888)
  518 FORMAT((E23.16),*(' ,',E23.16))
  ENDIF  
END SUBROUTINE HYP3SET

!> =====================================================================
!> @brief GENERATE A SMOOTH MASK FOR HYPERVISCOSITY FILTERING
!>
!> THIS SUBROUTINE CREATES A SMOOTH TRANSITION MASK THAT IS ZERO FOR
!> WAVENUMBERS BELOW A THRESHOLD AND SMOOTHLY TRANSITIONS TO 1 FOR
!> HIGHER WAVENUMBERS USING A HYPERBOLIC TANGENT FUNCTION.
!>
!> @param[in] K_VALS ARRAY OF WAVENUMBER VALUES TO GENERATE MASK FOR
!> @param[out] K_MASK ARRAY OF MASK VALUES (0 TO 1) FOR K_VALS
!> @param[in] RATIO OPTIONAL "SAFE" RATIO FOR FILTERING THRESHOLD
!>                 (DEFAULT: 2/3)
!>
!> @details
!> MASK FUNCTION:
!> - FOR K/K_MAX < RATIO: MASK = 0
!> - FOR K/K_MAX >= RATIO: MASK = TANH(A*(K/K_MAX - RATIO))/TANH(A)
!>   WHERE A IS THE STEEPNESS PARAMETER (3.0)
!>
!> NOTES:
!> - STEEPNESS PARAMETER CONTROLS TRANSITION SHARPNESS
!> - SAFETY CHECK PREVENTS DIVISION BY ZERO IF K_MAX IS SMALL
!>
!> @author JINGE WANG
!> @date SEP 2025
!> =====================================================================
SUBROUTINE HYP3MASK(K_VALS, K_MASK, RATIO)
!=======================================================================
  IMPLICIT NONE
  REAL(P8), INTENT(IN)          :: K_VALS(:)
  REAL(P8), INTENT(OUT)         :: K_MASK(:)
  REAL(P8), INTENT(IN), OPTIONAL :: RATIO ! THE "SAFE" RATIO
  
  REAL(P8) :: EFFECTIVE_RATIO, K_MAX, K_NORM, X_RAMP
  REAL(P8), PARAMETER :: STEEPNESS_A = 3.0D0
  INTEGER :: I

  IF (PRESENT(RATIO)) THEN
    EFFECTIVE_RATIO = RATIO
  ELSE
    EFFECTIVE_RATIO = 2.0D0 / 3.0D0 ! DEFAULT VALUE
  END IF
  
  K_MAX = MAXVAL(K_VALS)
  IF (K_MAX < 1.0D-12) K_MAX = 1.0D0 ! AVOID DIVISION BY ZERO

  DO I = 1, SIZE(K_VALS)
    K_NORM = K_VALS(I) / K_MAX
    IF (K_NORM < EFFECTIVE_RATIO) THEN
      K_MASK(I) = 0.0D0
    ELSE
      X_RAMP = (K_NORM - EFFECTIVE_RATIO) / (1.0D0 - EFFECTIVE_RATIO)
      K_MASK(I) = TANH(STEEPNESS_A * X_RAMP) / TANH(STEEPNESS_A)
    END IF
  END DO
    
END SUBROUTINE HYP3MASK

!> =====================================================================
!> @brief ADJUSTS DIRECTIONAL HYPERVISCOSITY FOR THE `HYPERV3` SCHEME.
!>
!> @details
!> THIS SUBROUTINE DYNAMICALLY ADJUSTS THE HYPERVISCOSITY COEFFICIENTS
!> (`NU_R`, `NU_T`, `NU_X`) BASED ON THE SHAPE OF THE ENERGY SPECTRA.
!> IT IS THE ADAPTIVE COUNTERPART TO `HYP3SET` FOR `VISC%SW=3`.
!>
!> THE ADJUSTMENT LOGIC IS AS FOLLOWS:
!> 1.  **SPECTRAL ANALYSIS**: IT COMPUTES THE ENERGY SPECTRA FOR THE
!>     AZIMUTHAL (`M`) AND AXIAL (`K`) DIRECTIONS USING `ENEMON`.
!> 2.  **CURVATURE CALCULATION**: IT MEASURES THE CURVATURE OF THE
!>     LOG-SCALE ENERGY SPECTRA TAILS. A POSITIVE CURVATURE INDICATES
!>     AN ENERGY BOTTLENECK AND POTENTIAL NUMERICAL INSTABILITY.
!> 3.  **PD CONTROLLER**: A PROPORTIONAL-DERIVATIVE (PD) CONTROLLER
!>     ADJUSTS `NU_T` AND `NU_X` BASED ON THEIR RESPECTIVE SPECTRAL
!>     CURVATURES.
!> 4.  **RADIAL COUPLING**: SINCE A RADIAL ENERGY SPECTRUM IS NOT
!>     AVAILABLE, `NU_R` IS ADJUSTED BASED ON A WEIGHTED AVERAGE OF
!>     THE `M` AND `K` SPECTRAL CURVATURES.
!>
!> @param[in]     PSI  >> TOROIDAL SCALAR FIELD IN FFF_SPACE.
!> @param[in]     CHI  >> POLOIDAL SCALAR FIELD IN FFF_SPACE.
!> @param[inout]  NU_R >> HYPERVISCOSITY COEFFICIENT FOR RADIAL DIR.
!> @param[inout]  NU_T >> HYPERVISCOSITY COEFFICIENT FOR AZIMUTHAL DIR.
!> @param[inout]  NU_X >> HYPERVISCOSITY COEFFICIENT FOR AXIAL DIR.
!>
!> @author JINGE WANG
!> @date   SEP 2025
!> =====================================================================
SUBROUTINE HYP3ADJ(PSI, CHI, NU_R, NU_T, NU_X)
! ======================================================================
  IMPLICIT NONE
  TYPE(SCALAR), INTENT(IN) :: PSI, CHI
  REAL(P8), INTENT(INOUT)  :: NU_R, NU_T, NU_X

  REAL(P8), DIMENSION(:), ALLOCATABLE :: EM, EK
  REAL(P8), DIMENSION(:), ALLOCATABLE :: SPM, SPK
  REAL(P8) :: SUMM, SUMK, SUMR, FAC, DX, X, SUM_M_CURVE, SUM_K_CURVE, SUM_R_CURVE, SUM_R_CURVE_O
  INTEGER  :: IS, IE, NM, NK, I

  ALLOCATE(EM(NTCHOP), EK(NXCHOP))

  CALL CHOPSET(2)
  CALL ENEMON(PSI, CHI, EM, EK)
  CALL CHOPSET(-2)

  ! --- AZIMUTHAL SPECTRUM ANALYSIS ---
  IS = SIZE(EM) / 3
  IE = SIZE(EM) - 2
  NM = IE - IS + 1
  IF (NM > 1) THEN
    ALLOCATE(SPM(NM))
    SPM = LOG10(EM(IS:IE))
    SUM_M_CURVE = 0.0_P8
    DX = 2.0D0 / (NM - 1) ! DOT PRODUCT WITH LEGENDRE POLYNOMIAL P_2(X)
    DO I = 1, NM
      X = -1.0_P8 + 2.0_P8 * (I - 1) / (NM - 1)
      FAC = 1.0_P8
      IF (I == 1 .OR. I == NM) FAC = 0.5_P8
      SUM_M_CURVE = SUM_M_CURVE + FAC * SPM(I) * DX * SQRT(5.0D0/8.0D0) * (3.0_P8 * X**2 - 1.0_P8)
    END DO
    DEALLOCATE(SPM)
  ELSE
    SUM_M_CURVE = 0.0_P8
  END IF

  ! --- AXIAL SPECTRUM ANALYSIS ---
  IS = SIZE(EK) / 3
  IE = SIZE(EK)
  NK = IE - IS + 1
  IF (NK > 1) THEN
    ALLOCATE(SPK(NK))
    SPK = LOG10(EK(IS:IE))
    SUM_K_CURVE = 0.0_P8
    DX = 2.0D0 / (NK - 1)
    DO I = 1, NK
      X = -1.0_P8 + 2.0_P8 * (I - 1) / (NK - 1)
      FAC = 1.0_P8
      IF (I == 1 .OR. I == NK) FAC = 0.5_P8
      SUM_K_CURVE = SUM_K_CURVE + FAC * SPK(I) * DX * SQRT(5.0D0/8.0D0) * (3.0_P8 * X**2 - 1.0_P8)
    END DO
    DEALLOCATE(SPK)
  ELSE
    SUM_K_CURVE = 0.0_P8
  END IF

  ! --- INITIALIZATION ON FIRST CALL ---
  IF (VISC%NUPB < 0.0D0) THEN
    VISC%SUMMO = SUM_M_CURVE
    VISC%SUMKO = SUM_K_CURVE
    VISC%NUPB = 0.2_P8 / (1.5D0 * NRCHOP**2 / ELL**2)**(VISC%P / 2.0_P8)
  ENDIF

  ! --- ADJUST NU_T, NU_X, AND NU_R BASED ON SPECTRAL CURVATURE ---
  ! AZIMUTHAL ADJUSTMENT
  SUMM = 2.0_P8 * (SUM_M_CURVE - VISC%SUMMO) + SUM_M_CURVE + 0.2_P8 ! PD-LIKE CONTROL
  SUMM = MIN(3.0D0, MAX(-0.5D0, 1.5_P8 * SUMM))
  NU_T = (1.0_P8 + SUMM) * NU_T
  IF (NU_T < VISC%NUPB) NU_T = VISC%NUPB

  ! AXIAL ADJUSTMENT
  SUMK = 2.0_P8 * (SUM_K_CURVE - VISC%SUMKO) + SUM_K_CURVE + 0.2_P8
  SUMK = MIN(3.0D0, MAX(-0.5D0, 1.5_P8 * SUMK))
  NU_X = (1.0_P8 + SUMK) * NU_X
  IF (NU_X < VISC%NUPB) NU_X = VISC%NUPB

  ! RADIAL ADJUSTMENT
  ! COUPLED ADJUSTMENT BASED ON AZIMUTHAL AND AXIAL CURVATURE
  IF (SUM_M_CURVE > SUM_K_CURVE) THEN ! GIVES MORE WEIGHT TO THE MORE UNSTABLE DIRECTION
    SUM_R_CURVE_O = (3.0_P8 * VISC%SUMMO + VISC%SUMKO) / 4.0_P8
    SUM_R_CURVE   = (3.0_P8 * SUM_M_CURVE + SUM_K_CURVE) / 4.0_P8
  ELSE
    SUM_R_CURVE_O = (VISC%SUMMO + 3.0_P8 * VISC%SUMKO) / 4.0_P8
    SUM_R_CURVE   = (SUM_M_CURVE + 3.0_P8 * SUM_K_CURVE) / 4.0_P8
  ENDIF
  SUMR = 2.0_P8 * (SUM_R_CURVE - SUM_R_CURVE_O) + SUM_R_CURVE + 0.2_P8
  SUMR = MIN(3.0D0, MAX(-0.5D0, 1.5_P8 * SUMR))
  NU_R = (1.0_P8 + SUMR) * NU_R
  IF (NU_R < VISC%NUPB) NU_R = VISC%NUPB

  IF (MPI_RANK == 0) THEN
    WRITE(6, 60) TIM%T, NU_R, NU_T, NU_X, SUM_M_CURVE, SUM_K_CURVE
60  FORMAT('HYP3ADJ:T=',1PE10.3,' NU_R=',1PE10.3,' NU_T=',1PE10.3,' NU_X=',1PE10.3, &
           ' SUMM=',1PE10.3,' SUMK=',1PE10.3)
  END IF

  VISC%SUMMO = SUM_M_CURVE
  VISC%SUMKO = SUM_K_CURVE

  DEALLOCATE(EM, EK)

  RETURN
END SUBROUTINE HYP3ADJ

!> =====================================================================
!> @brief APPLIES A 3D SPECTRAL HYPERVISCOSITY FILTER.
!>
!> @details
!> THIS SUBROUTINE APPLIES A PRE-CALCULATED HYPERVISCOSITY FILTER
!> TO THE SPECTRAL COEFFICIENTS OF THE `PSI`, `CHI`, AND `B` FIELDS.
!> IT IS ONLY ACTIVE WHEN `VISC%SW` IS SET TO 3.
!>
!> THE FILTERING IS DONE BY A DIRECT, ELEMENT-WISE MULTIPLICATION
!> OF THE SPECTRAL DATA WITH THE DAMPING FACTORS STORED IN THE
!> `VISC%HYPER_R`, `VISC%HYPER_T`, AND `VISC%HYPER_X` ARRAYS.
!>
!> IF THE DAMPING ARRAYS ARE NOT YET ALLOCATED, THIS ROUTINE WILL
!> AUTOMATICALLY CALL `HYP3SET` TO INITIALIZE THEM.
!>
!> @param[inout] PSI TOROIDAL SCALAR FIELD TO BE DAMPED.
!> @param[inout] CHI POLOIDAL SCALAR FIELD TO BE DAMPED.
!> @param[inout] B   BUOYANCY SCALAR FIELD TO BE DAMPED.
!>
!> @author JINGE WANG
!> @date   SEP 2025
!> =====================================================================
SUBROUTINE HYPERV3(PSI,CHI,B)
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR):: PSI,CHI,B
  INTEGER:: MM, KK, NN

  IF (VISC%SW.EQ.3) THEN

    IF (.NOT. ALLOCATED(VISC%HYPER_R)) THEN
      VISC%NUP_R = VISC%NUP
      VISC%NUP_T = VISC%NUP
      VISC%NUP_X = VISC%NUP
      CALL HYP3SET(VISC%NUP_R, VISC%NUP_T, VISC%NUP_X)
    ELSEIF ((VISC%ADJSW .NE. 0).AND.(MOD(TIM%N, VISC%ADJINT) .EQ. 0)) THEN
      CALL HYP3ADJ(PSI, CHI, VISC%NUP_R, VISC%NUP_T, VISC%NUP_X)
      CALL HYP3SET(VISC%NUP_R, VISC%NUP_T, VISC%NUP_X)
    END IF

    DO KK = 1,SIZE(PSI%E,3); DO MM = 1,SIZE(PSI%E,2)

        NN = NRCHOPS(MM + PSI%INTH)
        PSI%E(:NN,MM,KK) = PSI%E(:NN,MM,KK)*VISC%HYPER_R(:NN)*VISC%HYPER_T(MM+PSI%INTH)*VISC%HYPER_X(KK+PSI%INX)
        CHI%E(:NN,MM,KK) = CHI%E(:NN,MM,KK)*VISC%HYPER_R(:NN)*VISC%HYPER_T(MM+PSI%INTH)*VISC%HYPER_X(KK+PSI%INX)
          B%E(:NN,MM,KK) =   B%E(:NN,MM,KK)*VISC%HYPER_R(:NN)*VISC%HYPER_T(MM+PSI%INTH)*VISC%HYPER_X(KK+PSI%INX)

    ENDDO; ENDDO
    
  ENDIF

  RETURN
END SUBROUTINE

