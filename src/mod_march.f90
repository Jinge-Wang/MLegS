  SUBROUTINE FREEADJ()
!=======================================================================
! [USAGE]: 
! ADJUST FREESTREAM VELOCITY SUCH THAT THE CENTER OF VORTICITY
! DISTRIBUTION IS AT THE CENTER OF THE COMPUTATIONAL DOMAIN.
! [PARAMETERS]:
! N/A
! [UPDATES]:
! RE-CODED BY SANGJOON LEE @ NOV 20 2020
! MPI-ED BY JINGE WANG @ SEP 29 2021
!=======================================================================
  REAL(P8):: FREEDT,VX,VY

  FREEDT = ADV%INT*TIM%DT
  VX = (ADV%X1-ADV%X0)/(ADV%T1-ADV%T0) ! VELOCITY OF THE CENTER OF VORTEX
  VY = (ADV%Y1-ADV%Y0)/(ADV%T1-ADV%T0)
  ADV%UX = ADV%UX - ADV%X1/FREEDT - VX ! CANCEL OUT THE MOTION OF THE VORTEX CENTER
  ADV%UY = ADV%UY - ADV%Y1/FREEDT - VY
  
  NADD%U = SQRT(ADV%UX**2+ADV%UY**2) ! ADVECTIVE VELOCITY IN R-THETA PLANE
  
  IF(NADD%U.EQ.0.0) THEN
    NADD%ANG = 0.0
  ELSE
    IF(ADV%UY >= 0) THEN
      NADD%ANG = ACOS(ADV%UX/NADD%U)
    ELSE 
      NADD%ANG = -1.0*ACOS(ADV%UX/NADD%U)
    ENDIF
  ENDIF

  IF (MPI_RANK.EQ.0) THEN
    WRITE(6,60) TIM%N,TIM%T
60   FORMAT('FREEADJ: TIM%N=',I5,' TIM%T=',F10.6)
    WRITE(6,61) ADV%UX,ADV%UY,ADV%UZ
61   FORMAT('FREEADJ: ADV%UX=',E18.10,'  UY=',E18.10,' UZ=',E18.10)
    WRITE(6,62) NADD%U,NADD%ANG
62   FORMAT('FREEADJ: NADD%U=',E18.10,' ANG=',E18.10)
  ENDIF

  RETURN
  END SUBROUTINE FREEADJ

!> ====================================================================
!> @brief INITIALIZES SPONGE LAYER DAMPING COEFFICIENTS.
!>
!> @details
!> THIS SUBROUTINE INITIALIZES THE SPONGE LAYER BY COMPUTING SMOOTH
!> TWO-SIDED TRANSITION FUNCTION FOR AXIAL DIRECTION:
!> - DOMAIN: z in [0, ZLEN]
!> - ACTIVE REGION: |z - ZLEN/2| < (RATIO_L x ZLEN)/2
!> - TRANSITION WIDTH: RATIO_S x ZLEN
!>
!> THE DAMPING TIMESCALE IS SET TO N_TAU TIMESTEPS, AND THE
!> TRANSITION FUNCTIONS ARE PRECOMPUTED AND STORED IN RMV%TOPHAT_X
!> FOR EFFICIENT APPLICATION DURING TIME-STEPPING.
!>
!> @note ONLY OPERATES WHEN RMV%SW = 2. THE SPONGE LAYER PROVIDES
!>       OUTFLOW BOUNDARY CONDITIONS BY SMOOTHLY DAMPING DISTURBANCES
!>       THAT APPROACH THE DOMAIN BOUNDARIES.
!>
!> @author JINGE WANG  
!> @date   OCT 2025
!> ====================================================================
SUBROUTINE SPNGINIT()
! ======================================================================
  IMPLICIT NONE
  
  INTEGER:: N_TAU = 10
  REAL(P8):: RATIO_L = 0.86, RATIO_S = 0.04
  REAL(P8):: HLFWIDTH_X, STEEPNESS_X, HLFZ
  INTEGER:: LX_IND, SX_IND

  ! REAL(P8):: HLFWIDTH_R, STEEPNESS_R
  ! INTEGER:: LR_IND, SR_IND, R_IND
  ! IF (.NOT.ALLOCATED(RMV%TOPHAT_R)) ALLOCATE(RMV%TOPHAT_R(NDIMR))
  ! LR_IND = INT(RATIO_L*REAL(NR,P8))
  ! SR_IND = MIN(INT((RATIO_L + RATIO_S)*REAL(NR,P8)),NR)
  ! HLFWIDTH_R = REAL(LR_IND)
  ! STEEPNESS_R = REAL(SR_IND) - HLFWIDTH_R
  ! RMV%TOPHAT_R = 0.D0
  ! RMV%TOPHAT_R(:NR) = TOPHAT(REAL([(R_IND, R_IND = 0, NR-1)]), HLFWIDTH_R, STEEPNESS_R)

  IF (RMV%SW.NE.2) RETURN

  HLFZ = ZLEN/2.D0
  RMV%TAU = N_TAU*TIM%DT
  HLFWIDTH_X = ZLEN*RATIO_L/2.D0
  STEEPNESS_X = ZLEN*RATIO_S

  IF (.NOT.ALLOCATED(RMV%TOPHAT_X)) ALLOCATE(RMV%TOPHAT_X(NDIMX))
  RMV%TOPHAT_X = 0.D0
  RMV%TOPHAT_X(:NX) = TOPHAT(TFM%Z(:NX)-HLFZ, HLFWIDTH_X, STEEPNESS_X)

  RETURN
END SUBROUTINE SPNGINIT

