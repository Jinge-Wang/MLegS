  SUBROUTINE INITIALIZE(THIS, PSI, CHI, B)
!=======================================================================
! [USAGE]: 
! CONFIGURE THE SOLVER FOR TIME STEPPING AND ALLOCATE HISTORY VARIABLES
!=======================================================================
  IMPLICIT NONE
  CLASS(SOLVER_T), INTENT(INOUT) :: THIS
  TYPE(SCALAR), INTENT(INOUT)   :: PSI, CHI, B

  CALL MPRINT('SOLVER STARTED')
  IF (MPI_RANK.EQ.0) CALL PRINT_REAL_TIME()

  CALL MPRINT('SOLVER: Initializing and performing startup step...')
  THIS%TIME_START = MPI_WTIME()

  CALL MSAVE(PSI, TRIM(ADJUSTL(FILES%SAVEDIR)) // FILES%PSI0)
  CALL MSAVE(CHI, TRIM(ADJUSTL(FILES%SAVEDIR)) // FILES%CHI0)
  CALL MSAVE(B, TRIM(ADJUSTL(FILES%SAVEDIR)) // FILES%B0)

  IF (VISC%SW.GT.1) THEN
    CALL MPRINT('SOLVER: Initializing hyperviscosity...')
    SELECT CASE(VISC%SW)
      CASE(2) ! DEL2^{P/2} TYPE HYPERVISCOSITY
        ! TODO: Implement old HYPERV subroutine (VISC%SW=2)
        ! HYPERV uses higher-order del2 and does not require initialization
        ! This is a reminder for future implementation.
        CALL MPRINT('SOLVER: hyperviscosity option 2 not supported yet.')
        IF (.NOT. BSNSQ%ADAMS) THEN
          CALL MPRINT('SOLVER: ETD scheme MUST use velocity-based hyperviscosity.')
          CALL MPI_ABORT(MPI_COMM_IVP,ERR_FLAGS%SOLVER,IERR)
        END IF
      CASE(3) ! EXPONENTIAL TYPE HYPERVISCOSITY
        CALL HYP3INIT(.TRUE.) ! TODO: Allow optional b variable in the future
      CASE DEFAULT
        CALL MPRINT('SOLVER: hyperviscosity option not supported yet.')
    END SELECT
  ENDIF

  IF (RMV%SW.NE.0) THEN
    SELECT CASE(RMV%SW)
      CASE(2) ! AXIAL SPONGE LAYER
        CALL MPRINT('SOLVER: Initializing axial sponge layer...')
        CALL SPNGINIT()
    END SELECT
  ENDIF

  IF (BSNSQ%ADAMS) THEN
    CALL MPRINT('SOLVER: bsnsq%adams=T. Configuring AB2-CN scheme.')
    CALL ALLOCATE(THIS%N_B, FFF_SPACE)
    CALL ALLOCATE(THIS%N_PSI, FFF_SPACE)
    CALL ALLOCATE(THIS%N_CHI, FFF_SPACE)
    CALL RICH_BOUSSI_FE_BE(THIS, PSI, CHI, B)
  ELSE
    CALL MPRINT('SOLVER: bsnsq%adAMS=F. Configuring ETD2-CN scheme.')
    ALLOCATE(THIS%ETD_FULL, THIS%ETD_HALF)
    CALL CALC_BOUSSI_ETD_OP(THIS%ETD_FULL, TIM%DT, ECHO= .TRUE.)
    CALL CALC_BOUSSI_ETD_OP(THIS%ETD_HALF, TIM%DT*0.5D0, ECHO= .FALSE.)
    CALL ALLOCATE(THIS%N_B, PFF_SPACE)
    CALL ALLOCATE(THIS%R_N_R, PFF_SPACE)
    CALL ALLOCATE(THIS%R_N_R, PFF_SPACE)
    CALL ALLOCATE(THIS%R_N_P, PFF_SPACE)
    CALL ALLOCATE(THIS%N_Z, PFF_SPACE)
    CALL ALLOCATE(THIS%R_PI_R, PFF_SPACE)
    CALL ALLOCATE(THIS%R_PI_P, PFF_SPACE)
    CALL ALLOCATE(THIS%PI_Z, PFF_SPACE)
    CALL RICH_BOUSSI_ETDFE_BE(THIS, PSI, CHI, B)
  ENDIF

  CALL MPRINT('SOLVER: Initialization and Richardson startup complete.')

  RETURN
  END SUBROUTINE INITIALIZE
!=======================================================================

  SUBROUTINE TIME_STEPPING(THIS, PSI, CHI, B)
!=======================================================================
! [USAGE]: 
! PERFORM A SINGLE TIME-STEPPING
!=======================================================================
  IMPLICIT NONE
  CLASS(SOLVER_T), INTENT(INOUT) :: THIS
  TYPE(SCALAR), INTENT(INOUT)   :: PSI, CHI, B

  IF (BSNSQ%ADAMS) THEN
    CALL STEP_BOUSSI_AB_CN(THIS, PSI, CHI, B)
  ELSE
    CALL STEP_BOUSSI_ETDAB_CN(THIS, PSI, CHI, B)
  ENDIF

  ! DIAGNOSTIC
  CALL DIAGNOST(PSI, CHI)
  IF(MOD(TIM%N,DIAGV%IT1).EQ.0) THEN
    CALL CALC_BOUSSI_ENERGY(PSI, CHI, B, TIM%T, FILES%SAVEDIR)

    ! DEBUG: SAVE M = 0, K = 0 MODES
    CALL INSPECT(PSI,1)
    CALL INSPECT(CHI,1)
    CALL INSPECT(B,1)
  ENDIF

  ! VORTICITY REMOVAL
  ! TODO: RMV%SW = 2 ALSO TURN ON AXIAL SPONGE LAYER WHICH IS IMPLEMENTED FOR ETD
  !       BUT NOT FOR AB-CN. NEED TO ADD SUPPORT FOR AB-CN IN THE FUTURE.
  IF ((RMV%SW .NE. 0) .AND. (MOD(TIM%N,RMV%INT) .EQ. 0)) THEN
    CALL REMOVE(PSI, CHI, B)
    ! RESTART SIMULATION USING RICHARDSON (FORWARD ONE STEP)
    IF (BSNSQ%ADAMS) THEN
      CALL RICH_BOUSSI_FE_BE(THIS, PSI, CHI, B)
    ELSE
      CALL RICH_BOUSSI_ETDFE_BE(THIS, PSI, CHI, B)
    ENDIF
    ! DIAGNOSTIC AFTER REMOVAL
    CALL DIAGNOST(PSI, CHI)
    IF(MOD(TIM%N,DIAGV%IT1).EQ.0) THEN
      CALL CALC_BOUSSI_ENERGY(PSI, CHI, B, TIM%T, FILES%SAVEDIR)
    ENDIF
  ENDIF

  ! HYPERVISCOSITY ADJUSTMENT
  IF ((VISC%ADJSW .NE. 0) .AND. (MOD(TIM%N, VISC%ADJINT) .EQ. 0)) THEN
   ! TODO: Need to add case for VISC%SW=2 in the future (use hypadj and need to add support for b)
    CALL HYP3ADJ(PSI, CHI, B)
    CALL HYP3SET(VISC%NUP_R, VISC%NUP_T, VISC%NUP_X, VISC%HYPERV_R, VISC%HYPERV_T, VISC%HYPERV_X)
    CALL HYP3SET(VISC%KAPPAP_R, VISC%KAPPAP_T, VISC%KAPPAP_X, VISC%HYPERD_R, VISC%HYPERD_T, VISC%HYPERD_X)
  ENDIF

  ! SAVE OUTPUT
  IF ((FILES%T(FILES%N) .LE. TIM%T) .AND. (THIS%SAVE_VARIABLE)) THEN
    CALL MSAVE(PSI, TRIM(ADJUSTL(FILES%SAVEDIR)) // FILES%PSI(FILES%N))
    CALL MSAVE(CHI, TRIM(ADJUSTL(FILES%SAVEDIR)) // FILES%CHI(FILES%N))
    CALL MSAVE(B, TRIM(ADJUSTL(FILES%SAVEDIR)) // FILES%B(FILES%N))
    FILES%N = FILES%N + 1

    ! Stop the simulation once the last file is saved
    IF (FILES%N > FILES%NE) THIS%SAVE_VARIABLE = .FALSE.
  ENDIF

  RETURN
  END SUBROUTINE TIME_STEPPING
!=======================================================================

  SUBROUTINE FINALIZE(THIS, PSI, CHI, B)
!=======================================================================
  USE MOD_MISC, ONLY: PRINT_REAL_TIME
  IMPLICIT NONE
  CLASS(SOLVER_T), INTENT(INOUT) :: THIS
  TYPE(SCALAR), INTENT(INOUT), OPTIONAL :: PSI, CHI, B
  REAL(P8):: TIME_END

  CALL MPRINT('SOLVER: Deallocating ...')

  ! Free allocated memory
  IF (ALLOCATED(THIS%ETD_FULL)) DEALLOCATE(THIS%ETD_FULL)
  IF (ALLOCATED(THIS%ETD_HALF)) DEALLOCATE(THIS%ETD_HALF)
  IF (ALLOCATED(BSNSQ%RUP0)) DEALLOCATE(BSNSQ%RUP0,BSNSQ%OZ0)
  CALL DEALLOCATE(THIS%N_B)
  IF (BSNSQ%ADAMS) THEN
    CALL DEALLOCATE(THIS%N_PSI)
    CALL DEALLOCATE(THIS%N_CHI)
  ELSE
    CALL DEALLOCATE(THIS%R_N_R)
    CALL DEALLOCATE(THIS%R_N_P)
    CALL DEALLOCATE(THIS%N_Z  )
    CALL DEALLOCATE(THIS%R_PI_R)
    CALL DEALLOCATE(THIS%R_PI_P)
    CALL DEALLOCATE(THIS%PI_Z )
  ENDIF

  IF (PRESENT(PSI)) CALL DEALLOCATE(PSI)
  IF (PRESENT(CHI)) CALL DEALLOCATE(CHI)
  IF (PRESENT(B)) CALL DEALLOCATE(B)

  IF (VISC%SW.EQ.3) CALL HYP3FREE()
  IF (RMV%SW.EQ.2) CALL SPNGFREE()

  CALL MPRINT('SOLVER: ')
  TIME_END = MPI_WTIME()
  IF (MPI_RANK.eq.0) THEN
      WRITE(*,*) 'Finalized after ', TIM%N, 'steps'
      WRITE(*,*) 'Time-stepping total time: ', TIME_END-THIS%TIME_START,'seconds'
      CALL PRINT_REAL_TIME()
  ENDIF
  call MPI_BARRIER(MPI_COMM_IVP,IERR)
  call MPI_FINALIZE(IERR)

  RETURN
  END SUBROUTINE FINALIZE
