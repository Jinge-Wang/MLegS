!> =====================================================================
!> @brief APPLIES DIRECTIONAL 3D SPECTRAL HYPERVISCOSITY FILTER.
!>
!> @details
!> THIS SUBROUTINE APPLIES PRE-CALCULATED DIRECTIONAL HYPERVISCOSITY
!> FILTERS TO THE SPECTRAL COEFFICIENTS OF THE VELOCITY FIELDS (`PSI`,
!> `CHI`) AND OPTIONALLY THE DENSITY FIELD (`B`). IT IS ONLY ACTIVE
!> WHEN `VISC%SW` IS SET TO 3.
!>
!> **INITIALIZATION REQUIREMENTS**:
!> - MUST CALL `HYP3INIT` BEFORE FIRST USE TO ALLOCATE DAMPING ARRAYS
!> - MUST CALL `HYP3SET` TO COMPUTE INITIAL DAMPING FACTORS
!> - CALL `HYP3ADJ` DURING TIME-STEPPING FOR ADAPTIVE ADJUSTMENT
!>
!> @param[inout] PSI       >> TOROIDAL VELOCITY FIELD (IN FFF_SPACE)
!> @param[inout] CHI       >> POLOIDAL VELOCITY FIELD (IN FFF_SPACE)
!> @param[inout] B         >> OPTIONAL: DENSITY/BUOYANCY FIELD (IN FFF_SPACE)
!> @param[in]    DT_SCALE  >> OPTIONAL: TIME FACTOR FOR SUB-STEPPING
!>                            (DEFAULT=1.0, USE <1.0 FOR PREDICTOR STEPS)
!>
!> @author JINGE WANG
!> @date   SEP 2025
!> =====================================================================
SUBROUTINE HYPERV3(PSI, CHI, B, DT_SCALE)
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR):: PSI, CHI
  TYPE(SCALAR), OPTIONAL:: B
  REAL(P8), OPTIONAL, INTENT(IN):: DT_SCALE
  INTEGER:: MM, KK, NN
  REAL(P8):: TIME_FACTOR

  IF (VISC%SW .NE. 3) RETURN

  TIME_FACTOR = 1.0D0
  IF (PRESENT(DT_SCALE)) TIME_FACTOR = DT_SCALE

  !$OMP PARALLEL DO PRIVATE(KK, MM, NN) &
  !$OMP& SCHEDULE(STATIC) COLLAPSE(2)
  DO KK = 1,SIZE(PSI%E,3); DO MM = 1,SIZE(PSI%E,2)

    NN = NRCHOPS(MM + PSI%INTH)
    PSI%E(:NN,MM,KK) = PSI%E(:NN,MM,KK) * (VISC%HYPERV_R(:NN,MM+PSI%INTH) * VISC%HYPERV_T(MM+PSI%INTH) * VISC%HYPERV_X(KK+PSI%INX))**TIME_FACTOR
    CHI%E(:NN,MM,KK) = CHI%E(:NN,MM,KK) * (VISC%HYPERV_R(:NN,MM+PSI%INTH) * VISC%HYPERV_T(MM+PSI%INTH) * VISC%HYPERV_X(KK+PSI%INX))**TIME_FACTOR
    
    IF (PRESENT(B)) THEN
      B%E(:NN,MM,KK) = B%E(:NN,MM,KK) * &
        (VISC%HYPERD_R(:NN,MM+PSI%INTH) * VISC%HYPERD_T(MM+PSI%INTH) * VISC%HYPERD_X(KK+PSI%INX))**TIME_FACTOR
    END IF

  ENDDO; ENDDO
  !$OMP END PARALLEL DO

  CALL CHOPDO(PSI)
  CALL CHOPDO(CHI)
  IF (PRESENT(B)) CALL CHOPDO(B)

  RETURN
END SUBROUTINE HYPERV3

