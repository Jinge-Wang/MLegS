  SUBROUTINE VISC2(A,AO,NU,DT,WK)
!=======================================================================
! [USAGE]: 
! UPDATE A SCALAR FIELD WITH REGARD TO VISCOSITY
! USING CRANK-NICHOLSON (IMPLICIT) METHOD
! [PARAMETERS]:
! A   >> SCALAR FIELD TO BE UPDATED
! AO  >> SCALAR FIELD IN A PREVIOUS TIME STEP
! NU  >> VISCOSITY/DIFFUSIVITY
! DT  >> TIMESTEP
! WK  >> PRE-ALLOCATED WORKING VARIABLE
! [DEPENDENCIES]:
! 1. (DE)ALLOCATE(~) @ MOD_SCALAR3
! 2. CHOPSET(~) @ MOD_SCALAR3
! 3. CHOPDO(~) @ MOD_SCALAR3
! 4. DEL2(~) @ MOD_LEGOPS
! 5. IHELM(~) @ MOD_LEGOPS
! [NOTES]:
! THE FOLLOWING FORMULA IS UTILIZED TO UPDATE A.
!     A(1)-A(1/2)                  A(1)+A(0)
!    ------------ = VISCNU(DEL2)(------------)
!         DT                           2
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR),INTENT(INOUT):: A, WK
  TYPE(SCALAR),INTENT(IN):: AO
  REAL(P8):: DT, NU

  REAL(P8):: ALP

  IF(NU.EQ.0.0) THEN
    CALL MPRINT("VISC2: NU CAN'T BE ZERO")
    CALL MPI_ABORT(MPI_COMM_WORLD, ERR_FLAGS%SOLVER, IERR)
  ENDIF

  IF (A%SPACE .NE. FFF_SPACE) THEN
    CALL MPRINT("VISC2: INPUT IS NOT IN FFF_SPACE")
    CALL MPI_ABORT(MPI_COMM_WORLD, ERR_FLAGS%SOLVER, IERR)
  ENDIF

  IF (WK%SPACE .NE. FFF_SPACE) THEN
    CALL DEALLOCATE(WK)
    CALL ALLOCATE(WK,FFF_SPACE)
  ENDIF

  ALP=2/NU/DT

  CALL CHOPSET(2)
  CALL DEL2(AO,WK)
  CALL CHOPSET(-2)
  CALL CHOPDO(WK)

  WK%E = -WK%E-ALP*A%E
  IF ((A%INTH.EQ.0).AND.(A%INX.EQ.0)) WK%LN= -ALP*A%LN
  CALL IHELM(WK,A,ALP)

  RETURN
  END SUBROUTINE VISC2
