FUNCTION INTEG_P(F)
!=======================================================================
! [USAGE]:
! INTEGRATION OF A FUNCTION OVER A DOMAIN 
!     0  <  R   < INFTY
!     0  <  PHI < 2*PI
!     0  <  Z   < ZLEN
! [INPUTS]:
! F >> INTEGRANT
! [OUTPUTS]:
! INTEG >> INTEGRATION EQUAL TO INT_[FULL_RANGE](F(R,PHI,Z) RDR DPHI DZ)
!=======================================================================
IMPLICIT NONE
TYPE(SCALAR),INTENT(IN):: F
REAL(P8)::INTEG_P

TYPE(SCALAR):: F_COPY

IF(F%SPACE.NE.FFF_SPACE) THEN
  IF (MPI_RANK.EQ.0) WRITE(*,*) 'INTEG_P: NOT IN FFF_SPACE'
  STOP
ENDIF

IF(F%LN.NE.0.0) THEN
  WRITE(*,*) 'INTEGP: LOGTERM NOT ZERO'
  WRITE(*,*) 'LOGTERM=',F%LN
ENDIF

CALL ALLOCATE(F_COPY)
F_COPY = F
CALL RTRAN(F_COPY, 1)

IF ((F%INTH.EQ.0).AND.(F%INX.EQ.0)) THEN
  INTEG_P = 2.0_P8*PI*ZLEN*ELL2*DOT_PRODUCT(REAL(F%E(:NR,1,1))/(1-TFM%X(:NR))**2,TFM%W)
ELSE
  INTEG_P = 0
ENDIF
CALL MPI_ALLREDUCE(MPI_IN_PLACE, INTEG_P, 1, MPI_DOUBLE_PRECISION, &
      MPI_SUM, MPI_COMM_IVP, IERR)

CALL DEALLOCATE(F_COPY)

RETURN
END FUNCTION INTEG_P
