  SUBROUTINE STEP_BOUSSI_ETDAB_CN(THIS, PSI, CHI, B)
!=======================================================================
  IMPLICIT NONE
  TYPE(SOLVER_T), INTENT(INOUT) :: THIS
  TYPE(SCALAR), INTENT(INOUT)   :: PSI, CHI, B

  REAL(P8):: DT
  TYPE(SCALAR):: RURN, RUPN, UZN, BN
  TYPE(SCALAR):: RORN, ROPN, OZN
  TYPE(SCALAR):: PSI0, CHI0, B0
  TYPE(SCALAR):: W

  DT = TIM%DT
  TIM%T = TIM%T + DT
  TIM%N = TIM%N + 1
  ADV%X = ADV%X + ADV%UX*DT
  ADV%Y = ADV%Y + ADV%UY*DT

  CALL ALLOCATE(RURN); CALL ALLOCATE(RUPN); CALL ALLOCATE(UZN)
  CALL ALLOCATE(RORN); CALL ALLOCATE(ROPN); CALL ALLOCATE(OZN)

  CALL CHOPSET(3)
  CALL PC2VEL(PSI,CHI,RURN,RUPN,UZN)
  CALL PC2VOR(PSI,CHI,RORN,ROPN,OZN)
  CALL CHOPSET(-3)

  ! CALCULATE NONLINEAR TERMS: U X W AND -(U.GRAD)B' 
  ! NOTES:
  ! - B REMAIN IN FFF SPACE
  ! - RURN, RUPN, UZN ARE RETURNED IN PPP SPACE
  !   AND UPDATED WITH FREESTREAM ADJUSTMENT
  ! - RORN, ROPN, OZN ARE RETURNED IN PPP SPACE
  CALL CALC_BOUSSI_NONLIN(B,RURN,RUPN,UZN,BN,RORN,ROPN,OZN)

  CALL ALLOCATE(B0)
  B0 = B ! FFF SPACE

  ! APPLY ETD UPDATE TO RURN, RUPN, UZN, B
  ! TODO: CHECK HOW FREESTREAM ADJUSTMENT WILL AFFECT RESULTS
  CALL CALC_BOUSSI_ETDAB_SUB(THIS, B, RURN, RUPN, UZN, BN, RORN, ROPN, OZN)
  THIS%N_B = BN
  THIS%R_N_R = RORN
  THIS%R_N_P = ROPN
  THIS%N_Z = OZN
  THIS%R_PI_R = RURN
  THIS%R_PI_P = RUPN
  THIS%PI_Z = UZN
  CALL DEALLOCATE(BN)
  CALL DEALLOCATE(RORN)
  CALL DEALLOCATE(ROPN)
  CALL DEALLOCATE(OZN)

  CALL ALLOCATE(PSI0)
  CALL ALLOCATE(CHI0)
  PSI0 = PSI
  CHI0 = CHI

  CALL ALLOCATE(W)
  CALL PROJECT(RURN, RUPN, UZN, PSI, W, PSI%LN)
  CALL DEALLOCATE(RURN)
  CALL DEALLOCATE(RUPN)
  CALL DEALLOCATE(UZN)

  ! CALL IDEL2(W, CHI)
  CALL IDEL2LN(W, CHI)
  CALL DEALLOCATE(W)

  CALL TOFF(B)
  CALL CALC_BOUSSI_VISC_CN(PSI,CHI,B,PSI0,CHI0,B0)
  CALL DEALLOCATE(PSI0)
  CALL DEALLOCATE(CHI0)
  CALL DEALLOCATE(B0)

  CALL CALC_BOUSSI_HYPERV(PSI,CHI,B,DT)

  RETURN
  END SUBROUTINE STEP_BOUSSI_ETDAB_CN

