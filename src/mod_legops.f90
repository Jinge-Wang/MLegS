SUBROUTINE DIVXM_THOMAS(B, A)
!=======================================================================
! [USAGE]:
! APPLIES THE INVERSE OF THE (1-x) SPECTRAL OPERATOR.
!
! [METHOD]:
! LOOPS THROUGH ALL SPECTRAL MODES, GENERATES THE TRIDIAGONAL MATRIX
! FOR EACH MODE RESPECTING ITS SPECIFIC RADIAL TRUNCATION (NRCHOPS),
! AND SOLVES THE SYSTEM USING THE THOMAS ALGORITHM FOR TRI-BAND OP.
!
! [INPUTS]:
! B >> SCALAR OBJECT IN FFF SPACE.
!
! [OUTPUTS]:
! A >> (1-x)^(-1) * B.
!=======================================================================
   IMPLICIT NONE
   TYPE(SCALAR), INTENT(IN)    :: B
   TYPE(SCALAR), INTENT(INOUT) :: A

   INTEGER :: MM, KK, NN, AM
   REAL(P8), DIMENSION(:,:), ALLOCATABLE :: XM

   IF(A%SPACE.NE.FFF_SPACE) THEN
      CALL DEALLOCATE(A)
      CALL ALLOCATE(A, FFF_SPACE)
   ENDIF

   A%LN = B%LN
   A%E = 0.D0

!$OMP PARALLEL DEFAULT(SHARED) PRIVATE(MM, KK, AM, NN, XM)
!$OMP DO
   DO MM = 1, SIZE(B%E, 2)
      AM = M(MM + B%INTH)
      NN = NRCHOPS(MM + B%INTH)

      ALLOCATE(XM(NN, 3))

      ! GENERATE THE (1-x) MATRIX FOR THIS AZIMUTHAL MODE
      XM = BAND_LOGLEG_XM(NN, AM, TFM%LOGNORM(:NN, MM + B%INTH))

      ! SOLVE THE TRIDIAGONAL SYSTEM FOR EACH AXIAL WAVENUMBER
      DO KK = 1, SIZE(B%E, 3)
         A%E(:NN, MM, KK) = SOLVEB(XM, B%E(:NN, MM, KK))
      ENDDO

      DEALLOCATE(XM)
   ENDDO
!$OMP END DO
!$OMP END PARALLEL

   RETURN
END SUBROUTINE DIVXM_THOMAS
