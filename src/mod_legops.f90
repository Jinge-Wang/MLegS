FUNCTION Z2LN(UZ)
!=======================================================================
! [USAGE]: 
! COMPUTE THE LOG TERM BASED ON A GIVEN Z-COMPONENT OF A VECTOR FIELD:
!   LN = -ELL^2 * INT^1_-1[UZ_00/(1-X)^2]DX / 2
!=======================================================================
  IMPLICIT NONE
  TYPE(SCALAR), INTENT(IN) :: UZ
  REAL(P8) :: Z2LN

  IF (UZ%SPACE .NE. PFF_SPACE) THEN
    CALL MPRINT('Z2LN: UZ must be in PFF-space')
    RETURN
  END IF

  ! Compute the log term
  Z2LN = 0.D0
  IF ((UZ%INTH.EQ.0).AND.(UZ%INX.EQ.0)) THEN
    Z2LN = -0.5D0 * ELL2 * DOT_PRODUCT(REAL(UZ%E(:NR,1,1))/(1.D0-TFM%X)**2,TFM%W)
  END IF

  RETURN
END FUNCTION Z2LN
