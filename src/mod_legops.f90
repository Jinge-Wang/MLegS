SUBROUTINE VELMAX(RUR, RUP, UZ)
!=======================================================================
! [USAGE]:
! FIND THE MAXIMUM ELEMENTS IN UR, UP, UZ AND THEIR LOC
! [PARAMETERS]:
! RUR >> R*U_R IN PPP SPACE
! RUP >> R*U_P IN PPP SPACE
!  UZ >>   U_Z IN PPP SPACE
! [NOTES]:
! THE MAX ARE FOR UR, UP, UZ DESPITE INPUTS ARE RUR, RUP, UZ
!========================================================================
IMPLICIT NONE
TYPE(SCALAR),INTENT(IN):: RUR, RUP, UZ
REAL(P8):: URMAX, UPMAX, UZMAX, R, URMAX_LOC, UPMAX_LOC, UZMAX_LOC
INTEGER:: NN, MM, KK, NRTEMP, IR
REAL(P8), PARAMETER :: TOL = 1.0E-15
REAL(P8), PARAMETER :: THRESHOLD = 0.1D0  ! Adjust this threshold as needed
INTEGER:: URMAX_NN, URMAX_MM, URMAX_KK
INTEGER:: UPMAX_NN, UPMAX_MM, UPMAX_KK
INTEGER:: UZMAX_NN, UZMAX_MM, UZMAX_KK

IR = RUR%INR
NRTEMP = MIN(SIZE(RUR%E,1), NR-IR)

! Find local maxima and their locations
URMAX = 0.D0; UPMAX = 0.D0; UZMAX = 0.D0
URMAX_NN = 0; URMAX_MM = 0; URMAX_KK = 0
UPMAX_NN = 0; UPMAX_MM = 0; UPMAX_KK = 0
UZMAX_NN = 0; UZMAX_MM = 0; UZMAX_KK = 0

DO NN = 1, NRTEMP
  R = TFM%R(NN+IR)
  DO MM = 1, SIZE(RUR%E,2)
    DO KK = 1, SIZE(RUR%E,3)
      ! Check UR maximum
      IF (ABS(RUR%E(NN,MM,KK)/R) > URMAX) THEN
        URMAX = ABS(RUR%E(NN,MM,KK)/R)
        URMAX_NN = NN+IR; URMAX_MM = MM; URMAX_KK = KK
      END IF
      ! Check UP maximum
      IF (ABS(RUP%E(NN,MM,KK)/R) > UPMAX) THEN
        UPMAX = ABS(RUP%E(NN,MM,KK)/R)
        UPMAX_NN = NN+IR; UPMAX_MM = MM; UPMAX_KK = KK
      END IF
      ! Check UZ maximum
      IF (ABS(UZ%E(NN,MM,KK)) > UZMAX) THEN
        UZMAX = ABS(UZ%E(NN,MM,KK))
        UZMAX_NN = NN+IR; UZMAX_MM = MM; UZMAX_KK = KK
      END IF
    END DO
  END DO
END DO

URMAX_LOC = URMAX
UPMAX_LOC = UPMAX
UZMAX_LOC = UZMAX

! Global reduction to find overall maximum
CALL MPI_ALLREDUCE(MPI_IN_PLACE, URMAX, 1, MPI_DOUBLE_PRECISION, MPI_MAX, MPI_COMM_IVP, IERR)
CALL MPI_ALLREDUCE(MPI_IN_PLACE, UPMAX, 1, MPI_DOUBLE_PRECISION, MPI_MAX, MPI_COMM_IVP, IERR)
CALL MPI_ALLREDUCE(MPI_IN_PLACE, UZMAX, 1, MPI_DOUBLE_PRECISION, MPI_MAX, MPI_COMM_IVP, IERR)

! Only print global maxima if they exceed threshold (from rank 0)
IF (MPI_RANK.EQ.0) THEN
  WRITE(*,*) 'UR: Global max = ', URMAX
  WRITE(*,*) 'UP: Global max = ', UPMAX
  WRITE(*,*) 'UZ: Global max = ', UZMAX
END IF
CALL MPI_BARRIER(MPI_COMM_IVP, IERR)

! Check if this rank holds the global maximum and print location details
! Only print if the maximum exceeds threshold
IF (URMAX > THRESHOLD) THEN
  IF (ABS(URMAX - URMAX_LOC) < TOL) THEN
    R = TFM%R(URMAX_NN)
    WRITE(*,*) &
      'MAX UR at NN=', URMAX_NN, ' MM=', URMAX_MM, ' KK=', URMAX_KK, &
      ' RUR=', RUR%E(URMAX_NN-IR,URMAX_MM,URMAX_KK), ' R=', R, ' AT RANK=', MPI_RANK
  END IF
END IF

IF (UPMAX > THRESHOLD) THEN
  IF (ABS(UPMAX - UPMAX_LOC) < TOL) THEN
    R = TFM%R(UPMAX_NN)
    WRITE(*,*) &
      'MAX UP at NN=', UPMAX_NN, ' MM=', UPMAX_MM, ' KK=', UPMAX_KK, &
      ' RUP=', RUP%E(UPMAX_NN-IR,UPMAX_MM,UPMAX_KK), ' R=', R, ' AT RANK=', MPI_RANK
  END IF
END IF

IF (UZMAX > THRESHOLD) THEN
  IF (ABS(UZMAX - UZMAX_LOC) < TOL) THEN
    R = TFM%R(UZMAX_NN)
    WRITE(*,*) &
      'MAX UZ at NN=', UZMAX_NN, ' MM=', UZMAX_MM, ' KK=', UZMAX_KK, &
      ' UZ=', UZ%E(UZMAX_NN-IR,UZMAX_MM,UZMAX_KK), ' R=', R, ' AT RANK=', MPI_RANK
  END IF
END IF

CALL MPI_BARRIER(MPI_COMM_IVP, IERR)
END SUBROUTINE VELMAX
