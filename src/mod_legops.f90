SUBROUTINE DIVXM(B,A)
!=======================================================================
! [USAGE]:
! APPLIES THE INVERSE OF THE (1-X) SPECTRAL OPERATOR, WHICH IS
! MATHEMATICALLY EQUIVALENT TO DIVISION BY (1-X) OR MULTIPLICATION
! BY (R**2+L**2)/(2L**2).
!
! [PARAMETERS]:
! B >> (IN)  INPUT SCALAR FIELD IN FFF SPACE.
! A >> (OUT) RESULTING SCALAR FIELD A = (1-X)**(-1) * B.
!
! [DEPENDENCIES]:
! 1. BAND_LOGLEG_XM(~) @ MOD_LIN_LEGENDRE
! 2. BANMUL(~) @ MOD_BANDMAT
! 3. LUB(~) @ MOD_BANDMAT
! 4. SOLVEB(~) @ MOD_BANDMAT
! 5. (DE)ALLOCATE(SCALAR) @ MOD_SCALAR3
! 6. CHOPDO(~) @ MOD_SCALAR3
!
! [NOTES]:
! DIVXM IS A STABLE NUMERICAL INVERSE TO MULXM. HOWEVER, ITS PHYSICAL 
! COUNTERPART IS THE CONTINUOUS OPERATOR B/(1-X), WHICH IS SINGULAR
! AT X = 1 (R -> INFINITY). WHILE THE DISCRETE MATRIX REPRESENTATION
! FOR A FINITE TRUNCATION IS TECHNICALLY INVERTIBLE, DIVXM CAN BE
! SEVERELY ILL-CONDITIONED.
! 
! CONSEQUENCES:
! - SAFE USE: APPLYING DIVXM TO A FIELD THAT WAS CREATED BY MULXM IS A
!   VALID OPERATION, I.E., `DIVXM(MULXM(A))` WILL CORRECTLY RETURN `A`.
!   PERFORMING 'MULXM(DIVXM(A))' WILL ALSO RETURN 'A'.
!
! - UNSAFE USE: APPLYING DIVXM TO A GENERAL FIELD `B` WITHOUT CHECKING
!   ITS BEHAVIOR IS UNSAFE. DIRECTLY USING SUCH RESULT MAY LEAD TO
!   LARGE NUMERICAL ERRORS.
!
! THE USER IS RESPONSIBLE FOR ENSURING THE INPUT FIELD IS
! MATHEMATICALLY GUARANTEED TO BE IN THE RANGE OF THE (1-X) OPERATOR.
!=======================================================================
TYPE(SCALAR),INTENT(IN):: B
TYPE(SCALAR),INTENT(INOUT):: A

INTEGER:: MM,NN,N,KK
REAL(P8),DIMENSION(:,:),ALLOCATABLE:: XM

IF(B%SPACE.NE. FFF_SPACE) THEN
  IF (MPI_RANK.EQ.0) WRITE(*,*) 'DIVXM:INPUT NOT IN FFF_SPACE.'
  STOP
ENDIF

IF(A%SPACE.NE.FFF_SPACE) THEN
  CALL DEALLOCATE(A)
  CALL ALLOCATE(A)
ENDIF

IF ((B%INTH.EQ.0).AND.(B%INX.EQ.0)) THEN
  IF(B%LN.NE.0.D0) WRITE(*,*) 'DIVXM: A%LN IS NONRERO.'
ENDIF
A = B

A%LN = 0.0
CALL CHOPDO(A)

!$OMP PARALLEL DEFAULT(SHARED) PRIVATE(NN,XM,KK)

ALLOCATE( XM(NRCHOP,3) )

!$OMP DO
DO MM=1,SIZE(A%E,2) !NTCHOP
  NN = NRCHOPS(MM+A%INTH)
  XM(:NN,:) = BAND_LOGLEG_XM(NN,M(MM+A%INTH),TFM%LOGNORM(:,MM+A%INTH))
  CALL LUB(XM(:NN,:),2)
  !TODO: Simply have do kk = 1, size(a%e,3) instead of 1-a%inx
  DO KK=1-A%INX,SIZE(A%E,3) !NXCHOPDIM
    !XM(:NN,:) = BAND_LOGLEG_XM(NN,M(MM+A%INTH),TFM%LOGNORM(:,MM+A%INTH))
    !CALL LUB(XM(:NN,:),2)
    IF (KK.GT.0) CALL SOLVEB(XM(:NN,:),2,A%E(:NN,MM,KK))
  ENDDO
ENDDO
!$OMP ENDDO

DEALLOCATE( XM )

!$OMP END PARALLEL

RETURN
END SUBROUTINE DIVXM
