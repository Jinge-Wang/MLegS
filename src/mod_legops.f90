  CALL DEALLOCATE(B)
  CALL ALLOCATE(B)
ENDIF

IF ((A%INTH.EQ.0).AND.(A%INX.EQ.0)) THEN
  IF(A%LN.NE.0.D0) WRITE(*,*) 'MULXP: A%LN IS NONRERO.'
ENDIF

B%LN = 0.0
CALL CHOPDO(B)

!$OMP PARALLEL DEFAULT(SHARED) PRIVATE(NN,XP,KK)

ALLOCATE( XP(NRCHOP,3) )

!$OMP DO
DO MM=1,SIZE(A%E,2) !NTCHOP>=NTCHOPDIM
  NN = NRCHOPS(MM+A%INTH)
