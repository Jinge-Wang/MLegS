SUBROUTINE GRAD(A,RGRAD_R,RGRAD_P,GRAD_Z)
!=======================================================================
! [USAGE]: 
! CALCULATES THE GRADIENT OF A SCALAR FIELD
! RETURNS (R*GRAD(A)_R, R*GRAD(A)_P, GRAD(A)_Z) IN FFF SPACE
! [PARAMETERS]:
! A      >> INPUT SCALAR FIELD IN FFF SPACE
! RGRAD_R >> ON EXIT, R*GRAD(A)_R (R* RADIAL COMPONENT OF A'S GRADIENT)
! RGRAD_P >> ON EXIT, R*GRAD(A)_P (R* AZIMUTHAL COMPONENT OF A'S GRADIENT)
! GRAD_Z  >> ON EXIT,   GRAD(A)_Z (AXIAL COMPONENT OF A'S GRADIENT)
! [NOTE]:
! FOR A SCALAR FIELD A, THE GRADIENT IS DEFINED AS
! GRAD(A) = (D/DR(A), (D/DPHI(A))/R, D/DZ(A))
! [DEPENDENCIES]:
! 1. XXDX(~) @ MOD_LEGOPS
! 2. (DE)ALLOCATE(SCALAR) @ MOD_SCALAR3
! [UPDATES]:
! CODED BY JINGE WANG @ OCT 30 2024
!=======================================================================
IMPLICIT NONE
TYPE(SCALAR),INTENT(IN):: A
TYPE(SCALAR),INTENT(INOUT):: RGRAD_R,RGRAD_P,GRAD_Z
INTEGER:: MM,KK,NN,MV
REAL(P8):: KV

! ALLOCATION
IF (RGRAD_R%SPACE.NE.FFF_SPACE) THEN
  CALL ALLOCATE(RGRAD_R,FFF_SPACE)
  CALL ALLOCATE(RGRAD_P,FFF_SPACE)
  CALL ALLOCATE( GRAD_Z,FFF_SPACE)
ENDIF

! RAR = R*D/DR(A)
! NOTE: A%LN -> RGRAD_R'S (0,0,0) AND (1,0,0) COMPONENTS
CALL XXDX(A,RGRAD_R)

! RAP = R*(D/DPHI(A))/R = D/DPHI(A) = IU*MV*A
! AZ = D/DZ(A) = IU*KV*A
RGRAD_P%LN = 0.D0; CALL CHOPDO(RGRAD_P)
GRAD_Z%LN = 0.D0; CALL CHOPDO(GRAD_Z)

!$OMP PARALLEL DO DEFAULT(SHARED) PRIVATE(NN,MV,KV,KK)
DO MM=1,SIZE(A%E,2) !NTCHOP
  NN=NRCHOPS(MM+A%INTH)
  MV=M(MM+A%INTH)
  DO KK=1,SIZE(A%E,3) !NXCHOPDIM
    KV=AK(MM+A%INTH,KK+A%INX)
    
    ! RAP = R*D/DPHI(A)/R = D/DPHI(A) = IU*MV*A
    RGRAD_P%E(:NN,MM,KK)=IU*MV*A%E(:NN,MM,KK)

    ! AZ = D/DZ(A) = IU*KV*A
     GRAD_Z%E(:NN,MM,KK)=IU*KV*A%E(:NN,MM,KK)
    
  ENDDO
ENDDO
!$OMP END PARALLEL DO

RETURN
END SUBROUTINE GRAD
