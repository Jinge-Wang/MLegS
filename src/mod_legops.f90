SUBROUTINE HELMP(P,A,B,ALP,NU)
!=======================================================================
! [USAGE]: 
! REPEATED HELMHOLTZ OPERATOR (DEL^P+NU*DEL^2+ALPHA)* 
! WHERE P >= 4 AND EVEN.
! [PARAMETERS]:
! P >> EVEN NUMBER AND >=4
! A >> INPUT IN FFF SPACE
! B >> ON EXIT, (DEL^P+NU*DEL^2+ALPHA)(A)
! ALP >> ALPHA IN THE HELMHOLTZ OPERATOR
! NU >> (OPTIONAL) DEFAULT IS 0.
! [DEPENDENCIES]:
! 1. DEL2(~) @ MOD_LEGOPS
! 2. (DE)ALLOCATE(SCALAR) @ MOD_SCALAR3
! [UPDATES]:
! RE-CODED BY SANGJOON LEE @ NOV 11 2020
!=======================================================================
IMPLICIT NONE
INTEGER:: P
TYPE(SCALAR):: A,B
REAL(P8),INTENT(IN):: ALP
REAL(P8),OPTIONAL:: NU

TYPE(SCALAR):: W,D2
INTEGER:: I

CALL ALLOCATE(W)
CALL ALLOCATE(D2)
CALL DEL2(A,D2)

B=D2

DO I=4,P,2
  CALL DEL2(B,W)
  B=W
ENDDO

B%E = B%E -ALP*A%E

IF(PRESENT(NU)) THEN
  B%E=B%E +NU*D2%E
ENDIF

IF ((B%INTH.EQ.0).AND.(B%INX.EQ.0)) B%LN = -ALP*A%LN

CALL DEALLOCATE(W)
CALL DEALLOCATE(D2)

RETURN
END SUBROUTINE HELMP
