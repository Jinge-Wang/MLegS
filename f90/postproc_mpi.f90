PROGRAM POSTPROC
!=======================================================================
! [USAGE]: 
! READ TOROIDAL (PSII) AND POLODIAL (CHII) TERMS OF THE VELOCITY FIELD
! AND CREATE THE 3-D OR SECTIONAL VELOCITY OR VORTICITY FIELD
! OUTPUT DATA MAY BE COMPATIBLE WITH MATLAB
! [NOTE]:
! POSTPROCESS%JOB = 0: SAVE OMEGA_Z IN THE R-THETA PLANE
! POSTPROCESS%JOB = 1: SAVE R*U_THETA IN THE R-THETA PLANE
! POSTPROCESS%SLICEINT = 999: 3-DIMENSIONAL FIELD
! [UPDATES]:
! BASED ON TATSU'S ORIGINAL CODE & JOON'S MODERNIZED CODE
! LAST UPDATE ON OCT 6, 2024
!=======================================================================
USE OMP_LIB
USE MPI
USE MOD_MISC
USE MOD_BANDMAT
USE MOD_EIG
USE MOD_FD
USE MOD_LIN_LEGENDRE
USE MOD_SCALAR3
USE MOD_FFT 
USE MOD_LAYOUT
USE MOD_LEGOPS
USE MOD_MARCH
USE MOD_DIAGNOSTICS
USE MOD_INIT

IMPLICIT NONE
TYPE(SCALAR):: PSI,CHI,RUR,RUP,UZ,ROR,ROP,OZ 
CHARACTER(LEN=72) :: PSIFILE 
CHARACTER(LEN=72) :: CHIFILE 
CHARACTER(LEN=72) :: FILENAME, WRITENAME, OMEGAZFILE, UTHETAFILE
CHARACTER(LEN=8)  :: TEXT
CHARACTER(LEN=3)  :: NUM
INTEGER :: DATATYPE, RANGE, START, FINISH, STATUS, I
! I/O
real(P8):: time_start,time_end

! INITIALIZE PARALLEL ENVIRONMENT
CALL MPI_INIT_THREAD(MPI_THREAD_SERIALIZED,MPI_THREAD_MODE,IERR)
IF (MPI_THREAD_MODE.LT.MPI_THREAD_SERIALIZED) THEN
    WRITE(*,*) 'The threading support is lesser than that demanded.'
    CALL MPI_ABORT(MPI_COMM_WORLD,1,IERR)
ENDIF
CALL MPI_COMM_RANK(MPI_COMM_WORLD, MPI_RANK, IERR)
IF (MPI_RANK.EQ.0) THEN
    WRITE(*,*) 'PROGRAM STARTED'
    time_start = mpi_wtime()
    CALL PRINT_REAL_TIME()   ! @ MOD_MISC
ENDIF

! OBTAIN INFO FROM READ.INPUT
CALL READCOM('NOECHO')
CALL READIN(5)
CALL LEGINIT()

! SAVE OMEGA_Z IN THE R-THETA PLANE
IF(POSTPROCESS%JOB.EQ.0) THEN

    CALL ALLOCATE(ROR); CALL ALLOCATE(ROP); CALL ALLOCATE(OZ)

    DO I=POSTPROCESS%START,POSTPROCESS%FINISH

        CALL MPI_BARRIER(MPI_COMM_WORLD,IERR)

        ! LOAD PSI AND CHI
        CALL ALLOCATE(PSI); CALL ALLOCATE(CHI)
        IF (POSTPROCESS%FINISH .EQ. 1) THEN
            CALL MLOAD(TRIM(ADJUSTL(FILES%SAVEDIR))//FILES%PSII,PSI)
            CALL MLOAD(TRIM(ADJUSTL(FILES%SAVEDIR))//FILES%CHII,CHI)
        ELSE
            CALL MLOAD(TRIM(ADJUSTL(FILES%SAVEDIR))//FILES%PSI(I),PSI)
            CALL MLOAD(TRIM(ADJUSTL(FILES%SAVEDIR))//FILES%CHI(I),CHI)
        ENDIF

        ! Edited: avoid XXDX warning
        PSI%E(NRCHOPS(2),2,1) = 0.
        CHI%E(NRCHOPS(2),2,1) = 0.

        ! CONVERT THE POLOIDAL-TOROIDAL VARIALBES TO VORTICITY VARIALBES
        ! RETURNS (R*OMEGA_R,R*OMEGA_THETA,OMEGA_Z) IN FFF SPACE
        CALL PC2VOR(PSI,CHI,ROR,ROP,OZ)
        ! CALL TOFP(ROR)
        ! CALL TOFP(ROP)
        CALL TOFP(OZ) ! PPP SPACE

        ! SAVE FILE
        WRITE(NUM, 21) I
        IF (POSTPROCESS%SLICEINT.EQ.999) THEN
            OMEGAZFILE = 'omegaZ_3D_'//NUM//'.dat'
        ELSE
            OMEGAZFILE = 'omegaZ_RTplane_'//NUM//'.dat'  
        ENDIF
        CALL MSAVE_SLICES_IN_RTHETA_PLANE(OZ, TRIM(ADJUSTL(FILES%SAVEDIR))//OMEGAZFILE,&
            POSTPROCESS%SLICEINT)

        ! CLEAN-UP
        CALL DEALLOCATE(PSI); CALL DEALLOCATE(CHI)
        IF (POSTPROCESS%FINISH .EQ. 1) EXIT

    ENDDO

    CALL DEALLOCATE(ROR); CALL DEALLOCATE(ROP); CALL DEALLOCATE(OZ)

! SAVE R*(UTHETA) IN THE R-THETA PLANE
ELSE IF(POSTPROCESS%JOB.EQ.1) THEN

    CALL ALLOCATE(RUR); CALL ALLOCATE(RUP); CALL ALLOCATE(UZ)

    DO I=POSTPROCESS%START,POSTPROCESS%FINISH

        CALL MPI_BARRIER(MPI_COMM_WORLD,IERR)

        ! LOAD PSI AND CHI
        CALL ALLOCATE(PSI); CALL ALLOCATE(CHI)
        IF (POSTPROCESS%FINISH .EQ. 1) THEN
            CALL MLOAD(TRIM(ADJUSTL(FILES%SAVEDIR))//FILES%PSII,PSI)
            CALL MLOAD(TRIM(ADJUSTL(FILES%SAVEDIR))//FILES%CHII,CHI)
        ELSE
            CALL MLOAD(TRIM(ADJUSTL(FILES%SAVEDIR))//FILES%PSI(I),PSI)
            CALL MLOAD(TRIM(ADJUSTL(FILES%SAVEDIR))//FILES%CHI(I),CHI)
        ENDIF

        ! Edited: avoid XXDX warning
        ! PSI%E(NRCHOPS(2),2,1) = 0.
        ! CHI%E(NRCHOPS(2),2,1) = 0.

        ! CONVERT THE POLOIDAL-TOROIDAL VARIALBES TO VORTICITY VARIALBES
        ! RETURNS (R*OMEGA_R,R*OMEGA_THETA,OMEGA_Z) IN FFF SPACE
        CALL PC2VEL(PSI,CHI,RUR,RUP,UZ)
        ! CALL TOFP(RUR)
        ! CALL TOFP(RUP)
        CALL TOFP(RUP) ! PPP SPACE

        ! SAVE FILE
        WRITE(NUM, 21) I
        IF (POSTPROCESS%SLICEINT.EQ.999) THEN
            UTHETAFILE = 'ru_Theta_3D_'//NUM//'.dat'
        ELSE
            UTHETAFILE = 'ru_Theta_RTplane_'//NUM//'.dat'
        ENDIF
        CALL MSAVE_SLICES_IN_RTHETA_PLANE(RUP, TRIM(ADJUSTL(FILES%SAVEDIR))//UTHETAFILE,&
                                    POSTPROCESS%SLICEINT)

        ! CLEAN-UP
        CALL DEALLOCATE(PSI); CALL DEALLOCATE(CHI)
        IF (POSTPROCESS%FINISH .EQ. 1) EXIT

    ENDDO

    CALL DEALLOCATE(RUR); CALL DEALLOCATE(RUP); CALL DEALLOCATE(UZ)

    CALL MLOAD(TRIM(ADJUSTL(FILES%SAVEDIR))//FILES%PSII,PSI)
    CALL MLOAD(TRIM(ADJUSTL(FILES%SAVEDIR))//FILES%CHII,CHI)

ELSE
    IF (MPI_RANK.EQ.0) WRITE(*,*) 'POSTPROCESS: WRONG JOB # INPUT'
ENDIF

21   FORMAT (I3.3)

!> final printout
IF (MPI_RANK.eq.0) THEN
    WRITE(*,*) 'PROGRAM ENDED'
    CALL PRINT_REAL_TIME()
    time_end = mpi_wtime()
    WRITE(*,*) 'EXECUTION TIME: ',time_end-time_start,'seconds'
ENDIF
call MPI_BARRIER(MPI_COMM_IVP,IERR)
call MPI_FINALIZE(IERR)

CONTAINS
!=======================================================================
!=================== PROGRAM-DEPENDENT SUBROUTINES =====================
!=======================================================================
SUBROUTINE MSAVE_SLICES_IN_RTHETA_PLANE(A,FILENAME,ZPLANE)
!=======================================================================
TYPE(SCALAR):: A
CHARACTER(LEN=*):: FILENAME
INTEGER:: ZPLANE

INTEGER:: MM,KK
COMPLEX(P8),DIMENSION(:,:,:),ALLOCATABLE:: A_GLB

IF(A%SPACE.EQ.FFF_SPACE) THEN
    IF (MPI_RANK.EQ.0) WRITE(*,*) 'MSAVE_SLICES_IN_RTHETA_PLANE: INPUT IN FFF SPACE'
    CALL MPI_ABORT(MPI_COMM_WORLD,1,IERR)
ENDIF

ALLOCATE(A_GLB(NDIMR,NDIMTH,NDIMX))
CALL MASSEMBLE(A%E,A_GLB,2)

IF (MPI_RANK.EQ.0) THEN
    IF (ZPLANE.EQ.999) THEN
        CALL MSAVE(A_GLB(:NR,:NTH,:NX), FILENAME)
    ELSE
        CALL MSAVE(A_GLB(:NR,:NTH,ZPLANE), FILENAME)
    ENDIF
ENDIF

RETURN
END SUBROUTINE MSAVE_SLICES_IN_RTHETA_PLANE
!=======================================================================
SUBROUTINE MSAVE_SLICES_IN_RZ_PLANE(A,FILENAME,THETAPLANE)
!=======================================================================
TYPE(SCALAR):: A
CHARACTER(LEN=*):: FILENAME
INTEGER:: THETAPLANE

INTEGER:: MM,KK
COMPLEX(P8),DIMENSION(:,:,:),ALLOCATABLE:: A_GLB

IF(A%SPACE.EQ.FFF_SPACE) THEN
    IF (MPI_RANK.EQ.0) WRITE(*,*) 'MSAVE_SLICES_IN_RZ_PLANE: INPUT IN FFF SPACE'
    CALL MPI_ABORT(MPI_COMM_WORLD,1,IERR)
ENDIF

ALLOCATE(A_GLB(NDIMR,NDIMTH,NDIMX))
CALL MASSEMBLE(A%E,A_GLB,2)

IF (MPI_RANK.EQ.0) THEN
    CALL MSAVE(A_GLB(:NR,THETAPLANE,:NX), FILENAME)
ENDIF

RETURN

END SUBROUTINE MSAVE_SLICES_IN_RZ_PLANE
!=======================================================================
END PROGRAM POSTPROC
