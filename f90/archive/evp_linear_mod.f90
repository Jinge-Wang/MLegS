PROGRAM EVP_LINEAR_MOD
!=======================================================================
! [USAGE]: 
! FIND EIGENVALUES AND EIGENVECTORS OF THE LINEARIZED EULER EQUATIONS
! EXPRESSED IN A POLOIDAL-TOROLIDALLY DECOMPOSED FORM
! [UPDATES]:
! LAST UPDATE ON NOV 26, 2020
!=======================================================================
      USE MOD_MISC
      USE MOD_BANDMAT
      USE MOD_EIG
      USE MOD_FD
      USE MOD_LIN_LEGENDRE
      USE MOD_SCALAR3
      USE MOD_LAYOUT
      USE MOD_LEGOPS
      USE MOD_MARCH
      USE MOD_DIAGNOSTICS
      USE MOD_INIT

      IMPLICIT NONE
      TYPE(SCALAR):: PSI0,CHI0,RUR0,RUP0,UZ0,ROR0,ROP0,OZ0
      TYPE(SCALAR):: PSIU,CHIU,RURU,RUPU,UZU,RORU,ROPU,OZU
      TYPE(SCALAR):: PSID,CHID,RDR ,RDP, DZ
      TYPE(SCALAR):: PSI1,CHI1,PSI2,CHI2,PSI3,CHI3,PSI4,CHI4
      INTEGER     :: MIND,AKIND,MREAD
      REAL(P8)    :: AKREAD
      COMPLEX(P8),DIMENSION(:,:),ALLOCATABLE:: H,H2

      INTEGER     :: I,J,K

      WRITE(*,*) 'PROGRAM STARTED'
      CALL PRINT_REAL_TIME()   ! @ MOD_MISC

      ! TYPE '%read.input' TO READ THE INPUT VALUES FROM read.input
      CALL READIN(5)           ! @ MOD_INIT

      CALL ALLOCATE(PSI0)
      CALL ALLOCATE(CHI0)
      CALL ALLOCATE(RUR0)
      CALL ALLOCATE(RUP0)
      CALL ALLOCATE( UZ0)
      CALL ALLOCATE(ROR0)
      CALL ALLOCATE(ROP0)
      CALL ALLOCATE( OZ0)

      CALL ALLOCATE(PSIU)
      CALL ALLOCATE(CHIU)
      CALL ALLOCATE(RURU)
      CALL ALLOCATE(RUPU)
      CALL ALLOCATE( UZU)
      CALL ALLOCATE(RORU)
      CALL ALLOCATE(ROPU)
      CALL ALLOCATE( OZU)

      CALL ALLOCATE(PSID)
      CALL ALLOCATE(CHID)
      CALL ALLOCATE(RDR )
      CALL ALLOCATE(RDP )
      CALL ALLOCATE( DZ )

      CALL ALLOCATE(PSI1)
      CALL ALLOCATE(PSI2)
      CALL ALLOCATE(PSI3)
      CALL ALLOCATE(PSI4)
      CALL ALLOCATE(CHI1)
      CALL ALLOCATE(CHI2)
      CALL ALLOCATE(CHI3)
      CALL ALLOCATE(CHI4)

      ! LOAD INITIAL PSI (PSI0) AND CHI (CHI0) DATA
      ! PERFORM 'INIT' AS A PREREQUISITE TO MAKE PSI0 AND CHI0
      CALL MLOAD(TRIM(ADJUSTL(FILES%SAVEDIR))//FILES%PSI0,PSI0)
      CALL MLOAD(TRIM(ADJUSTL(FILES%SAVEDIR))//FILES%CHI0,CHI0)

      ! CONVERT THE POLOIDAL-TOROIDAL VARIALBES TO VORTICITY VARIALBES
      ! RETURNS (R*OMEGA0_R,R*OMEGA0_THETA,OMEGA0_Z) IN FFF SPACE
      CALL PC2VOR(PSI0,CHI0,ROR0,ROP0,OZ0)

      ! CONVERT THE POLOIDAL-TOROIDAL VARIALBES TO VORTICITY VARIALBES
      ! RETURNS (R*U0_R,R*U0_THETA,U0_Z) IN FFF SPACE
      CALL PC2VEL(PSI0,CHI0,RUR0,RUP0,UZ0)

      WRITE(*,*) ''
      WRITE(*,102) MINC
      WRITE(*,*) 'M_IND = INPUT - 1'
      WRITE(*,*) 'CHOOSE AN AZIMUTHAL WAVENUMBER (M) INDEX; M_IND ='
      WRITE(*,101) NTCHOPDIM
      READ(5,'(I72)') MIND
      WRITE(*,*) ''
      WRITE(*,103) ZLEN
      WRITE(*,104) NXCHOP
      WRITE(*,105) NXCHOPDIM, NXCHOP
      WRITE(*,*) 'CHOOSE AN AXIAL WAVENUMBER (AK) INDEX; AK_IND ='
      WRITE(*,101) NXCHOPDIM
      READ(5,'(I72)') AKIND
 101  FORMAT(' *** POSSIBLE INDICES: 1 ~ ', I3)
 102  FORMAT(' M  = ', I3, ' *(M_IND - 1)')
 103  FORMAT(' AK = 2*PI*AK_IND/', F0.3)
 104  FORMAT(' AK_IND = INPUT - 1          (INPUT <=', I3, ')')
 105  FORMAT('          -(', I3,' - INPUT + 1) (INPUT >', I3, ')')

      MREAD = M(MIND)
      AKREAD = AK(MIND,AKIND)

      WRITE(*,*) 'AZIMUTHAL AND AXIAL WAVENUMBERS:'
      WRITE(*,106) MREAD, AKREAD
 106  FORMAT('M = ',I8,' & K = ',F8.3)

      ALLOCATE(H (2*NRCHOPS(MIND),2*NRCHOPS(MIND)))
      ALLOCATE(H2(2*NRCHOPS(MIND),2*NRCHOPS(MIND)))
      H2 = 0.D0

      DO I = 1,NRCHOPS(MIND)
        PSIU%LN = 0.D0
        CHIU%LN = 0.D0
        PSIU%E = 0.D0
        CHIU%E = 0.D0
        PSIU%E(I,MIND,AKIND) = 1.D0

        CALL CHOPSET(3)

        CALL PC2VOR(PSIU,CHIU,RORU,ROPU,OZU)
        CALL PC2VEL(PSIU,CHIU,RURU,RUPU,UZU)

        CALL MATDEV(ROR0,ROP0,OZ0,RURU,RUPU,UZU,RDR,RDP,DZ)
        CALL PROJECT(RDR,RDP,DZ,PSI1,CHI1)

        CALL MATDEV(RORU,ROPU,OZU,RUR0,RUP0,UZ0,RDR,RDP,DZ)
        CALL PROJECT(RDR,RDP,DZ,PSI2,CHI2)

        CALL MATDEV(RUR0,RUP0,UZ0,RORU,ROPU,OZU,RDR,RDP,DZ)
        CALL PROJECT(RDR,RDP,DZ,PSI3,CHI3)

        CALL MATDEV(RURU,RUPU,UZU,ROR0,ROP0,OZ0,RDR,RDP,DZ)
        CALL PROJECT(RDR,RDP,DZ,PSI4,CHI4)

        CALL CHOPSET(-3)

        PSI1%E = PSI1%E + PSI2%E - PSI3%E - PSI4%E
        CHI1%E = CHI1%E + CHI2%E - CHI3%E - CHI4%E

        H(:NRCHOPS(MIND),  I) = PSI1%E(:NRCHOPS(MIND),MIND,AKIND)
        H(NRCHOPS(MIND)+1:,I) = CHI1%E(:NRCHOPS(MIND),MIND,AKIND)

        CALL DEL2(PSIU,PSI2)
        H2(NRCHOPS(MIND)+1:, I) = PSI2%E(:NRCHOPS(MIND),MIND,AKIND)

        PSIU%LN = 0.D0
        CHIU%LN = 0.D0
        PSIU%E = 0.D0
        CHIU%E = 0.D0
        CHIU%E(I,MIND,AKIND) = 1.D0
        
        CALL IDEL2(CHIU,CHIU)

        CALL CHOPSET(3)

        CALL PC2VOR(PSIU,CHIU,RORU,ROPU,OZU)
        CALL PC2VEL(PSIU,CHIU,RURU,RUPU,UZU)

        CALL MATDEV(ROR0,ROP0,OZ0,RURU,RUPU,UZU,RDR,RDP,DZ)
        CALL PROJECT(RDR,RDP,DZ,PSI1,CHI1)

        CALL MATDEV(RORU,ROPU,OZU,RUR0,RUP0,UZ0,RDR,RDP,DZ)
        CALL PROJECT(RDR,RDP,DZ,PSI2,CHI2)

        CALL MATDEV(RUR0,RUP0,UZ0,RORU,ROPU,OZU,RDR,RDP,DZ)
        CALL PROJECT(RDR,RDP,DZ,PSI3,CHI3)

        CALL MATDEV(RURU,RUPU,UZU,ROR0,ROP0,OZ0,RDR,RDP,DZ)
        CALL PROJECT(RDR,RDP,DZ,PSI4,CHI4)

        CALL CHOPSET(-3)

        PSI1%E = PSI1%E + PSI2%E - PSI3%E - PSI4%E
        CHI1%E = CHI1%E + CHI2%E - CHI3%E - CHI4%E

        H(:NRCHOPS(MIND),  I+NRCHOPS(MIND)) &
                            = PSI1%E(:NRCHOPS(MIND),MIND,AKIND)
        H(NRCHOPS(MIND)+1:,I+NRCHOPS(MIND)) &
                            = CHI1%E(:NRCHOPS(MIND),MIND,AKIND)

        H2(I,NRCHOPS(MIND)+I) = -1.D0

        WRITE(*,107) I, NRCHOPS(MIND)
      ENDDO
 107  FORMAT('PROGRESS: ',I3.3,'/',I3.3)

      H = INV(H2).MUL.H

      ! CALL MCAT(EIGVEC('R',H))

      CALL MCAT(GENEIG(H))

      DEALLOCATE( H )

      CALL DEALLOCATE(PSI1)
      CALL DEALLOCATE(PSI2)
      CALL DEALLOCATE(PSI3)
      CALL DEALLOCATE(PSI4)
      CALL DEALLOCATE(CHI1)
      CALL DEALLOCATE(CHI2)
      CALL DEALLOCATE(CHI3)
      CALL DEALLOCATE(CHI4)

      CALL DEALLOCATE(PSID)
      CALL DEALLOCATE(CHID)
      CALL DEALLOCATE(RDR )
      CALL DEALLOCATE(RDP )
      CALL DEALLOCATE( DZ )

      CALL DEALLOCATE(PSIU)
      CALL DEALLOCATE(CHIU)
      CALL DEALLOCATE(RURU)
      CALL DEALLOCATE(RUPU)
      CALL DEALLOCATE( UZU)
      CALL DEALLOCATE(RORU)
      CALL DEALLOCATE(ROPU)
      CALL DEALLOCATE( OZU)

      CALL DEALLOCATE(PSI0)
      CALL DEALLOCATE(CHI0)
      CALL DEALLOCATE(RUR0)
      CALL DEALLOCATE(RUP0)
      CALL DEALLOCATE( UZ0)
      CALL DEALLOCATE(ROR0)
      CALL DEALLOCATE(ROP0)
      CALL DEALLOCATE( OZ0)

      WRITE(*,*) ''
      WRITE(*,*) 'PROGRAM FINISHED'
      CALL PRINT_REAL_TIME()  ! @ MOD_MISC

CONTAINS
!=======================================================================
!=================== PROGRAM-DEPENDENT SUBROUTINES =====================
!=======================================================================
      SUBROUTINE MATDEV(RAR,RAP,AZ,RBR,RBP,BZ,RCR,RCP,CZ)
!=======================================================================
      IMPLICIT NONE
      TYPE(SCALAR):: RAR,RAP,AZ ! FFF_SPACE
      TYPE(SCALAR):: RBR,RBP,BZ ! FFF_SPACE
      TYPE(SCALAR):: RCR,RCP,CZ ! PPP_SPACE

      TYPE(SCALAR):: TMP1,TMP2,TMP3
      INTEGER:: NN,MM,KK

      CALL TOFP(RAR)
      CALL TOFP(RAP)
      CALL TOFP(AZ)

      CALL ALLOCATE(TMP1)
      CALL ALLOCATE(TMP2)
      CALL ALLOCATE(TMP3)

      CALL XXDX(RBR,TMP2)
      TMP1%E = -RBR%E + TMP2%E
      DO MM = 1,NTCHOP
        NN=NRCHOPS(MM)
        TMP2%E(:NN,MM,:NXCHOPDIM) = RBR%E(:NN,MM,:NXCHOPDIM)*IU*M(MM)
        DO KK = 1,NXCHOPDIM
          TMP3%E(:NN,MM,KK) = RBR%E(:NN,MM,KK)*IU*AK(MM,KK)
        ENDDO
      ENDDO

      CALL TOFP(TMP1)
      CALL TOFP(TMP2)
      CALL TOFP(TMP3)

      CALL TOFP(RBP)

      TMP1%E = ELEMUL(TMP1,RAR) + ELEMUL(TMP2,RAP) &
             - ELEMUL(RAP,RBP)
      DO NN=1,NR
        TMP1%E(NN,:,:) = TMP1%E(NN,:,:) / TFM%R(NN)**2.
      ENDDO
      TMP1%E = TMP1%E + ELEMUL(TMP3,AZ)
      RCR = TMP1

      CALL TOFF(RBP)

      CALL DEALLOCATE(TMP1)
      CALL DEALLOCATE(TMP2)
      CALL DEALLOCATE(TMP3)

      CALL ALLOCATE(TMP1)
      CALL ALLOCATE(TMP2)
      CALL ALLOCATE(TMP3)

      CALL XXDX(RBP,TMP2)
      TMP1%E = -RBP%E + TMP2%E
      DO MM = 1,NTCHOP
        NN=NRCHOPS(MM)
        TMP2%E(:NN,MM,:NXCHOPDIM) = RBP%E(:NN,MM,:NXCHOPDIM)*IU*M(MM)
        DO KK = 1,NXCHOPDIM
          TMP3%E(:NN,MM,KK) = RBP%E(:NN,MM,KK)*IU*AK(MM,KK)
        ENDDO
      ENDDO

      CALL TOFP(TMP1)
      CALL TOFP(TMP2)
      CALL TOFP(TMP3)

      CALL TOFP(RBR)

      TMP1%E = ELEMUL(TMP1,RAR) + ELEMUL(TMP2,RAP) &
             + ELEMUL(RAP,RBR)
      DO NN=1,NR
        TMP1%E(NN,:,:) = TMP1%E(NN,:,:) / TFM%R(NN)**2.
      ENDDO
      TMP1%E = TMP1%E + ELEMUL(TMP3,AZ)
      RCP = TMP1

      CALL TOFF(RBR)

      CALL DEALLOCATE(TMP1)
      CALL DEALLOCATE(TMP2)
      CALL DEALLOCATE(TMP3)

      CALL ALLOCATE(TMP1)
      CALL ALLOCATE(TMP2)
      CALL ALLOCATE(TMP3)

      CALL XXDX(BZ,TMP2)
      TMP1%E = TMP2%E
      DO MM = 1,NTCHOP
        NN=NRCHOPS(MM)
        TMP2%E(:NN,MM,:NXCHOPDIM) = BZ%E(:NN,MM,:NXCHOPDIM)*IU*M(MM)
        DO KK = 1,NXCHOPDIM
          TMP3%E(:NN,MM,KK) = BZ%E(:NN,MM,KK)*IU*AK(MM,KK)
        ENDDO
      ENDDO

      CALL TOFP(TMP1)
      CALL TOFP(TMP2)
      CALL TOFP(TMP3)

      TMP1%E = ELEMUL(TMP1,RAR) + ELEMUL(TMP2,RAP)
      DO NN=1,NR
        TMP1%E(NN,:,:) = TMP1%E(NN,:,:) / TFM%R(NN)**2.
      ENDDO
      TMP1%E = TMP1%E + ELEMUL(TMP3,AZ)
      CZ = TMP1

      CALL DEALLOCATE(TMP1)
      CALL DEALLOCATE(TMP2)
      CALL DEALLOCATE(TMP3)

      CALL TOFF(RAR)
      CALL TOFF(RAP)
      CALL TOFF(AZ)

      RETURN
      END SUBROUTINE MATDEV
!=======================================================================
      FUNCTION ELEMUL(A,B)
!=======================================================================
      IMPLICIT NONE
      TYPE(SCALAR):: A,B
      COMPLEX(P8),DIMENSION(NDIMR,NDIMTH,NDIMX):: ELEMUL

      INTEGER :: I1,J1,K1
      REAL(P8):: C1,C2,D1,D2

      IF((A%SPACE.NE.PPP_SPACE).OR.(B%SPACE.NE.PPP_SPACE)) THEN
        WRITE(*,*) ,'ELEMUL: BOTH INPUTS MUST BE IN PPP SPACE'
        STOP
      ENDIF

      DO K1=1,NX
        DO J1=1,NTH
          DO I1=1,NR
            C1 = REAL(A%E(I1,J1,K1))
            C2 = REAL(B%E(I1,J1,K1))
            D1 = AIMAG(A%E(I1,J1,K1))
            D2 = AIMAG(B%E(I1,J1,K1))
            ELEMUL(I1,J1,K1) = CMPLX(C1*C2,D1*D2,P8)
          ENDDO
        ENDDO
      ENDDO

      RETURN
      END FUNCTION ELEMUL
!=======================================================================    
END PROGRAM EVP_LINEAR_MOD
