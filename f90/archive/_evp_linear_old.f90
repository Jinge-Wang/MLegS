      CALL ALLOCATE(TMP1)
      CALL ALLOCATE(TMP2)
      CALL ALLOCATE(TMP3)
      CALL ALLOCATE(TMP4)

      TMP1%E = 0.D0
      
      TMP3 = A
      CALL DEL2(TMP3,TMP3)
      CALL MULXMDIVXP(TMP3,TMP3,.TRUE.)
      DO MM = 1,NTCHOP
        NN=NRCHOPS(MM)
        TMP3%E(:NN,MM,:NXCHOPDIM) = TMP3%E(:NN,MM,:NXCHOPDIM)*IU*M(MM)
      ENDDO
      TMP1%E = TMP1%E + TMP3%E
      CALL TOFP(TMP1)

      TMP2%E = 0.D0

      TMP4 = UZ
      CALL XXDX(TMP4,TMP4)
      TMP2%E = TMP2%E + TMP4%E
      CALL TOFP(TMP2)

      TMP1%E = TMP1%E * TMP2%E

      CALL HORFFT(TMP1,-1)
      CALL VERFFT(TMP1,-1)

