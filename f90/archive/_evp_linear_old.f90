      TMP1%E = TMP1%E + TMP3%E

      TMP3 = A
      CALL XXDX(TMP3,TMP3)
      TMP3%E = 2.*TMP3%E
      TMP1%E = TMP1%E + TMP3%E

      CALL MULXMDIVXP(TMP1,TMP1,.TRUE.)
      DO MM = 1,NTCHOP
        NN=NRCHOPS(MM)
        TMP1%E(:NN,MM,:NXCHOPDIM) = TMP1%E(:NN,MM,:NXCHOPDIM)*IU*M(MM)
      ENDDO
      TMP1%E = -TMP1%E
      CALL TOFP(TMP1)

      TMP2%E = 0.D0

