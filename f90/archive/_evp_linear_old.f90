      TMP4%E = -TMP4%E
      TMP2%E = TMP2%E + TMP4%E

      TMP4 = ROP
      CALL XXDX(TMP4,TMP4)
      TMP2%E = TMP2%E + TMP4%E

      CALL MULXMDIVXP(TMP2,TMP2,.TRUE.)
      CALL TOFP(TMP2)

