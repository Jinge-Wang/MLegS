!=======================================================================
      FUNCTION PSICURLMOM(A,ROR,ROP,OZ,RUR,RUP,UZ,MIND,AKIND)
!=======================================================================
      IMPLICIT NONE
      TYPE(SCALAR):: A,ROR,ROP,OZ,RUR,RUP,UZ
      INTEGER:: MIND,AKIND
      COMPLEX(P8), DIMENSION(NR):: PSICURLMOM

      TYPE(SCALAR):: TMP1,TMP2,TMP3,TMP4
      INTEGER:: NN,MM,KK

      PSICURLMOM = 0.D0
      ! 9>---------------
      CALL ALLOCATE(TMP1)
      CALL ALLOCATE(TMP2)
      CALL ALLOCATE(TMP3)
      CALL ALLOCATE(TMP4)

      TMP1%E = 0.D0
      
      TMP3 = A
      DO MM = 1,NTCHOP
        NN=NRCHOPS(MM)
        TMP3%E(:NN,MM,:NXCHOPDIM) = TMP3%E(:NN,MM,:NXCHOPDIM)*IU*M(MM)
      ENDDO
      TMP1%E = TMP1%E + TMP3%E

      TMP3 = A
      CALL XXDX(TMP3,TMP3)
      TMP1%E = TMP1%E + TMP3%E

      TMP3 = A
      CALL XXDX(TMP3,TMP3)
      CALL XXDX(TMP3,TMP3)
      TMP3%E = 2.*TMP3%E
      TMP1%E = TMP1%E + TMP3%E

      CALL MULXMDIVXP(TMP1,TMP1,.TRUE.)
      TMP1%E = -TMP1%E

      TMP3 = A
      DO MM = 1,NTCHOP
        NN=NRCHOPS(MM)
        TMP3%E(:NN,MM,:NXCHOPDIM) = TMP3%E(:NN,MM,:NXCHOPDIM)*IU*M(MM)
      ENDDO
      CALL DEL2(TMP3,TMP3)
      TMP3%E = -TMP3%E
      TMP1%E = TMP1%E + TMP3%E

      TMP3 = A
      CALL XXDX(TMP3,TMP3)
      CALL DEL2(TMP3,TMP3)
      TMP1%E = TMP1%E + TMP3%E

      CALL MULXMDIVXP(TMP1,TMP1,.TRUE.)
      DO MM = 1,NTCHOP
        NN=NRCHOPS(MM)
        DO KK = 1,NXCHOPDIM
          TMP1%E(:NN,MM,KK) = TMP1%E(:NN,MM,KK)*IU*AK(MM,KK)
        ENDDO
      ENDDO

      CALL TOFP(TMP1)

      TMP2%E = 0.D0

      TMP4 = RUP
      TMP2 = TMP4
      CALL TOFP(TMP2)

      TMP1%E = TMP1%E * TMP2%E

      CALL HORFFT(TMP1,-1)
      CALL VERFFT(TMP1,-1)

      PSICURLMOM = PSICURLMOM + TMP1%E(:NR,MIND,AKIND)

      CALL DEALLOCATE(TMP1)
      CALL DEALLOCATE(TMP2)
      CALL DEALLOCATE(TMP3)
      CALL DEALLOCATE(TMP4)

      ! 10>--------------
      CALL ALLOCATE(TMP1)
      CALL ALLOCATE(TMP2)
      CALL ALLOCATE(TMP3)
      CALL ALLOCATE(TMP4)

      TMP1%E = 0.D0
      
      TMP3 = A
      CALL MULXMDIVXP(TMP3,TMP3,.TRUE.)
      DO MM = 1,NTCHOP
        NN=NRCHOPS(MM)
        TMP3%E(:NN,MM,:NXCHOPDIM) = TMP3%E(:NN,MM,:NXCHOPDIM)*IU*M(MM)
      ENDDO
      DO MM = 1,NTCHOP
        NN=NRCHOPS(MM)
        DO KK = 1,NXCHOPDIM
          TMP3%E(:NN,MM,KK) = -TMP3%E(:NN,MM,KK)*(AK(MM,KK)**2.)
        ENDDO
      ENDDO
      TMP3%E = -2.*TMP3%E
      TMP1%E = TMP1%E + TMP3%E
      CALL TOFP(TMP1)

      TMP2%E = 0.D0

      TMP4 = ROP
      TMP2 = TMP4
      CALL TOFP(TMP2)

      TMP1%E = TMP1%E * TMP2%E

      CALL HORFFT(TMP1,-1)
      CALL VERFFT(TMP1,-1)

      PSICURLMOM = PSICURLMOM + TMP1%E(:NR,MIND,AKIND)

      CALL DEALLOCATE(TMP1)
      CALL DEALLOCATE(TMP2)
      CALL DEALLOCATE(TMP3)
      CALL DEALLOCATE(TMP4)

      ! 11>--------------
      CALL ALLOCATE(TMP1)
      CALL ALLOCATE(TMP2)
      CALL ALLOCATE(TMP3)
      CALL ALLOCATE(TMP4)

      TMP1%E = 0.D0
      
      TMP3 = A
      CALL DELSQH(TMP3,TMP3)
      CALL MULXM(TMP3,TMP3)
      CALL MULXM(TMP3,TMP3)
      DO MM = 1,NTCHOP
        NN=NRCHOPS(MM)
        DO KK = 1,NXCHOPDIM
          TMP3%E(:NN,MM,KK) = TMP3%E(:NN,MM,KK)*IU*AK(MM,KK)
        ENDDO
      ENDDO
      TMP3%E = -2.*TMP3%E
      
      TMP1%E = TMP1%E + TMP3%E
      CALL TOFP(TMP1)

      TMP2%E = 0.D0

      TMP4 = OZ
      TMP2 = TMP4
      CALL TOFP(TMP2)

      TMP1%E = TMP1%E * TMP2%E

      CALL HORFFT(TMP1,-1)
      CALL VERFFT(TMP1,-1)

      PSICURLMOM = PSICURLMOM + TMP1%E(:NR,MIND,AKIND)

      CALL DEALLOCATE(TMP1)
      CALL DEALLOCATE(TMP2)
      CALL DEALLOCATE(TMP3)
      CALL DEALLOCATE(TMP4)

      ! 12>--------------
      CALL ALLOCATE(TMP1)
      CALL ALLOCATE(TMP2)
      CALL ALLOCATE(TMP3)
      CALL ALLOCATE(TMP4)

      TMP1%E = 0.D0
      
      TMP3 = A
      TMP3%E = -TMP3%E
      TMP1%E = TMP1%E + TMP3%E

      TMP3 = A
      CALL XXDX(TMP3,TMP3)
      TMP3%E = 2.*TMP3%E
      TMP1%E = TMP1%E + TMP3%E

      CALL XXDX(TMP1,TMP1)
      CALL MULXMDIVXP(TMP1,TMP1,.TRUE.)
      DO MM = 1,NTCHOP
        NN=NRCHOPS(MM)
        DO KK = 1,NXCHOPDIM
          TMP1%E(:NN,MM,KK) = TMP1%E(:NN,MM,KK)*IU*AK(MM,KK)
        ENDDO
      ENDDO
      CALL TOFP(TMP1)

      TMP2%E = 0.D0

      TMP4 = RUP
      TMP4%E = -TMP4%E
      TMP2%E = TMP2%E + TMP4%E

      TMP4 = RUP
      CALL XXDX(TMP4,TMP4)
      TMP2%E = TMP2%E + TMP4%E

      CALL MULXMDIVXP(TMP2,TMP2,.TRUE.)
      CALL TOFP(TMP2)

      TMP1%E = TMP1%E * TMP2%E

      CALL HORFFT(TMP1,-1)
      CALL VERFFT(TMP1,-1)

      PSICURLMOM = PSICURLMOM + TMP1%E(:NR,MIND,AKIND)

