      FUNCTION PSIMOM(A,ROR,ROP,OZ,RUR,RUP,UZ,MIND,AKIND)
!=======================================================================
      IMPLICIT NONE
      TYPE(SCALAR):: A,ROR,ROP,OZ,RUR,RUP,UZ
      INTEGER:: MIND,AKIND
      COMPLEX(P8), DIMENSION(NR):: PSIMOM

      TYPE(SCALAR):: TMP1,TMP2
      INTEGER:: NN,MM,KK

      PSIMOM = CMPLX(0.D0,0.D0)
      ! 1>---------------
      CALL ALLOCATE(TMP1)
      CALL ALLOCATE(TMP2)

      TMP1 = A

      CALL DELSQH(TMP1,TMP1)
      CALL MULXM(TMP1,TMP1)
      CALL MULXM(TMP1,TMP1)
      CALL MULXMDIVXP(TMP1,TMP1,.TRUE.)
      DO MM = 1,NTCHOP
        NN=NRCHOPS(MM)
        TMP1%E(:NN,MM,:NXCHOPDIM) = TMP1%E(:NN,MM,:NXCHOPDIM)*IU*M(MM)
      ENDDO
      CALL TOFP(TMP1)

      TMP2 = RUP
      CALL TOFP(TMP2)

      TMP1%E = TMP1%E * TMP2%E

      CALL HORFFT(TMP1,-1)
      CALL VERFFT(TMP1,-1)

      PSIMOM = PSIMOM + TMP1%E(:NR,MIND,AKIND)

      CALL DEALLOCATE(TMP1)
      CALL DEALLOCATE(TMP2)

      ! 2>---------------
      CALL ALLOCATE(TMP1)
      CALL ALLOCATE(TMP2)

      TMP1 = A

      CALL DELSQH(TMP1,TMP1)
      CALL MULXM(TMP1,TMP1)
      CALL MULXM(TMP1,TMP1)
      DO MM = 1,NTCHOP
        NN=NRCHOPS(MM)
        DO KK = 1,NXCHOPDIM
          TMP1%E(:NN,MM,KK) = TMP1%E(:NN,MM,KK)*IU*AK(MM,KK)
        ENDDO
      ENDDO
      CALL TOFP(TMP1)

      TMP2 = UZ
      CALL TOFP(TMP2)

      TMP1%E = TMP1%E * TMP2%E

      CALL HORFFT(TMP1,-1)
      CALL VERFFT(TMP1,-1)

      PSIMOM = PSIMOM + TMP1%E(:NR,MIND,AKIND)

      CALL DEALLOCATE(TMP1)
      CALL DEALLOCATE(TMP2)

      ! 3>---------------
      CALL ALLOCATE(TMP1)
      CALL ALLOCATE(TMP2)

      TMP1 = A

      CALL XXDX(TMP1,TMP1)
      CALL MULXMDIVXP(TMP1,TMP1,.TRUE.)
      DO MM = 1,NTCHOP
        NN=NRCHOPS(MM)
        DO KK = 1,NXCHOPDIM
          TMP1%E(:NN,MM,KK) = TMP1%E(:NN,MM,KK)*IU*AK(MM,KK)
        ENDDO
      ENDDO
      CALL TOFP(TMP1)

      TMP2 = UZ
      CALL XXDX(TMP2,TMP2)
      CALL TOFP(TMP2)

      TMP1%E = TMP1%E * TMP2%E

      CALL HORFFT(TMP1,-1)
      CALL VERFFT(TMP1,-1)

      PSIMOM = PSIMOM + TMP1%E(:NR,MIND,AKIND)

      CALL DEALLOCATE(TMP1)
      CALL DEALLOCATE(TMP2)

      ! 4>---------------
      CALL ALLOCATE(TMP1)
      CALL ALLOCATE(TMP2)

      TMP1 = A

      CALL MULXMDIVXP(TMP1,TMP1,.TRUE.)
      DO MM = 1,NTCHOP
        NN=NRCHOPS(MM)
        TMP1%E(:NN,MM,:NXCHOPDIM) = TMP1%E(:NN,MM,:NXCHOPDIM)*IU*M(MM)
      ENDDO
      CALL TOFP(TMP1)

      TMP2 = OZ
      CALL XXDX(TMP2,TMP2)
      CALL TOFP(TMP2)

      TMP1%E = TMP1%E * TMP2%E

      CALL HORFFT(TMP1,-1)
      CALL VERFFT(TMP1,-1)

      PSIMOM = PSIMOM + TMP1%E(:NR,MIND,AKIND)

      CALL DEALLOCATE(TMP1)
      CALL DEALLOCATE(TMP2)

      RETURN
      END FUNCTION PSIMOM
