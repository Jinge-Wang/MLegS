      CALL DEALLOCATE(TMP2)
      CALL DEALLOCATE(TMP3)
      CALL DEALLOCATE(TMP4)

      ! 14>--------------
      CALL ALLOCATE(TMP1)
      CALL ALLOCATE(TMP2)
      CALL ALLOCATE(TMP3)
      CALL ALLOCATE(TMP4)

      TMP1%E = 0.D0
      
      TMP3 = A
